lines=text.split('\n')
com=None
out=[]
for l in lines:
    s=l.strip()
    m=re.match(r'IF SELECTCOM == (\d+)',s)
    if m: com=int(m.group(1))
    mr=re.match(r'IF SELECTCOM >= (\d+)',s)
    if mr: com=int(mr.group(1))  # 280 / 410
    if com in D and re.search(r'PRINTFORM[WL]?\s+「」',l):
        nxt=next(iters[com])
        l=re.sub(r'(PRINTFORM[WL]?\s+「)」', lambda mm:mm.group(1)+nxt+'」', l, count=1)
    out.append(l)
for k,v in iters.items():
    rest=list(v)
    assert not rest, f'COM{k} 未使用 {len(rest)}'
