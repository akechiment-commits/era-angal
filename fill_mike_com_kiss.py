# 指定アンカーから次の「IF SELECTCOM」または「@」または「;===」大区切りまでを1ブロックとし、
# その中の空「」を順に置換する
def fill_block(text, anchor, lines):
    m = re.search(anchor, text)
    if not m:
        raise SystemExit(f'アンカー未検出: {anchor}')
    start = m.start()
    # 次境界を探す
    rest = text[m.end():]
    ends = []
    for pat in [r'\n\s*IF SELECTCOM', r'\n@', r'\n;={10,}']:
        mm = re.search(pat, rest)
        if mm:
            ends.append(mm.start())
    end_off = min(ends) if ends else len(rest)
    seg_start = start
    seg_end = m.end() + end_off
    seg = text[seg_start:seg_end]
    n_empty = seg.count('「」')
    if n_empty != len(lines):
        raise SystemExit(f'{anchor}: 空{n_empty} != セリフ{len(lines)}')
    idx = [0]
    def repl(mo):
        s = lines[idx[0]]; idx[0]+=1
        return '「'+s+'」'
    seg2 = re.sub('「」', repl, seg)
    return text[:seg_start] + seg2 + text[seg_end:]

