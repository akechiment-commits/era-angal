# cp932 事前チェック（1文字でも不可なら全体を中止）
for i, s in enumerate(L):
    try:
        s.encode('cp932')
    except UnicodeEncodeError as e:
        raise SystemExit(f'cp932不可 #{i+1}: {e} -> {s}')

with open(PATH, 'rb') as f:
    content = f.read().decode('cp932')

# 空スロット（PRINTFORML/PRINTFORMW + 「」）をファイル順に置換
pat = re.compile(r'(PRINTFORM[LW]+ +)「」')
matches = list(pat.finditer(content))
print('空スロット数:', len(matches), '／ 用意した本数:', len(L))
assert len(matches) == len(L), 'スロット数と本数が不一致'

# 末尾から置換してオフセットを保つ
out = content
for m, text in zip(reversed(matches), reversed(L)):
    rep = m.group(1) + '「' + text + '」'
    out = out[:m.start()] + rep + out[m.end():]

# 検算：残り空スロット0／CRLF維持
assert '「」' not in re.sub(r'.', lambda x: x.group(), out) or pat.search(out) is None, '空スロット残存'
assert pat.search(out) is None, '空スロット残存'

data = out.encode('cp932')
# CRLF 維持確認
if b'\r\n' not in data:
    raise SystemExit('CRLFが失われている')

with open(PATH, 'wb') as f:
    f.write(data)

print('書き込み完了。残り空スロット:', len(pat.findall(out)))
