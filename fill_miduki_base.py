# 波ダッシュ正規化（U+301C -> U+FF5E）と半角チルダ検査
norm = []
for s in S:
    s = s.replace('〜', '～')
    if '~' in s:
        sys.exit('半角~混入: ' + s)
    norm.append(s)
S = norm

print('用意した枠数:', len(S))

raw = open(PATH, 'rb').read().decode('cp932')
empties = raw.count('「」')
print('ファイル内の空き「」数:', empties)
assert empties == len(S), f'枠数不一致 file={empties} script={len(S)}'

# 文書順に先頭から順次置換
out = raw
for s in S:
    out = out.replace('「」', '「' + s + '」', 1)

assert out.count('「」') == 0, '空き残存'

# cp932エンコード確認 + CRLF
out = out.replace('\r\n', '\n').replace('\n', '\r\n')
data = out.encode('cp932')
open(PATH, 'wb').write(data)
print('書き込み完了:', len(data), 'bytes')
