with open(PATH,'rb') as f: text=f.read().decode('shift_jis')
lines=text.split('\r\n')
def fill(lo,hi,arr):
    c=0
    for i,l in enumerate(lines):
        if lo<=i+1<=hi and re.search(r'PRINTFORM[LW]\s*「」',l):
            lines[i]=l.replace('「」','「'+arr[c]+'」',1); c+=1
    return c
