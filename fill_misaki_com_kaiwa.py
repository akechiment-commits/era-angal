def fill_one(content, com, texts):
    lines=content.split('\r\n')
    sel=[i for i,l in enumerate(lines) if re.search(r'IF SELECTCOM\s*==\s*\d+',l)]
    for k,i in enumerate(sel):
        if int(re.search(r'==\s*(\d+)',lines[i]).group(1))==com:
            end=sel[k+1] if k+1<len(sel) else len(lines)
            idx=[j for j in range(i,end) if '「」' in lines[j]]
            assert len(idx)==len(texts), f"{len(idx)}!={len(texts)}"
            it=iter(texts)
            for j in idx: lines[j]=lines[j].replace('「」','「'+next(it)+'」',1)
            return '\r\n'.join(lines)
    raise SystemExit('COM未検出')

for s in texts:
    if '~' in s: raise SystemExit(f'半角~: {s}')
    s.encode('cp932')

c=open(PATH,'rb').read().decode('cp932')
b=c.count('「」')
c=fill_one(c,301,texts)
data=c.encode('cp932')
