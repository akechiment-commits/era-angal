norm=[]
for s in S:
    s=s.replace('〜','～')
    if '~' in s: sys.exit('半角~混入: '+s)
    norm.append(s)
S=norm
print('用意した枠数:', len(S))

raw=open(PATH,'rb').read().decode('cp932')
# COM340直前までを対象領域に
mark=re.search(r'\n[^\n]*SELECTCOM\s*==\s*340\b', raw)
cut=mark.start()
head, tail = raw[:cut], raw[cut:]
print('対象領域の空き「」:', head.count('「」'))
assert head.count('「」')==len(S), '枠数不一致'

for s in S:
    head=head.replace('「」','「'+s+'」',1)
assert head.count('「」')==0
out=head+tail
out=out.replace('\r\n','\n').replace('\n','\r\n')
data=out.encode('cp932')
open(PATH,'wb').write(data)
print('書き込み完了:', len(data), 'bytes / 残り全体空き:', out.count('「」'))
