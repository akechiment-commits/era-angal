def fill_block(text, anchor, lines):
    m = re.search(anchor, text)
    if not m: raise SystemExit(f'アンカー未検出: {anchor}')
    start=m.start(); rest=text[m.end():]
    ends=[]
    for pat in [r'\n\s*IF SELECTCOM', r'\n@', r'\n;={10,}']:
        mm=re.search(pat, rest)
        if mm: ends.append(mm.start())
    end_off=min(ends) if ends else len(rest)
    seg_start=start; seg_end=m.end()+end_off
    seg=text[seg_start:seg_end]; n=seg.count('「」')
    if n!=len(lines): raise SystemExit(f'{anchor}: 空{n} != {len(lines)}')
    idx=[0]
    def repl(mo):
        s=lines[idx[0]]; idx[0]+=1; return '「'+s+'」'
    return text[:seg_start]+re.sub('「」',repl,seg)+text[seg_end:]

