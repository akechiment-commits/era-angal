def main() -> None:
    changed = 0
    for filename, replacements in REPAIRS.items():
        path = ROOT / "ERB/CHAR" / filename
        raw = path.read_bytes()
        text = raw.decode("cp932")
        updated = text
        pending = 0
        for index, (old, new) in enumerate(replacements):
            old_count = updated.count(old)
            if old_count == 1:
                updated = updated.replace(old, new)
                pending += 1
            elif old_count == 0 and any(candidate in updated for _, candidate in replacements[index:]):
                continue
            else:
                raise ValueError(f"{filename}: 対象行の出現数が不正です: {old_count} / {old}")
        if pending == 0:
            print(f"{filename}: 修正済み、無変更")
            continue
        backup = BACKUP_DIR / filename
        if not backup.exists():
            backup.parent.mkdir(parents=True, exist_ok=True)
            backup.write_bytes(raw)
        path.write_bytes(updated.encode("cp932"))
        changed += pending
        print(f"{filename}: {pending}行を視点修正")
    print(f"COM131/132視点修正: {changed}行")


if __name__ == "__main__":
    main()
