def replace_prints(lines: list[str], command_id: int, values: list[str], start: int, end: int) -> None:
    header = f"IF SELECTCOM == {command_id}"
    begin = next(i for i in range(start, end) if lines[i] == header)
    block_end = next(
        (i for i in range(begin + 1, end) if lines[i].startswith("IF SELECTCOM == ")),
        end,
    )
    prints = [i for i in range(begin, block_end) if lines[i].strip().startswith("PRINTFORMW")]
    if len(prints) != 6:
        raise RuntimeError(f"COM{command_id} expected 6 PRINTFORMW lines, got {len(prints)}")
    for index, line_index in enumerate(prints):
        indent = lines[line_index][: len(lines[line_index]) - len(lines[line_index].lstrip())]
        lines[line_index] = indent + "PRINTFORMW " + values[index]


def main() -> None:
    text = TARGET.read_bytes().decode("cp932").replace("\r\n", "\n").replace("\r", "\n")
    lines = text.split("\n")
    start = next(i for i, line in enumerate(lines) if line == START_MARKER)
    end = next(i for i, line in enumerate(lines) if line == END_MARKER)
    for command_id, values in NEW_LINES.items():
        replace_prints(lines, command_id, values, start, end)
    text = "\n".join(lines)
    for before, after in REMAINDERS:
        text = text.replace(before, after)
    TARGET.write_bytes(text.replace("\n", "\r\n").encode("cp932"))
    print("CHAR31 new10 and remaining strict-tone lines softened")


if __name__ == "__main__":
    main()
