def apply_rand3_block(text: str, command: int, branch_pairs: list[tuple[str, str]]) -> tuple[str, bool]:
    start, end = command_span(text, command)
    block = text[start:end]
    if "RAND:3" in block:
        return text, False
    lines = block.rstrip("\n").split("\n")
    indices = print_indices(lines)
    if len(indices) != len(branch_pairs):
        raise RuntimeError(f"COM{command}: PRINTFORM数 {len(indices)} != 枝数 {len(branch_pairs)}")
    for index, branch_pair in reversed(list(zip(indices, branch_pairs))):
        lines[index : index + 1] = wrap_print_line(lines[index], branch_pair)
    selector = next(i for i, line in enumerate(lines) if line.strip() == f"IF SELECTCOM == {command}")
    lines.insert(selector + 1, "\tA = RAND:3")
    new_block = "\n".join(lines) + "\n"
    return text[:start] + new_block + text[end:], True


