def command_span(text: str, command: int) -> tuple[int, int]:
    match = re.search(rf"(?m)^IF SELECTCOM == {command}\n", text)
    if match is None:
        raise RuntimeError(f"COM{command} の開始行がありません")
    next_match = re.search(r"(?m)^IF SELECTCOM == \d+\n", text[match.end() :])
    end = match.end() + next_match.start() if next_match else len(text)
    return match.start(), end


def print_indices(lines: list[str]) -> list[int]:
    return [
        i
        for i, line in enumerate(lines)
        if re.match(r"^\s*PRINTFORM(?:L|W)?\b", line, re.I)
        and not line.lstrip().startswith(";")
    ]


