def indented(lines: list[str], extra: str = "\t") -> list[str]:
    return [extra + line if line else line for line in lines]


def relation_expanded(body: list[str], variants: tuple[list[str], list[str]]) -> list[str]:
    rel = next(i for i, line in enumerate(body) if re.fullmatch(r"\t*IF TALENT:TARGET:153", line))
    rel_indent = re.match(r"\t*", body[rel]).group(0)
    else_i = next(i for i in range(rel + 1, len(body)) if body[i] == rel_indent + "ELSE")
    end_i = next(i for i in range(else_i + 1, len(body)) if body[i] == rel_indent + "ENDIF")
    romantic = body[rel + 1 : else_i]
    normal = body[else_i + 1 : end_i]
    out = body[:rel]
    out += [body[rel], rel_indent + "\tIF A == 0"]
    out += indented(romantic)
    out += [rel_indent + "\tELSEIF A == 1", rel_indent + "\t\tPRINTFORMW " + variants[0][0]]
    out += [rel_indent + "\tELSE", rel_indent + "\t\tPRINTFORMW " + variants[0][1], rel_indent + "\tENDIF"]
    out += [rel_indent + "ELSE", rel_indent + "\tIF A == 0"]
    out += indented(normal)
    out += [rel_indent + "\tELSEIF A == 1", rel_indent + "\t\tPRINTFORMW " + variants[1][0]]
    out += [rel_indent + "\tELSE", rel_indent + "\t\tPRINTFORMW " + variants[1][1], rel_indent + "\tENDIF", rel_indent + "ENDIF"]
    return out


def find_top_end(lines: list[str], start: int) -> int:
    for i in range(start + 1, len(lines)):
        if lines[i] == "ENDIF":
            return i
    raise ValueError(f"top-level ENDIF not found at {start + 1}")


def expand_simple(lines: list[str], command: int) -> list[str]:
    start = next(i for i, line in enumerate(lines) if line == f"IF SELECTCOM == {command}")
    end = find_top_end(lines, start)
    body = lines[start + 1 : end]
    out = [f"IF SELECTCOM == {command}", "\tA = RAND:3"]
    out += relation_expanded(body, (R[command], N[command]))
    return lines[:start] + out + lines[end:]


def expand_item(lines: list[str], command: int) -> list[str]:
    start = next(i for i, line in enumerate(lines) if line == f"IF SELECTCOM == {command}")
    end = find_top_end(lines, start)
    body = lines[start + 1 : end]
    tequip = next(i for i, line in enumerate(body) if line == f"\tIF TEQUIP:{command}")
    tequip_else = next(i for i in range(tequip + 1, len(body)) if body[i] == "\tELSE")
    tequip_end = next(i for i in range(tequip_else + 1, len(body)) if body[i] == "\tENDIF")
    on_body = body[tequip + 1 : tequip_else]
    off_body = body[tequip_else + 1 : tequip_end]
    vals = ITEM[command]
    out = [f"IF SELECTCOM == {command}", "\tA = RAND:3", f"\tIF TEQUIP:{command}"]
    out += relation_expanded(on_body, (vals[0], vals[1]))
    out += ["\tELSE"]
    out += relation_expanded(off_body, (vals[2], vals[3]))
    out += ["\tENDIF"]
    return lines[:start] + out + lines[end:]


def expand_chain(lines: list[str], commands: list[int]) -> list[str]:
    start = next(i for i, line in enumerate(lines) if line == f"IF SELECTCOM == {commands[0]}")
    end = find_top_end(lines, start)
    block = lines[start:end]
    branch_starts = [i for i, line in enumerate(block) if re.fullmatch(r"(?:IF|ELSEIF) SELECTCOM == \d+", line)]
    branch_starts.append(len(block))
    out: list[str] = []
    for a, b in zip(branch_starts, branch_starts[1:]):
        header = block[a]
        body = block[a + 1 : b]
        command = int(re.search(r"(\d+)$", header).group(1))
        out += [header, "\tA = RAND:3"]
        out += relation_expanded(body, (R[command], N[command]))
    out += ["ENDIF"]
    return lines[:start] + out + lines[end + 1 :]


def main() -> None:
    text = TARGET.read_bytes().decode("cp932")
    if MARKER in text:
        raise SystemExit("quality RAND3 expansion already present; refusing to duplicate it")
    lines = text.splitlines()
    lines = expand_chain(lines, sorted(CHAIN_1))
    lines = expand_chain(lines, sorted(CHAIN_2))
    for command in sorted(SIMPLE_IDS):
        lines = expand_simple(lines, command)
    for command in sorted(ITEM_IDS):
        lines = expand_item(lines, command)
    marker_i = next(i for i, line in enumerate(lines) if line == ";--- COM3 自慰 ---")
    lines.insert(marker_i, MARKER)
    lines.insert(marker_i + 1, "; ななの既存80コマンド：元口上をA=0に残し、意味の異なるA=1/A=2を追加")
    # %LOCALS% is already the complete character-specific address.
    output = ("\r\n".join(lines) + "\r\n").replace("%LOCALS%さん", "%LOCALS%")
    TARGET.write_bytes(output.encode("cp932"))
    print(f"rewrote {len(SIMPLE_IDS) + len(ITEM_IDS) + len(CHAIN_1) + len(CHAIN_2)} commands")


if __name__ == "__main__":
    main()
