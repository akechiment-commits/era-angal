def find_end(lines: list[str], start: int) -> int:
    depth = 0
    for i in range(start, len(lines)):
        stripped = lines[i].strip()
        if stripped.startswith("IF "):
            depth += 1
        elif stripped == "ENDIF":
            depth -= 1
            if depth == 0:
                return i + 1
    raise RuntimeError(f"ENDIF not found: {start}")


def print_variants(block: list[str], talent_idx: int) -> tuple[int, list[str], list[str]]:
    talent_end = find_end(block, talent_idx)
    else_idx = next(i for i in range(talent_idx + 1, talent_end) if block[i].strip() == "ELSE")
    love = [x.strip() for x in block[talent_idx + 1:else_idx] if x.strip().startswith("PRINTFORM")]
    normal = [x.strip() for x in block[else_idx + 1:talent_end - 1] if x.strip().startswith("PRINTFORM")]
    if not love or not normal:
        raise RuntimeError("talent branch has no speech")
    return talent_end, love, normal


def render_variant(variant: list[str] | str, indent: str) -> list[str]:
    if isinstance(variant, str):
        variant = [variant]
    out = []
    for line in variant:
        clean = line.strip()
        if clean.startswith("PRINTFORM"):
            prefix, separator, body = clean.partition(" ")
            if body.startswith("……"):
                clean = prefix + separator + "「" + body
        elif clean.startswith("……"):
            clean = "「" + clean
        out.append(indent + (clean if clean.startswith("PRINTFORM") else "PRINTFORMW " + clean))
    return out


def render_talent(base: str, love0: list[str], normal0: list[str], extra: tuple[list[str], list[str]]) -> list[str]:
    love_extra, normal_extra = extra
    love = [love0, [love_extra[0]], [love_extra[1]]]
    normal = [normal0, [normal_extra[0]], [normal_extra[1]]]
    out = [base + "A = RAND:3", base + "IF TALENT:TARGET:153"]
    out += [base + "\tIF A == 0"] + render_variant(love[0], base + "\t\t")
    out += [base + "\tELSEIF A == 1"] + render_variant(love[1], base + "\t\t")
    out += [base + "\tELSE"] + render_variant(love[2], base + "\t\t")
    out += [base + "\tENDIF", base + "ELSE"]
    out += [base + "\tIF A == 0"] + render_variant(normal[0], base + "\t\t")
    out += [base + "\tELSEIF A == 1"] + render_variant(normal[1], base + "\t\t")
    out += [base + "\tELSE"] + render_variant(normal[2], base + "\t\t")
    out += [base + "\tENDIF", base + "ENDIF"]
    return out


def command_starts(lines: list[str]) -> list[tuple[int, int]]:
    return [(i, int(m.group(1))) for i, line in enumerate(lines) if (m := re.match(r"^(?:IF|ELSEIF) SELECTCOM == ([0-9]+)", line))]


def build_simple_mod(lines: list[str], start: int, end: int, command_id: int) -> list[str]:
    block = lines[start:end]
    talent_idx = next(i for i, line in enumerate(block) if line.strip() == "IF TALENT:TARGET:153")
    _, love0, normal0 = print_variants(block, talent_idx)
    base = block[talent_idx][:len(block[talent_idx]) - len(block[talent_idx].lstrip())]
    return block[:talent_idx] + render_talent(base, love0, normal0, EXTRA[command_id]) + ["ENDIF"]


def build_state_mod(lines: list[str], start: int, end: int, command_id: int) -> list[str]:
    block = lines[start:end]
    talent_indices = [i for i, line in enumerate(block) if line.strip() == "IF TALENT:TARGET:153"]
    if len(talent_indices) != 2:
        raise RuntimeError(f"state command {command_id} expected 2 talent branches, got {len(talent_indices)}")
    for talent_idx in reversed(talent_indices):
        talent_end, love0, normal0 = print_variants(block, talent_idx)
        base = block[talent_idx][:len(block[talent_idx]) - len(block[talent_idx].lstrip())]
        state = "on" if talent_idx == talent_indices[0] else "off"
        block[talent_idx:talent_end] = render_talent(base, love0, normal0, STATE_EXTRA[command_id][state])
    return block


def build_chain_mod(lines: list[str], start: int, end: int, ids: list[int]) -> list[str]:
    chain = lines[start:end]
    branch_starts = [i for i, line in enumerate(chain) if re.match(r"^(?:IF|ELSEIF) SELECTCOM == [0-9]+", line)]
    out: list[str] = []
    for pos, branch_start in enumerate(branch_starts):
        branch_end = branch_starts[pos + 1] if pos + 1 < len(branch_starts) else len(chain) - 1
        branch = chain[branch_start:branch_end]
        command_id = int(re.match(r"^(?:IF|ELSEIF) SELECTCOM == ([0-9]+)", branch[0]).group(1))
        if command_id not in ids:
            raise RuntimeError(f"unexpected command in chain: {command_id}")
        talent_idx = next(i for i, line in enumerate(branch) if line.strip() == "IF TALENT:TARGET:153")
        _, love0, normal0 = print_variants(branch, talent_idx)
        base = branch[talent_idx][:len(branch[talent_idx]) - len(branch[talent_idx].lstrip())]
        out += branch[:talent_idx] + render_talent(base, love0, normal0, CUSTOM_EXTRA[command_id])
    out.append("ENDIF")
    return out


def build_mods(lines: list[str]) -> list[tuple[int, int, list[str]]]:
    starts = command_starts(lines)
    start_by_id = {command_id: index for index, command_id in starts if lines[index].startswith("IF SELECTCOM")}
    required = SIMPLE_IDS | set(STATE_IDS) | {first_id for first_id, _ in CUSTOM_GROUPS}
    missing = sorted(required - set(start_by_id))
    if missing:
        raise RuntimeError(f"missing existing command blocks: {missing}")
    mods = []
    for command_id in sorted(SIMPLE_IDS):
        start = start_by_id[command_id]
        end = find_end(lines, start)
        mods.append((start, end, build_simple_mod(lines, start, end, command_id)))
    for command_id in STATE_IDS:
        start = start_by_id[command_id]
        end = find_end(lines, start)
        mods.append((start, end, build_state_mod(lines, start, end, command_id)))
    for first_id, ids in CUSTOM_GROUPS:
        start = start_by_id[first_id]
        end = find_end(lines, start)
        mods.append((start, end, build_chain_mod(lines, start, end, ids)))
    return mods


def render_new_command(command_id: int, label: str, love: list[str], normal: list[str]) -> list[str]:
    out = [f";--- COM{command_id} {label} ---", f"IF SELECTCOM == {command_id}"]
    if command_id in {62, 76, 202, 258}:
        out += ["\tCALL AITE_YOBI, 27, ASSI", '\tLOCALS \'= @"%RESULTS%"']
    out += ["\tA = RAND:3", "\tIF TALENT:TARGET:85"]
    for index, line in enumerate(love):
        out.append("\t\tIF A == 0" if index == 0 else "\t\tELSEIF A == 1" if index == 1 else "\t\tELSE")
        out.append("\t\t\tPRINTFORMW " + line)
    out += ["\t\tENDIF", "\tELSE"]
    for index, line in enumerate(normal):
        out.append("\t\tIF A == 0" if index == 0 else "\t\tELSEIF A == 1" if index == 1 else "\t\tELSE")
        out.append("\t\t\tPRINTFORMW " + line)
    out += ["\t\tENDIF", "\tENDIF", "ENDIF", ""]
    return out


def add_new_commands(lines: list[str]) -> None:
    existing = {int(m.group(1)) for _, line in enumerate(lines) if (m := re.match(r"^(?:IF|ELSEIF) SELECTCOM == ([0-9]+)", line))}
    overlap = sorted(existing & set(NEW_COMMANDS))
    if overlap:
        raise RuntimeError(f"new command ids already exist: {overlap}")
    marker = next(i for i, line in enumerate(lines) if line.startswith("@CHAR_VIRGIN_27"))
    return_idx = next(i for i in range(marker - 1, -1, -1) if lines[i].strip() == "RETURN 0")
    block = [";=== NATSUNO YURI MISSING COMMAND TRIAL START ===", "; 追加10コマンド（恋慕TALENT:85／非恋慕を各3種）", ""]
    for command_id, (label, love, normal) in NEW_COMMANDS.items():
        block.extend(render_new_command(command_id, label, love, normal))
    block.extend([";=== NATSUNO YURI MISSING COMMAND TRIAL END ===", ""])
    lines[return_idx:return_idx] = block


def main() -> None:
    if set(EXTRA) != SIMPLE_IDS:
        raise RuntimeError(f"EXTRA/SIMPLE_IDS mismatch: {sorted(SIMPLE_IDS - set(EXTRA))} / {sorted(set(EXTRA) - SIMPLE_IDS)}")
    if set(STATE_EXTRA) != set(STATE_IDS):
        raise RuntimeError("STATE_EXTRA/STATE_IDS mismatch")
    if set(CUSTOM_EXTRA) != {command_id for _, ids in CUSTOM_GROUPS for command_id in ids}:
        raise RuntimeError("CUSTOM_EXTRA/CUSTOM_GROUPS mismatch")
    if set(NEW_COMMANDS) != {60, 62, 76, 78, 79, 84, 86, 202, 258, 318}:
        raise RuntimeError("NEW_COMMANDS id mismatch")

    text = COM_PATH.read_bytes().decode("cp932").replace("\r\n", "\n").replace("\r", "\n")
    lines = text.split("\n")
    mods = build_mods(lines)
    used = set()
    for start, end, _ in mods:
        if any(i in used for i in range(start, end)):
            raise RuntimeError("overlapping modifications")
        used.update(range(start, end))
    for start, end, replacement in sorted(mods, reverse=True):
        lines[start:end] = replacement
    add_new_commands(lines)
    result = "\n".join(lines)
    COM_PATH.write_bytes(result.replace("\n", "\r\n").encode("cp932"))
    print(f"randomized existing blocks: simple={len(SIMPLE_IDS)}, state={len(STATE_IDS)}, custom=10; added new commands={len(NEW_COMMANDS)}")


if __name__ == "__main__":
    main()
