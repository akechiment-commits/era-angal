def read_cp932(path: Path) -> str:
    data = path.read_bytes()
    return data.decode("cp932")


def write_cp932_crlf(path: Path, text: str) -> None:
    normalized = text.replace("\r\n", "\n").replace("\r", "\n")
    encoded = normalized.replace("\n", "\r\n").encode("cp932")
    path.write_bytes(encoded)


def rand_block(love, normal, indent="\t"):
    """恋慕3本・非恋慕3本のRAND:3ブロックを作る。"""
    out = [
        f"{indent}A = RAND:3",
        f"{indent}IF TALENT:TARGET:85",
        f"{indent}\tIF A == 0",
        f"{indent}\t\tPRINTFORMW {love[0]}",
        f"{indent}\tELSEIF A == 1",
        f"{indent}\t\tPRINTFORMW {love[1]}",
        f"{indent}\tELSE",
        f"{indent}\t\tPRINTFORMW {love[2]}",
        f"{indent}\tENDIF",
        f"{indent}ELSE",
        f"{indent}\tIF A == 0",
        f"{indent}\t\tPRINTFORMW {normal[0]}",
        f"{indent}\tELSEIF A == 1",
        f"{indent}\t\tPRINTFORMW {normal[1]}",
        f"{indent}\tELSE",
        f"{indent}\t\tPRINTFORMW {normal[2]}",
        f"{indent}\tENDIF",
        f"{indent}ENDIF",
    ]
    return "\n".join(out)


