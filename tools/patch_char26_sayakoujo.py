    lines = section.split("\n")
    starts = [
        i for i, line in enumerate(lines)
        if re.match(r"^IF SELECTCOM == \d+$", line.strip())
    ]
    if len(starts) != 10:
        raise RuntimeError("追加10コマンドのトップレベルIF数が10ではありません")
    marker_line = next(
        i for i, line in enumerate(lines) if line.strip() == add_end
    )
    ends = starts[1:] + [marker_line]
    for start, end in reversed(list(zip(starts, ends))):
        branch = lines[start:end]
        if_count = sum(
            1 for line in branch
            if not line.strip().startswith(";")
            and re.match(r"^IF(?:\s|$)", line.strip())
        )
        endif_count = sum(
            1 for line in branch
            if re.match(r"^ENDIF(?:\s|$)", line.strip())
        )
        missing = if_count - endif_count
        if missing < 0:
            raise RuntimeError(f"追加COMのENDIFが過剰です: {branch[0]}")
        if missing:
            lines[end:end] = ["ENDIF"] * missing
    repaired = "\n".join(lines)
    return text[:section_start] + repaired + text[marker_end:]


