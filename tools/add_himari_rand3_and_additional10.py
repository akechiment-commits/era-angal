RAND3_IDS = set(EXTRA)
ADDITIONAL_IDS = set(ADDITIONAL)


def find_matching_if(lines: list[str], start: int) -> int:
    depth = 0
    for index in range(start, len(lines)):
        stripped = lines[index].strip()
        if stripped.startswith("IF "):
            depth += 1
        elif stripped == "ENDIF":
            depth -= 1
            if depth == 0:
                return index + 1
    raise RuntimeError(f"ENDIF not found at line {start + 1}")


def top_level_else(lines: list[str], start: int, end: int) -> int:
    depth = 1
    for index in range(start + 1, end - 1):
        stripped = lines[index].strip()
        if stripped.startswith("IF "):
            depth += 1
        elif stripped == "ENDIF":
            depth -= 1
        elif stripped == "ELSE" and depth == 1:
            return index
    raise RuntimeError(f"ELSE not found at line {start + 1}")


def reindent_body(body: list[str], indent: str) -> list[str]:
    out: list[str] = []
    for line in body:
        if not line.strip():
            out.append("")
            continue
        out.append(indent + line.lstrip())
    return out


def render_speech(indent: str, speech: str) -> str:
    return f'{indent}PRINTFORMW 「{speech}」'


def wrap_talent(lines: list[str], talent_index: int, variants: tuple[str, ...]) -> list[str]:
    talent_end = find_matching_if(lines, talent_index)
    else_index = top_level_else(lines, talent_index, talent_end)
    talent_line = lines[talent_index]
    talent_indent = talent_line[: len(talent_line) - len(talent_line.lstrip())]
    inner_indent = talent_indent + "\t"
    love_body = lines[talent_index + 1 : else_index]
    normal_body = lines[else_index + 1 : talent_end - 1]
    love1, love2, normal1, normal2 = variants
    out: list[str] = [talent_indent + "A = RAND:3", talent_line]
    out.append(inner_indent + "IF A == 0")
    out.extend(reindent_body(love_body, inner_indent + "\t"))
    out.append(inner_indent + "ELSEIF A == 1")
    out.append(render_speech(inner_indent + "\t", love1))
    out.append(inner_indent + "ELSE")
    out.append(render_speech(inner_indent + "\t", love2))
    out.append(inner_indent + "ENDIF")
    out.append(lines[else_index])
    out.append(inner_indent + "IF A == 0")
    out.extend(reindent_body(normal_body, inner_indent + "\t"))
    out.append(inner_indent + "ELSEIF A == 1")
    out.append(render_speech(inner_indent + "\t", normal1))
    out.append(inner_indent + "ELSE")
    out.append(render_speech(inner_indent + "\t", normal2))
    out.append(inner_indent + "ENDIF")
    out.append(talent_indent + "ENDIF")
    return out


def command_ranges(lines: list[str]) -> list[tuple[int, int, int]]:
    starts = [(i, int(m.group(1))) for i, line in enumerate(lines) if (m := re.match(r"^(?:IF|ELSEIF) SELECTCOM == (\d+)", line))]
    ranges: list[tuple[int, int, int]] = []
    for index, (start, command_id) in enumerate(starts):
        end = starts[index + 1][0] if index + 1 < len(starts) else len(lines)
        ranges.append((command_id, start, end))
    return ranges


def transform_rand3(lines: list[str]) -> list[str]:
    ranges = command_ranges(lines)
    for command_id, start, end in sorted(ranges, key=lambda item: item[1], reverse=True):
        if command_id not in RAND3_IDS:
            continue
        # 同一COM内にTEQUIPオン/オフなど複数のTALENT分岐がある場合も、各分岐を独立に処理する。
        block = lines[start:end]
        talent_indices = [i for i, line in enumerate(block) if line.strip() == "IF TALENT:TARGET:153"]
        for talent_index in reversed(talent_indices):
            end_index = find_matching_if(block, talent_index)
            if "A = RAND:3" in "\n".join(block[talent_index:end_index]):
                continue
            block[talent_index:end_index] = wrap_talent(block, talent_index, EXTRA[command_id])
        lines[start:end] = block
    return lines


def render_additional(command_id: int, label: str, viewpoint: str, love: list[str], normal: list[str]) -> list[str]:
    out = [f";--- COM{command_id} {label}（追加10コマンド） ---", f";▼【視点】{viewpoint}", f"IF SELECTCOM == {command_id}"]
    if command_id in {60, 62, 76, 202, 258}:
        out.extend(["\tCALL AITE_YOBI, 61, ASSI", '\tLOCALS \'= @"%RESULTS%"'])
    out.extend(["\tA = RAND:3", "\tIF TALENT:TARGET:85"])
    for index, speech in enumerate(love):
        out.append("\t\tIF A == 0" if index == 0 else "\t\tELSEIF A == 1" if index == 1 else "\t\tELSE")
        out.append(render_speech("\t\t\t", speech))
    out.extend(["\t\tENDIF", "\tELSE"])
    for index, speech in enumerate(normal):
        out.append("\t\tIF A == 0" if index == 0 else "\t\tELSEIF A == 1" if index == 1 else "\t\tELSE")
        out.append(render_speech("\t\t\t", speech))
    out.extend(["\t\tENDIF", "\tENDIF", "ENDIF", ""])
    return out


def main() -> None:
    raw = COM_PATH.read_bytes().decode("cp932")
    if MARKER in raw:
        print("CHAR61のRAND3/追加10ブロックは適用済みです。")
        return
    missing_rand3 = RAND3_IDS - set(command_id for command_id, _, _ in command_ranges(raw.replace("\r\n", "\n").split("\n")))
    if missing_rand3:
        raise RuntimeError(f"existing RAND3 targets missing: {sorted(missing_rand3)}")
    missing_additional = ADDITIONAL_IDS & set(command_id for command_id, _, _ in command_ranges(raw.replace("\r\n", "\n").split("\n")))
    if missing_additional:
        raise RuntimeError(f"additional command IDs already exist: {sorted(missing_additional)}")
    lines = raw.replace("\r\n", "\n").replace("\r", "\n").split("\n")
    if lines and lines[-1] == "":
        lines.pop()
    transform_rand3(lines)
    return_index = next(i for i, line in enumerate(lines) if line.strip() == "RETURN 0")
    addition: list[str] = [MARKER, "; 既存A=0を保持し、A=1/A=2の反応差分と追加10コマンドを付与する。", ""]
    for command_id in (60, 62, 76, 78, 79, 84, 86, 202, 258, 318):
        label, viewpoint, love, normal = ADDITIONAL[command_id]
        addition.extend(render_additional(command_id, label, viewpoint, love, normal))
    lines[return_index:return_index] = addition
    output = "\r\n".join(lines) + "\r\n"
    COM_PATH.write_bytes(output.encode("cp932"))
    print(f"CHAR61: RAND3 {len(RAND3_IDS)}種、追加10コマンド10種を適用しました。")


if __name__ == "__main__":
    main()
