raw=open(PATH,'rb').read(); text=raw.decode('cp932')
lines=text.split('\r\n')
ptr=defaultdict(int); cur=None; stack=[]
def classify():
    c=' && '.join(stack)
    if re.search(r'CFLAG:TARGET:\d+ == 0',c): return 'first'
    if 'TFLAG:18 == -1' in c: return 'fail_k' if 'TALENT:TARGET:153' in c else 'fail'
    if 'TALENT:TARGET:153' in c: return 'koi'
    if 'ABL:TARGET:0 >= 6' in c: return 'sin'
    return 'tu'
out=[]
for ln in lines:
    s=ln.strip()
    m=re.match(r'IF\s+SELECTCOM\s*==\s*(\d+)',s)
    if s.startswith('@'): cur=None; stack=[]; out.append(ln); continue
    if m: cur=int(m.group(1)); stack=[]; out.append(ln); continue
    if cur in TARGETS:
        if re.match(r'IF\b',s) and 'SELECTCOM' not in s: stack.append(s[2:].strip())
        elif re.match(r'ELSEIF\b',s):
            if stack: stack[-1]=s[6:].strip()
        elif s=='ELSE':
            if stack: stack[-1]='ELSE'
        elif re.match(r'ENDIF',s):
            if stack: stack.pop()
    if re.search(r'PRINTFORM[LW]\s*「」',s) and cur in TARGETS:
        lab=classify(); pool=TXT[cur].get(lab)
        if pool is None: print('no pool',cur,lab); sys.exit(1)
        k=ptr[(cur,lab)]
        if k>=len(pool): print('exhausted',cur,lab); sys.exit(1)
        ptr[(cur,lab)]+=1
        out.append(ln.replace('「」','「'+pool[k]+'」')); continue
    out.append(ln)
err=False
for com,d in TXT.items():
    for lab,pool in d.items():
        if ptr[(com,lab)]!=len(pool): print('mismatch',com,lab,ptr[(com,lab)],len(pool)); err=True
if err: sys.exit(1)
nt='\r\n'.join(out)
if '~' in nt: print('ASCII ~'); sys.exit(1)
open(PATH,'wb').write(nt.encode('cp932'))
print('ステップ3 埋め込み完了:', sum(len(p) for d in TXT.values() for p in d.values()))
print('残り全空き「」:', nt.count('「」'))
