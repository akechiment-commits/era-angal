def branch(
    old_love: str,
    old_normal: str,
    additions: tuple[str, str, str, str],
    love_comment: str = "",
    normal_comment: str = "",
) -> str:
    love1, love2, normal1, normal2 = additions
    love_note = f"\t\t\t{love_comment.strip()}\n" if love_comment else ""
    normal_note = f"\t\t\t{normal_comment.strip()}\n" if normal_comment else ""
    return "\n".join(
        [
            "\tIF TALENT:TARGET:153",
            "\t\tIF A == 0",
            *(love_note.rstrip("\n").splitlines() if love_note else []),
            f"\t\t\tPRINTFORMW {old_love}",
            "\t\tELSEIF A == 1",
            f"\t\t\tPRINTFORMW {love1}",
            "\t\tELSE",
            f"\t\t\tPRINTFORMW {love2}",
            "\t\tENDIF",
            "\tELSE",
            "\t\tIF A == 0",
            *(normal_note.rstrip("\n").splitlines() if normal_note else []),
            f"\t\t\tPRINTFORMW {old_normal}",
            "\t\tELSEIF A == 1",
            f"\t\t\tPRINTFORMW {normal1}",
            "\t\tELSE",
            f"\t\t\tPRINTFORMW {normal2}",
            "\t\tENDIF",
            "\tENDIF",
        ]
    )


def main() -> None:
    text = PATH.read_bytes().decode("cp932").replace("\r\n", "\n")
    for number, additions in EXTRA.items():
        starts = [i for i, line in enumerate(text.splitlines()) if line == f"IF SELECTCOM == {number}"]
        if len(starts) != 1:
            raise RuntimeError(f"COM{number}: SELECTCOM blocks={len(starts)}")
        lines = text.splitlines()
        start = starts[0]
        end = next((i for i in range(start + 1, len(lines)) if lines[i].startswith("IF SELECTCOM == ") or lines[i] == "RETURN 0"), len(lines))
        block = "\n".join(lines[start:end])
        if "A = RAND:3" in block:
            continue
        relation = re.compile(
            r"\tIF TALENT:TARGET:153\n"
            r"(?P<love_comment>\t\t;[^\n]*\n)?"
            r"\t\tPRINTFORMW (?P<love>[^\n]*)\n"
            r"\tELSE\n"
            r"(?P<normal_comment>\t\t;[^\n]*\n)?"
            r"\t\tPRINTFORMW (?P<normal>[^\n]*)\n"
            r"\tENDIF"
        )
        match = relation.search(block)
        if not match:
            raise RuntimeError(f"COM{number}: simple relation not found")
        header = f"IF SELECTCOM == {number}\n"
        if not block.startswith(header):
            raise RuntimeError(f"COM{number}: unexpected header")
        replaced = (
            header
            + "\tA = RAND:3\n"
            + block[len(header) : match.start()]
            + branch(
                match.group("love"),
                match.group("normal"),
                additions,
                match.group("love_comment") or "",
                match.group("normal_comment") or "",
            )
            + block[match.end() :]
        )
        text = "\n".join(lines[:start] + replaced.splitlines() + lines[end:])

    PATH.write_bytes(text.replace("\n", "\r\n").encode("cp932"))
    print(f"CHAR06 standard RAND3 added: {len(EXTRA)} commands")


if __name__ == "__main__":
    main()
