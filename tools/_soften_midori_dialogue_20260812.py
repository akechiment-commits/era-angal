def soften(dialogue: str) -> str:
    for old, new in sorted(REPLACEMENTS, key=lambda item: len(item[0]), reverse=True):
        dialogue = dialogue.replace(old, new)
    # A few generated branches used an excited punctuation mark after a
    # request.  Keep Midori's fluster, but make the request sound less sharp.
    dialogue = dialogue.replace("よぉ！", "よぉ……")
    dialogue = dialogue.replace("ねっ……っ", "ね……っ")
    dialogue = dialogue.replace("くれる？ぇ", "くれる？")
    dialogue = dialogue.replace("？。", "。")
    dialogue = dialogue.replace("？……", "……")
    dialogue = dialogue.replace("？、", "、")
    dialogue = dialogue.replace("？！", "！")
    dialogue = dialogue.replace("ねね", "ね")
    dialogue = dialogue.replace("？よ", "よ")
    dialogue = dialogue.replace("お願いね！", "お願いね……")
    dialogue = dialogue.replace("ね……！", "ね……")
    dialogue = dialogue.replace("よ！　", "よ……　")
    return dialogue


def soften_section(section: str) -> tuple[str, int]:
    changed = 0
    out: list[str] = []
    trailing_newline = section.endswith("\n")
    for line in section.splitlines():
        if "PRINTFORM" in line and "「" in line and "」" in line:
            left, rest = line.split("「", 1)
            dialogue, right = rest.rsplit("」", 1)
            updated = soften(dialogue)
            if updated != dialogue:
                changed += 1
            line = left + "「" + updated + "」" + right
        out.append(line)
    result = "\n".join(out)
    if trailing_newline:
        result += "\n"
    return result, changed


def replace_range(text: str, start_marker: str, end_marker: str) -> tuple[str, int]:
    start = text.index(start_marker)
    end = text.index(end_marker, start)
    section, changed = soften_section(text[start:end])
    return text[:start] + section + text[end:], changed


