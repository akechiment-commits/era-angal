import re, glob
files=[p for p in glob.glob('ERB/CHAR/CHAR_*_COM.ERB') if re.search(r'CHAR_(\d+)_',p)]
def num(p): return int(re.search(r'CHAR_(\d+)_',p).group(1))

OLD_NOTE=';  ※パートナーがプレイヤーにクスコを使うコマンド\r\n;  ※（プレイヤーがやられる側）'
NEW_NOTE=';  ▼ パートナーが女子生徒にクスコを使うコマンド（キャラが使う側）\r\n;  ※プレイヤー(転校生)は常に男性。クスコは女性器用のため相手は助手か他の女子で、転校生ではない（転校生は見る/命じる側）'
annot=0
for p in files:
    t=open(p,'rb').read().decode('cp932')
    if OLD_NOTE in t:
        t=t.replace(OLD_NOTE,NEW_NOTE); open(p,'wb').write(t.encode('cp932')); annot+=1
print('COM203 注釈更新ファイル数:',annot)

def fix_com(num, koi, tu):
    p=[x for x in files if globals()['num'](x)==num][0]
    t=open(p,'rb').read().decode('cp932'); lines=t.split('\r\n')
    i=[k for k,l in enumerate(lines) if re.match(r'IF\s+SELECTCOM\s*==\s*203\b',l.strip())][0]
    slot=[]
    for j in range(i,len(lines)):
        s=lines[j].strip()
        if j>i and (re.match(r'IF\s+SELECTCOM\s*==',s) or s.startswith('@') or s.startswith(';--- COM')): break
        if re.search(r'PRINTFORM[LW]\s*「[^」]*」',lines[j]): slot.append(j)
    assert len(slot)==2,(num,len(slot))
    for j,new in zip(slot,[koi,tu]): lines[j]=re.sub(r'「[^」]*」','「'+new+'」',lines[j],count=1)
    nt='\r\n'.join(lines); assert '~' not in nt
    open(p,'wb').write(nt.encode('cp932'))

