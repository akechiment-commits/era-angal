def normalize(text: str) -> str:
    return text.replace("\r\n", "\n").replace("\r", "\n")


def find_matching_endif(lines: list[str], start: int) -> int:
    depth = 0
    for index in range(start, len(lines)):
        token = lines[index].strip().split(" ", 1)[0]
        if token == "IF":
            depth += 1
        elif token == "ENDIF":
            depth -= 1
            if depth == 0:
                return index
    raise ValueError(f"ENDIFが見つかりません: {start + 1}")


def printed_lines(lines: list[str]) -> list[str]:
    result = []
    for line in lines:
        stripped = line.strip()
        if stripped.startswith("PRINTFORM"):
            result.append(stripped)
    if not result:
        raise ValueError("原版のPRINTFORMが見つかりません")
    return result


def render_random_talent(
    indent: str,
    love_body: list[str],
    normal_body: list[str],
    extra: tuple[str, ...],
) -> list[str]:
    love1, love2, normal1, normal2 = extra
    control = indent + "\t"
    speech = control + "\t"
    result = [
        f"{indent}A = RAND:3",
        f"{indent}IF TALENT:TARGET:153",
        f"{control}IF A == 0",
    ]
    result.extend(speech + line for line in printed_lines(love_body))
    result.extend(
        [
            f"{control}ELSEIF A == 1",
            f'{speech}PRINTFORMW 「{love1}」',
            f"{control}ELSE",
            f'{speech}PRINTFORMW 「{love2}」',
            f"{control}ENDIF",
            f"{indent}ELSE",
            f"{control}IF A == 0",
        ]
    )
    result.extend(speech + line for line in printed_lines(normal_body))
    result.extend(
        [
            f"{control}ELSEIF A == 1",
            f'{speech}PRINTFORMW 「{normal1}」',
            f"{control}ELSE",
            f'{speech}PRINTFORMW 「{normal2}」',
            f"{control}ENDIF",
            f"{indent}ENDIF",
        ]
    )
    return result


def direct_else(lines: list[str], start: int, end: int) -> int:
    depth = 1
    for i in range(start + 1, end):
        token = lines[i].strip().split(" ", 1)[0]
        if token == "IF":
            depth += 1
        elif token == "ENDIF":
            depth -= 1
        elif token == "ELSE" and depth == 1:
            return i
    raise ValueError(f"TALENT分岐のELSEが見つかりません: {start + 1}")


def replace_talent_block(
    lines: list[str], branch_start: int, branch_end: int, extra: tuple[str, ...]
) -> tuple[int, int, list[str]]:
    talent_start = next(
        i for i in range(branch_start, branch_end) if lines[i].strip() == "IF TALENT:TARGET:153"
    )
    talent_end = find_matching_endif(lines, talent_start)
    else_index = direct_else(lines, talent_start, talent_end)
    indent = lines[talent_start][: len(lines[talent_start]) - len(lines[talent_start].lstrip())]
    return (
        talent_start,
        talent_end + 1,
        render_random_talent(
            indent,
            lines[talent_start + 1 : else_index],
            lines[else_index + 1 : talent_end],
            extra,
        ),
    )


def command_ranges(lines: list[str]) -> list[tuple[int, int, int]]:
    starts = [
        (i, int(match.group(1)))
        for i, line in enumerate(lines)
        if (match := re.match(r"IF SELECTCOM == (\d+)\s*$", line.strip()))
    ]
    result = []
    for pos, (start, command) in enumerate(starts):
        next_start = starts[pos + 1][0] if pos + 1 < len(starts) else next(
            i for i in range(start + 1, len(lines)) if lines[i].strip() == "RETURN 0"
        )
        result.append((start, next_start, command))
    return result


def simple_modifications(lines: list[str]) -> list[tuple[int, int, list[str]]]:
    ranges = {command: (start, end) for start, end, command in command_ranges(lines)}
    actual = {
        command
        for command, (start, end) in ranges.items()
        if "A = RAND:" not in "\n".join(lines[start:end])
    }
    expected = SIMPLE_IDS | STATE_IDS | {280, 410}
    if actual != expected:
        raise ValueError(f"RAND未設定コマンドが想定外です: {sorted(actual)} != {sorted(expected)}")
    return [
        replace_talent_block(lines, *ranges[command], EXTRA[command])
        for command in sorted(SIMPLE_IDS)
    ]


def state_modifications(lines: list[str]) -> list[tuple[int, int, list[str]]]:
    ranges = {command: (start, end) for start, end, command in command_ranges(lines)}
    modifications = []
    for command in sorted(STATE_IDS):
        start, end = ranges[command]
        equip_start = next(i for i in range(start, end) if lines[i].strip() == f"IF TEQUIP:{command}")
        equip_end = find_matching_endif(lines, equip_start)
        outer_else = direct_else(lines, equip_start, equip_end)
        modifications.append(
            replace_talent_block(lines, equip_start + 1, outer_else, STATE_EXTRA[command]["on"])
        )
        modifications.append(
            replace_talent_block(lines, outer_else + 1, equip_end, STATE_EXTRA[command]["off"])
        )
    return modifications


def custom_modifications(lines: list[str]) -> list[tuple[int, int, list[str]]]:
    modifications = []
    for first, last in CUSTOM_GROUPS:
        outer_start = next(i for i, line in enumerate(lines) if line.strip() == f"IF SELECTCOM == {first}")
        outer_end = find_matching_endif(lines, outer_start)
        branches = [
            (i, int(match.group(1)))
            for i in range(outer_start, outer_end + 1)
            if (match := re.match(r"(?:IF|ELSEIF) SELECTCOM == (\d+)\s*$", lines[i].strip()))
        ]
        if [command for _, command in branches] != list(range(first, last + 1)):
            raise ValueError(f"COM{first}-{last}の構造が想定外です")
        for pos, (branch_start, command) in enumerate(branches):
            branch_end = branches[pos + 1][0] if pos + 1 < len(branches) else outer_end
            modifications.append(replace_talent_block(lines, branch_start, branch_end, CUSTOM_EXTRA[command]))
    return modifications


def render_new_command(command: int, label: str, love: list[str], normal: list[str]) -> list[str]:
    result = [f";--- COM{command} {label}（原作精査後の追加10コマンド） ---", f"IF SELECTCOM == {command}"]
    if command in NEW_ASSISTANT_COMS:
        result.extend(["\tCALL AITE_YOBI, 42, ASSI", '\tLOCALS \'= @"%RESULTS%"'])
    result.extend(
        [
            "\tA = RAND:3",
            "\tIF TALENT:TARGET:153",
            "\t\tIF A == 0",
            f'\t\t\tPRINTFORMW 「{love[0]}」',
            "\t\tELSEIF A == 1",
            f'\t\t\tPRINTFORMW 「{love[1]}」',
            "\t\tELSE",
            f'\t\t\tPRINTFORMW 「{love[2]}」',
            "\t\tENDIF",
            "\tELSE",
            "\t\tIF A == 0",
            f'\t\t\tPRINTFORMW 「{normal[0]}」',
            "\t\tELSEIF A == 1",
            f'\t\t\tPRINTFORMW 「{normal[1]}」',
            "\t\tELSE",
            f'\t\t\tPRINTFORMW 「{normal[2]}」',
            "\t\tENDIF",
            "\tENDIF",
            "ENDIF",
            "",
        ]
    )
    return result


def additional_block() -> list[str]:
    result = [
        MARKER,
        "; 原作精査：一人称「あっし」。恋慕はTARGET:153。助手相手はAITE_YOBIで%LOCALS%を解決。",
    ]
    for command, (label, love, normal) in NEW_COMMANDS.items():
        result.extend(render_new_command(command, label, love, normal))
    return result


def main() -> None:
    raw = COM_PATH.read_bytes()
    text = normalize(raw.decode("cp932"))
    if MARKER in text:
        print("CHAR42再構成ブロックは適用済みです。")
        return
    lines = text.split("\n")
    modifications = simple_modifications(lines)
    # Wフェラはプレイヤーと助手の二本をキャラが奉仕するため、助手呼称を解決する。
    com66_start, _, _ = next(item for item in command_ranges(lines) if item[2] == 66)
    modifications.append((com66_start + 1, com66_start + 1, ["\tCALL AITE_YOBI, 42, ASSI", '\tLOCALS \'= @"%RESULTS%"']))
    modifications.extend(state_modifications(lines))
    modifications.extend(custom_modifications(lines))
    virgin_index = next(i for i, line in enumerate(lines) if line.strip() == "@CHAR_VIRGIN_42")
    return_index = next(i for i in range(virgin_index - 1, -1, -1) if lines[i].strip() == "RETURN 0")
    modifications.append((return_index, return_index, additional_block()))

    updated = lines[:]
    for start, end, replacement in sorted(modifications, key=lambda item: item[0], reverse=True):
        updated[start:end] = replacement
    result = "\n".join(updated).rstrip("\n") + "\n"
    # 原作で主流の依頼形に統一する。粗い創作語尾「くだせぇ」は使わない。
    result = result.replace("くだせい", "ください")
    encoded = result.encode("cp932")
    if not BACKUP_PATH.exists():
        BACKUP_PATH.parent.mkdir(parents=True, exist_ok=True)
        BACKUP_PATH.write_bytes(raw)
    COM_PATH.write_bytes(encoded.replace(b"\r\n", b"\n").replace(b"\n", b"\r\n"))
    print("CHAR42 榊むつみを原版から再構成しました。")


if __name__ == "__main__":
    main()
