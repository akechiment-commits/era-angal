def main() -> None:
    raw = TARGET.read_bytes()
    text = raw.decode("cp932")
    lines = text.replace("\r\n", "\n").splitlines()
    for line_no, (old, new) in REPLACEMENTS.items():
        current = lines[line_no - 1]
        if old not in current:
            raise SystemExit(
                f"現行本文が一致しません: L{line_no}: expected={old!r} actual={current!r}"
            )
        lines[line_no - 1] = current.replace(f"「{old}」", f"「{new}」", 1)
    updated = "\r\n".join(lines)
    if text.endswith("\n"):
        updated += "\r\n"
    encoded = updated.encode("cp932")
    if b"\n" in encoded.replace(b"\r\n", b""):
        raise SystemExit("lone LF が混入しました")
    TARGET.write_bytes(encoded)
    print(f"updated {TARGET}")
    print(f"replacements {len(REPLACEMENTS)}")


if __name__ == "__main__":
    main()
