ASSISTANT_COM = {61, 63, 65, 160, 188, 189, 196, 200, 203}


def section_spans(text: str) -> dict[int, tuple[int, int]]:
    headings = list(re.finditer(r"(?m)^(?:IF|ELSEIF) SELECTCOM == (\d+)\s*$", text))
    result: dict[int, tuple[int, int]] = {}
    for index, heading in enumerate(headings):
        end = headings[index + 1].start() if index + 1 < len(headings) else len(text)
        result[int(heading.group(1))] = (heading.start(), end)
    return result


def indent_body(body: str, prefix: str) -> str:
    return "\n".join(prefix + line if line else line for line in body.split("\n"))


def add_rand_assignment(block: str) -> str:
    return re.sub(
        r"^(?P<head>(?:IF|ELSEIF) SELECTCOM == \d+)\n",
        r"\g<head>\n\tA = RAND:3\n",
        block,
        count=1,
        flags=re.MULTILINE,
    )


def with_assistant_name(block: str) -> str:
    if "CALL AITE_YOBI, 20, ASSI" in block:
        return block
    return re.sub(
        r"^(?P<head>(?:IF|ELSEIF) SELECTCOM == \d+)\n",
        r'\g<head>\n\tCALL AITE_YOBI, 20, ASSI\n\tLOCALS \'= @"%RESULTS%"\n',
        block,
        count=1,
        flags=re.MULTILINE,
    )


def wrap_talent_branches(block: str, variants: list[tuple[str, str, str, str]]) -> str:
    pattern = re.compile(
        r"(?ms)^(?P<indent>\t+)IF TALENT:TARGET:153\n"
        r"(?P<lover>.*?)(?=\n(?P=indent)ELSE\n)"
        r"\n(?P=indent)ELSE\n"
        r"(?P<normal>.*?)\n(?P=indent)ENDIF"
    )
    matches = list(pattern.finditer(block))
    if len(matches) != len(variants):
        raise RuntimeError(f"TALENT分岐数が不一致: detected={len(matches)} expected={len(variants)}")

    for match, values in reversed(list(zip(matches, variants))):
        indent = match.group("indent")
        lover_body = match.group("lover")
        normal_body = match.group("normal")
        lover1, lover2, normal1, normal2 = values
        inner = indent + "\t"
        line_indent = indent + "\t\t"

        def branch(body: str, first: str, second: str) -> str:
            return "\n".join([
                f"{inner}IF A == 0",
                indent_body(body, line_indent),
                f"{inner}ELSEIF A == 1",
                f"{line_indent}PRINTFORMW 「{first}」",
                f"{inner}ELSE",
                f"{line_indent}PRINTFORMW 「{second}」",
                f"{inner}ENDIF",
            ])

        replacement = "\n".join([
            f"{indent}IF TALENT:TARGET:153",
            branch(lover_body, lover1, lover2),
            f"{indent}ELSE",
            branch(normal_body, normal1, normal2),
            f"{indent}ENDIF",
        ])
        block = block[:match.start()] + replacement + block[match.end():]
    return block


def replace_block(text: str, command: int, block: str) -> str:
    start, end = section_spans(text)[command]
    return text[:start] + block + text[end:]


def prepare_com60(text: str) -> str:
    start, end = section_spans(text)[60]
    block = text[start:end]
    if "CALL AITE_YOBI, 20, ASSI" not in block:
        block = re.sub(
            r"^(IF SELECTCOM == 60)\n",
            r'\1\n\tCALL AITE_YOBI, 20, ASSI\n\tLOCALS \'= @"%RESULTS%"\n',
            block,
            count=1,
            flags=re.MULTILINE,
        )
    block = block.replace("その子", "%LOCALS%")
    return replace_block(text, 60, block)


def process_com17(text: str, variants: tuple[tuple[str, str, str, str], tuple[str, str, str, str]]) -> str:
    marker = "@CHAR_VIRGIN_20"
    start = text.index("IF SELECTCOM == 17\n")
    end = text.index(marker, start)
    block = text[start:end]
    block = add_rand_assignment(block)
    block = wrap_talent_branches(block, list(variants))
    return text[:start] + block + text[end:]


def process(
    text: str,
    command: int,
    variants: list[tuple[str, str, str, str]] | tuple[str, str, str, str],
    *,
    assistant: bool = False,
) -> str:
    start, end = section_spans(text)[command]
    block = text[start:end]
    block = add_rand_assignment(block)
    if assistant:
        block = with_assistant_name(block)
    values = variants if isinstance(variants, list) else [variants]
    block = wrap_talent_branches(block, values)
    return replace_block(text, command, block)


def main() -> int:
    source = SOURCE.read_text(encoding="utf-8-sig")
    if not source.startswith("# しずく（全2689件）"):
        raise RuntimeError("しずく原作テキストのヘッダー確認に失敗しました")
    text = BACKUP.read_bytes().decode("cp932").replace("\r\n", "\n")

    text = prepare_com60(text)
    for command, variants in STANDARD_VARIANTS.items():
        text = process(text, command, variants, assistant=command in ASSISTANT_COM)
    for command, variants in CUSTOM_VARIANTS.items():
        text = process(text, command, variants)
    for command, variants in EQUIPMENT_VARIANTS.items():
        if command == 17:
            text = process_com17(text, variants)
        else:
            text = process(text, command, list(variants))

    expected = [*STANDARD_VARIANTS, *CUSTOM_VARIANTS, *EQUIPMENT_VARIANTS]
    spans = section_spans(text)
    missing = [command for command in expected if "A = RAND:3" not in text[spans[command][0]:spans[command][1]]]
    if missing:
        raise RuntimeError(f"RAND3未整備が残っています: {missing}")

    TARGET.write_bytes(text.replace("\n", "\r\n").encode("cp932"))
    print(
        f"CHAR20再構成完了: 標準{len(STANDARD_VARIANTS)}・独自{len(CUSTOM_VARIANTS)}・"
        f"装着{len(EQUIPMENT_VARIANTS)}、COM60補助参照を確認"
    )
    return 0


