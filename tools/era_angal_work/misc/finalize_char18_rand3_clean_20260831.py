def set_overrides(mapping: dict[int, tuple[str, str, str, str]]) -> None:
    for (command, index), value in OVERRIDES.items():
        if command not in mapping:
            continue
        values = list(mapping[command])
        values[index] = line(value)
        mapping[command] = tuple(values)  # type: ignore[assignment]


def prepare_com56(text: str) -> str:
    start, end = structure.section_spans(text)[56]
    block = text[start:end].replace("%LOCALS%", "%CALLNAME:ASSI%")
    return structure.replace_block(text, 56, block)


def main() -> None:
    source = SOURCE.read_text(encoding="utf-8")
    if not source.startswith("# ひめの（全1241件）"):
        raise RuntimeError("ひめの.txt の原作見出しを確認できません")

    raw = BASE_BACKUP.read_bytes().decode("cp932")
    text = raw.replace("\r\n", "\n")

    standard = dict(data.STANDARD)
    custom = dict(data.CUSTOM)
    equipment = dict(data.EQUIPMENT)
    set_overrides(standard)
    set_overrides(custom)

    text = structure.prepare_com60(text)
    text = prepare_com56(text)
    for command, variants in standard.items():
        text = structure.process_simple(text, command, variants)
    for command, variants in custom.items():
        text = structure.process_custom(text, command, variants)
    for command, variants in equipment.items():
        text = structure.process_equipment(text, command, variants)

    required = [*standard, *custom, *equipment]
    missing = []
    for command in required:
        start, end = structure.section_spans(text)[command]
        if "A = RAND:" not in text[start:end]:
            missing.append(command)
    if missing:
        raise RuntimeError(f"RAND3未整備が残っています: {missing}")

    new_bytes = text.replace("\n", "\r\n").encode("cp932")
    current = TARGET.read_bytes()
    if current == new_bytes:
        print("変更なし: CHAR18はクリーンなRAND3状態です")
        return
    SAFETY_BACKUP.parent.mkdir(parents=True, exist_ok=True)
    if not SAFETY_BACKUP.exists():
        shutil.copy2(TARGET, SAFETY_BACKUP)
    TARGET.write_bytes(new_bytes)
    print("CHAR18: RAND3追加枝をバックアップからクリーンに再構成しました")
    print("backup:", SAFETY_BACKUP)


if __name__ == "__main__":
    main()
