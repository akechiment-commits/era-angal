raw=open(PATH,'rb').read()
text=raw.decode('cp932')
lines=text.split('\r\n') if '\r\n' in text else text.split('\n')

# pointers
ptr=defaultdict(int)
hp=[0]

cur_com=None
stack=[]  # inner IF conds within a SELECTCOM block
in_hourai=False

def classify():
    conds=' && '.join(stack)
    if re.search(r'CFLAG:TARGET:\d+ == 0',conds): return 'first'
    if 'TFLAG:18 == -1' in conds:
        return 'fail_k' if 'TALENT:TARGET:153' in conds else 'fail'
    if 'TALENT:TARGET:153' in conds: return 'koi'
    if 'ABL:TARGET:0 >= 6' in conds: return 'sin'
    return 'tu'

out=[]
for ln in lines:
    s=ln.strip()
    mcom=re.match(r'IF\s+SELECTCOM\s*==\s*(\d+)',s)
    if s.startswith('@HOURAI_KOJO_68'):
        in_hourai=True; cur_com=None; stack=[]
        out.append(ln); continue
    if s.startswith('@') and not s.startswith('@HOURAI_KOJO_68'):
        in_hourai=False; cur_com=None; stack=[]
        out.append(ln); continue
    if mcom:
        cur_com=int(mcom.group(1)); stack=[]; in_hourai=False
        out.append(ln); continue
    # track inner IF stack only inside a COM block (300-325)
    if cur_com is not None and 300<=cur_com<=325:
        if re.match(r'IF\b',s) and 'SELECTCOM' not in s:
            stack.append(s[2:].strip())
        elif re.match(r'ELSEIF\b',s):
            if stack: stack[-1]=s[6:].strip()
        elif s=='ELSE':
            if stack: stack[-1]='ELSE'
        elif re.match(r'ENDIF',s):
            if stack: stack.pop()
    # fill empty slots
    if re.search(r'PRINTFORM[LW]\s*「」',s):
        if in_hourai:
            if hp[0] < len(HOURAI):
                rep=HOURAI[hp[0]]; hp[0]+=1
                out.append(ln.replace('「」','「'+rep+'」')); continue
            out.append(ln); continue
        if cur_com is not None and 300<=cur_com<=325:
            lab=classify()
            pool=TXT[cur_com].get(lab)
            if pool is None:
                print('!!! no pool COM%d %s'%(cur_com,lab)); sys.exit(1)
            k=ptr[(cur_com,lab)]
            if k>=len(pool):
                print('!!! pool exhausted COM%d %s (need more)'%(cur_com,lab)); sys.exit(1)
            ptr[(cur_com,lab)]+=1
            out.append(ln.replace('「」','「'+pool[k]+'」')); continue
    out.append(ln)

# verify all pools fully consumed
