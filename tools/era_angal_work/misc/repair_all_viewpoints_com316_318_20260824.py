def main() -> None:
    BACKUP_DIR.mkdir(parents=True, exist_ok=True)
    changed = 0
    merged = {filename: list(pairs) for filename, pairs in REPLACEMENTS.items()}
    for extra in (MORE_REPLACEMENTS, EVEN_MORE_REPLACEMENTS, FINAL_REPLACEMENTS, LAST_REPLACEMENTS, ULTIMATE_REPLACEMENTS):
        for filename, pairs in extra.items():
            merged.setdefault(filename, []).extend(pairs)
    for filename, pairs in merged.items():
        target = CHAR_DIR / filename
        backup = BACKUP_DIR / filename
        if not backup.exists():
            shutil.copy2(target, backup)
        source = backup if backup.exists() else target
        text = source.read_bytes().decode("cp932").replace("\r\n", "\n").replace("\r", "\n")
        for old, new in pairs:
            count = text.count(old)
            if count != 1:
                raise RuntimeError(f"{filename}: {count} matches for {old!r}")
            text = text.replace(old, new, 1)
            changed += 1
        target.write_bytes(text.replace("\n", "\r\n").encode("cp932"))
        print(f"updated {filename}: {len(pairs)}")
    print(f"total replacements: {changed}")
    print(f"backup: {BACKUP_DIR}")


if __name__ == "__main__":
    main()
