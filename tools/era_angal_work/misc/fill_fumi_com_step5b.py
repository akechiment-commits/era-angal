def lookup(lab):
    p=lab.split('・')
    rel=p[0]; idx=int(p[-1])-1
    if p[1]=='五重絶頂':
        return FIVE[p[2]][rel][idx]
    if p[1]=='複絶頂':
        return MULTI[p[2]][p[3]][rel][idx]
    # 単絶頂: rel・部位・強度・n
    return SINGLE[p[1]][p[2]][rel][idx]

