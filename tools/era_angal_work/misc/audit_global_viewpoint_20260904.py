def main() -> int:
    found = 0
    for path in char_files():
        text = read_cp932(path)
        blocks = extract_blocks(text)
        lines = text.replace("\r\n", "\n").splitlines()
        number = char_number(path)
        for command, patterns in RULES.items():
            block = blocks.get(command)
            if block is None:
                continue
            for offset, line in enumerate(block.lines):
                if not line.lstrip().startswith("PRINTFORM") or "「" not in line:
                    continue
                if any(re.search(pattern, line) for pattern in patterns):
                    found += 1
                    print(f"CHAR{number:02d} COM{command} L{block.start + offset + 1}: {line.strip()}")
    print(f"視点逆向き候補: {found}件")
    return 0


