def rand_block(old_line: str, new_one: str, new_two: str) -> str:
    prefix = old_line[: len(old_line) - len(old_line.lstrip("\t"))]
    text = old_line.strip()
    if not text.startswith("PRINTFORMW "):
        raise ValueError(old_line)
    return "\n".join([
        prefix + "A = RAND:3",
        prefix + "IF A == 0",
        prefix + "\t" + text,
        prefix + "ELSEIF A == 1",
        prefix + "\tPRINTFORMW " + new_one,
        prefix + "ELSE",
        prefix + "\tPRINTFORMW " + new_two,
        prefix + "ENDIF",
    ])

