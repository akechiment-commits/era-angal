ROOT = 'ERB/CHAR'
done = []
skipped = []
errors = []

for fn in sorted(os.listdir(ROOT)):
    if not fn.endswith('.ERB') or fn.endswith('_COM.ERB') or 'TEMPLATE' in fn:
        continue
    p = os.path.join(ROOT, fn)
    b = open(p, 'rb').read()
    if b'\r\n' not in b:
        continue
    t = b.decode('cp932')
    m = re.search(r'@KOJO_JUN_K(\d+)', t)
    if not m:
        continue
    cno = int(m.group(1))
    if cno not in MUGE:
        continue
    serif = MUGE[cno]
    # 検証
    if '~' in serif:
        errors.append((fn, '半角~')); continue
    try:
        serif.encode('cp932')
    except UnicodeEncodeError as e:
        errors.append((fn, 'cp932:%s' % e)); continue

    lines = t.split('\r\n')
    # 600==3 → 601==0 (ELSE) 側の空 PRINTFORMW 「」 を置換
    repl_done = False
    for i, l in enumerate(lines):
        if re.match(r'IF TFLAG:600 == 3\s*$', l):
            # ブロック内のELSE側を辿る
            in_else = False
            depth = 0
            for j in range(i, len(lines)):
                s = lines[j].strip()
                if re.match(r'IF\b', s):
                    depth += 1
                # 601==0側=内側のELSE
                if depth == 2 and re.match(r'ELSE\b', s):
                    in_else = True
                if in_else and 'PRINTFORMW 「」' in lines[j]:
                    lines[j] = lines[j].replace('PRINTFORMW 「」', 'PRINTFORMW 「' + serif + '」', 1)
                    repl_done = True
                    break
                if re.match(r'ENDIF\b', s):
                    depth -= 1
                    if depth == 0:
                        break
            break
    if not repl_done:
        errors.append((fn, '無下空欄が見つからない')); continue
    out = '\r\n'.join(lines)
    data = out.encode('cp932')
    with open(p, 'wb') as f:
        f.write(data)
    done.append((cno, fn))

print('埋めた数:', len(done))
print('エラー:', errors)
for cno, fn in sorted(done):
    print('  K%d %s' % (cno, fn))
