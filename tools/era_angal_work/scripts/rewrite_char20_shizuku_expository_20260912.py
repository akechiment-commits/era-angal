def replace_printform_line(line: str, dialogue: str) -> str:
    match = re.search(r"PRINTFORM\w*\s+", line)
    if not match:
        raise ValueError(f"not a PRINTFORM line: {line!r}")
    return line[: match.start()] + match.group(0) + "「" + dialogue + "」"


def main() -> None:
    lines = TARGET.read_bytes().decode("cp932").splitlines(keepends=True)
    if not BACKUP.exists():
        BACKUP_DIR.mkdir(parents=True, exist_ok=True)
        shutil.copy2(TARGET, BACKUP)

    for number, dialogue in REPLACEMENTS.items():
        index = number - 1
        line = lines[index].rstrip("\r\n")
        if not line.lstrip().startswith("PRINTFORM"):
            raise ValueError(f"unexpected line {number}: {line!r}")
        ending = "\r\n" if lines[index].endswith("\r\n") else "\n"
        if number == 3712:
            match = re.search(r"PRINTFORM\w*\s+", line)
            lines[index] = line[: match.start()] + "PRINTFORML 「" + dialogue + ending
        elif number == 3713:
            match = re.search(r"PRINTFORM\w*\s+", line)
            lines[index] = line[: match.start()] + "PRINTFORMW " + dialogue + ending
        else:
            lines[index] = replace_printform_line(line, dialogue) + ending

    TARGET.write_bytes("".join(lines).encode("cp932"))
    print(f"updated {TARGET}")
    print(f"changed_physical_lines {len(REPLACEMENTS)}")
    print(f"backup {BACKUP}")


if __name__ == "__main__":
    main()
