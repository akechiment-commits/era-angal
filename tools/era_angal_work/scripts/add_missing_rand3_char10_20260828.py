def rewrite_custom(lines: list[str]) -> None:
    start = next(i for i, line in enumerate(lines) if line == ";--- COM280-284 独自ウフフ ---")
    section_end = next(i for i in range(start + 1, len(lines)) if lines[i] == ";==============================================================")
    ufu = [
        ";--- COM280-284 独自ウフフ ---",
        ";  ※ウフフ中の独自カスタムコマンド（各キャラ固有の性的シチュエーション）",
    ]
    for index, scene in enumerate(CUSTOM_UFUHU):
        if index == 0:
            ufu.extend(scene)
        else:
            ufu.append("ELSEIF " + scene[0].replace("IF ", "", 1))
            ufu.extend(scene[1:])
    ufu.append("ENDIF")

    pure = [
        ";--- COM410-414 独自純愛 ---",
        ";  ※純愛系の独自カスタムコマンド（ウフフ外・各キャラ固有のシチュエーション）",
    ]
    for index, scene in enumerate(CUSTOM_PURELOVE):
        if index == 0:
            pure.extend(scene)
        else:
            pure.append("ELSEIF " + scene[0].replace("IF ", "", 1))
            pure.extend(scene[1:])
    pure.append("ENDIF")
    lines[start:section_end] = ufu + ["", ""] + pure


def normalize_assistant_alias(lines: list[str], command: int) -> None:
    start = next(i for i, line in enumerate(lines) if line == f"IF SELECTCOM == {command}")
    end = find_end(lines, start)
    block = [
        line
        for line in lines[start:end]
        if not line.strip().startswith("CALL AITE_YOBI,")
        and not line.strip().startswith("LOCALS '= ")
    ]
    block[1:1] = [
        "\tCALL AITE_YOBI, 10, ASSI",
        '\tLOCALS \'= @"%RESULTS%"',
    ]
    lines[start:end] = block


