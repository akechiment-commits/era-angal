def _speech_groups(lines: list[str], start: int, end: int) -> list[tuple[int, int]]:
    """PRINTFORM系の一つの発話を、折り返し行込みで一組として拾う。"""
    groups = []
    index = start
    while index < end:
        if "PRINTFORML" not in lines[index] and "PRINTFORMW" not in lines[index]:
            index += 1
            continue
        last = index
        while last < end and "」" not in lines[last]:
            last += 1
        if last >= end:
            raise ValueError(f"発話の終端が見つかりません: {index + 1}")
        groups.append((index, last))
        index = last + 1
    return groups


def _label_range(lines: list[str], label: str) -> tuple[int, int]:
    start = next(i for i, line in enumerate(lines) if line.strip() == label)
    end = next((i for i in range(start + 1, len(lines)) if lines[i].startswith("@")), len(lines))
    return start, end


def _replace_function_speeches(lines: list[str], label: str, texts: tuple[str, ...]) -> None:
    start, end = _label_range(lines, label)
    groups = _speech_groups(lines, start, end)
    if len(groups) != len(texts):
        raise ValueError(f"{label}: 発話数と置換文数が不一致: {len(groups)} / {len(texts)}")
    for (first, last), text in reversed(list(zip(groups, texts))):
        indent = lines[first][: len(lines[first]) - len(lines[first].lstrip())]
        lines[first:last + 1] = [f'{indent}PRINTFORMW 「{text}」']


