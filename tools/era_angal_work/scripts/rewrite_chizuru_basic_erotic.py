def _header_ranges(lines: list[str]) -> list[tuple[int, int, int]]:
    headers = [i for i, line in enumerate(lines) if re.match(r";--- COM\d+ ", line)]
    result = []
    for pos, start in enumerate(headers):
        end = headers[pos + 1] if pos + 1 < len(headers) else len(lines)
        match = re.match(r";--- COM(\d+) ", lines[start])
        if match:
            result.append((start, end, int(match.group(1))))
    return result


def _replace_prints(lines: list[str], indices: list[int], texts: tuple[str, ...]) -> None:
    if len(indices) != len(texts):
        raise ValueError(f"PRINTFORM数と置換文数が不一致: {len(indices)} / {len(texts)}")
    for index, text in zip(indices, texts):
        indent = lines[index][: len(lines[index]) - len(lines[index].lstrip())]
        lines[index] = f'{indent}PRINTFORMW 「{text}」'


def main() -> None:
    current_bytes = COM_PATH.read_bytes()
    current = current_bytes.decode(ENCODING)
    BACKUP_PATH.parent.mkdir(parents=True, exist_ok=True)
    if MARKER in current:
        if not BACKUP_PATH.exists():
            raise RuntimeError("リライト済みですが、再生成元のバックアップがありません")
        source = BACKUP_PATH.read_bytes().decode(ENCODING)
    else:
        if not BACKUP_PATH.exists():
            BACKUP_PATH.write_bytes(current_bytes)
        source = current
    lines = source.replace("\r\n", "\n").replace("\r", "\n").split("\n")
    if lines and lines[-1] == "":
        lines.pop()

    rewritten = 0
    for start, end, command in _header_ranges(lines):
        if command > 205 or command in ADDITIONAL:
            continue
        header = lines[start]
        if "追加10コマンド" in header:
            continue
        indices = [i for i in range(start, end) if "PRINTFORM" in lines[i]]
        if command == 3:
            _replace_prints(lines, indices, _com3_texts())
            rewritten += 1
        elif command in {11, 13, 14, 15, 16}:
            _replace_prints(lines, indices, _equipment_texts(command))
            rewritten += 1
        elif len(indices) == 6:
            texts = _manual().get(command) or _generated(command)
            _replace_prints(lines, indices, texts)
            rewritten += 1

    # COM17はファイル末尾の特殊関数まで次のCOM注釈がないため、最初のRETURNで切る。
    start = next(i for i, line in enumerate(lines) if line.startswith(";--- COM17 "))
    finish = next(i for i in range(start + 1, len(lines)) if lines[i] == "RETURN 0")
    indices = [i for i in range(start, finish) if "PRINTFORM" in lines[i]]
    _replace_prints(lines, indices, _equipment_texts(17))
    rewritten += 1

    _replace_function_speeches(lines, "@CHAR_EJAC_63", _ejac_texts("surface"))
    _replace_function_speeches(lines, "@CHAR_EJAC_MOUTH_63", _ejac_texts("mouth"))
    _replace_function_speeches(lines, "@CHAR_EJAC_IN_63", _ejac_texts("inside"))
    _replace_function_speeches(lines, "@CHAR_ORGASM_63", _orgasm_texts())
    for start, end, command in _header_ranges(lines):
        if command in LEGACY_EROTIC:
            groups = _speech_groups(lines, start, end)
            _replace_prints(lines, [first for first, last in groups], _legacy_erotic_texts(command))

    marker_index = next(i for i, line in enumerate(lines) if line.startswith(";--- COM0 "))
    lines.insert(marker_index, MARKER)
    result = "\r\n".join(lines)
    if not result.endswith("\r\n"):
        result += "\r\n"
    COM_PATH.write_bytes(result.encode(ENCODING))
    print(f"CHAR63: 基本性愛口上{rewritten}ブロックを反応中心にリライトしました。バックアップ: {BACKUP_PATH}")


if __name__ == "__main__":
    main()
