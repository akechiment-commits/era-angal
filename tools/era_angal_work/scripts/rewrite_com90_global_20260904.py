def replace_com90(path: Path, lines: list[str]) -> bool:
    text = read_cp932(path).replace("\r\n", "\n")
    block = extract_blocks(text).get(90)
    if block is None:
        return False
    file_lines = text.splitlines()
    starts = [
        block.start + offset
        for offset, line in enumerate(block.lines)
        if line.lstrip().startswith("PRINTFORM") and "「" in line
    ]
    if len(starts) != 6:
        raise ValueError(f"{path.name}: COM90台詞数が6でない ({len(starts)})")
    for index in range(5, -1, -1):
        start = starts[index]
        end = start + 1
        if "」" not in file_lines[start]:
            if end >= len(file_lines) or not file_lines[end].lstrip().startswith("PRINTFORM"):
                raise ValueError(f"{path.name}: COM90の継続行を読めない L{start + 1}")
            end += 1
        indent = file_lines[start][: len(file_lines[start]) - len(file_lines[start].lstrip())]
        file_lines[start:end] = [f'{indent}PRINTFORMW {lines[index]}']
    path.write_bytes("\r\n".join(file_lines).encode("cp932"))
    return True


def main() -> int:
    BACKUP_DIR.mkdir(parents=True, exist_ok=True)
    changed = 0
    for number, (source_name, lines) in DATA.items():
        source = ROOT / "tools/output" / f"{source_name}.txt"
        if not source.read_text(encoding="utf-8-sig").startswith(f"# {source_name}（全"):
            raise RuntimeError(f"原作ヘッダー確認失敗: {source}")
        path = next(ROOT.glob(f"ERB/CHAR/CHAR_{number:02d}_*_COM.ERB"))
        backup = BACKUP_DIR / path.name
        if not backup.exists():
            shutil.copy2(path, backup)
        changed += int(replace_com90(path, lines))
    print(f"COM90再作成CHAR数: {changed}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
