def normalize(text: str) -> str:
    return text.replace("\r\n", "\n").replace("\r", "\n")


def find_end(lines: list[str], start: int) -> int:
    depth = 0
    for i in range(start, len(lines)):
        stripped = lines[i].strip()
        if stripped.startswith("IF "):
            depth += 1
        elif stripped == "ENDIF":
            depth -= 1
            if depth == 0:
                return i + 1
    raise RuntimeError(f"ENDIF not found: {start + 1}")


def print_variants(block: list[str], talent_idx: int) -> tuple[int, list[str], list[str]]:
    talent_end = find_end(block, talent_idx)
    else_idx = next(i for i in range(talent_idx + 1, talent_end) if block[i].strip() == "ELSE")
    love = [x.strip() for x in block[talent_idx + 1 : else_idx] if x.strip().startswith("PRINTFORM")]
    normal = [x.strip() for x in block[else_idx + 1 : talent_end - 1] if x.strip().startswith("PRINTFORM")]
    if not love or not normal:
        raise RuntimeError("talent branch has no speech")
    return talent_end, love, normal


def render_variant(variant: list[str] | str, indent: str) -> list[str]:
    if isinstance(variant, str):
        variant = [variant]
    return [indent + line.strip() for line in variant if line.strip().startswith("PRINTFORM")]


def render_talent(base: str, love0: list[str], normal0: list[str], extra: tuple[str, ...], talent: str = "153") -> list[str]:
    love1, love2, normal1, normal2 = extra
    out = [base + "A = RAND:3", base + f"IF TALENT:TARGET:{talent}"]
    out += [base + "\tIF A == 0"] + render_variant(love0, base + "\t\t")
    out += [base + "\tELSEIF A == 1", base + f'\t\tPRINTFORMW 「{love1}」', base + "\tELSE", base + f'\t\tPRINTFORMW 「{love2}」', base + "\tENDIF", base + "ELSE"]
    out += [base + "\tIF A == 0"] + render_variant(normal0, base + "\t\t")
    out += [base + "\tELSEIF A == 1", base + f'\t\tPRINTFORMW 「{normal1}」', base + "\tELSE", base + f'\t\tPRINTFORMW 「{normal2}」', base + "\tENDIF", base + "ENDIF"]
    return out


def command_starts(lines: list[str]) -> list[tuple[int, int]]:
    return [(i, int(m.group(1))) for i, line in enumerate(lines) if (m := re.match(r"^(?:IF|ELSEIF) SELECTCOM == (\d+)", line))]


def build_simple_mod(lines: list[str], start: int, end: int, command_id: int) -> list[str]:
    block = lines[start:end]
    talent_idx = next(i for i, line in enumerate(block) if line.strip() == "IF TALENT:TARGET:153")
    talent_end, love0, normal0 = print_variants(block, talent_idx)
    base = block[talent_idx][: len(block[talent_idx]) - len(block[talent_idx].lstrip())]
    return block[:talent_idx] + render_talent(base, love0, normal0, EXTRA[command_id]) + block[talent_end:]


def build_state_mod(lines: list[str], start: int, end: int, command_id: int) -> list[str]:
    block = lines[start:end]
    talent_indices = [i for i, line in enumerate(block) if line.strip() == "IF TALENT:TARGET:153"]
    if len(talent_indices) != 2:
        raise RuntimeError(f"COM{command_id} expected two talent branches, got {len(talent_indices)}")
    for talent_idx in reversed(talent_indices):
        talent_end, love0, normal0 = print_variants(block, talent_idx)
        base = block[talent_idx][: len(block[talent_idx]) - len(block[talent_idx].lstrip())]
        state = "on" if talent_idx == talent_indices[0] else "off"
        block[talent_idx:talent_end] = render_talent(base, love0, normal0, STATE_EXTRA[command_id][state])
    return block


def build_chain_mod(lines: list[str], start: int, end: int, ids: list[int]) -> list[str]:
    chain = lines[start:end]
    branch_starts = [i for i, line in enumerate(chain) if re.match(r"^(?:IF|ELSEIF) SELECTCOM == \d+", line)]
    out: list[str] = []
    for pos, branch_start in enumerate(branch_starts):
        branch_end = branch_starts[pos + 1] if pos + 1 < len(branch_starts) else len(chain) - 1
        branch = chain[branch_start:branch_end]
        command_id = int(re.match(r"^(?:IF|ELSEIF) SELECTCOM == (\d+)", branch[0]).group(1))
        if command_id not in ids:
            raise RuntimeError(f"unexpected custom command: {command_id}")
        talent_idx = next(i for i, line in enumerate(branch) if line.strip() == "IF TALENT:TARGET:153")
        talent_end, love0, normal0 = print_variants(branch, talent_idx)
        base = branch[talent_idx][: len(branch[talent_idx]) - len(branch[talent_idx].lstrip())]
        out += branch[:talent_idx] + render_talent(base, love0, normal0, CUSTOM_EXTRA[command_id])
    out.append("ENDIF")
    return out


def build_mods(lines: list[str]) -> list[tuple[int, int, list[str]]]:
    starts = command_starts(lines)
    start_by_id = {command_id: index for index, command_id in starts if lines[index].startswith("IF SELECTCOM")}
    required = SIMPLE_IDS | set(STATE_IDS) | {first_id for first_id, _ in CUSTOM_GROUPS}
    missing = sorted(required - set(start_by_id))
    if missing:
        raise RuntimeError(f"missing existing command blocks: {missing}")
    mods = []
    for command_id in sorted(SIMPLE_IDS):
        start = start_by_id[command_id]
        mods.append((start, find_end(lines, start), build_simple_mod(lines, start, find_end(lines, start), command_id)))
    for command_id in STATE_IDS:
        start = start_by_id[command_id]
        mods.append((start, find_end(lines, start), build_state_mod(lines, start, find_end(lines, start), command_id)))
    for first_id, ids in CUSTOM_GROUPS:
        start = start_by_id[first_id]
        mods.append((start, find_end(lines, start), build_chain_mod(lines, start, find_end(lines, start), ids)))
    return mods


def render_new_command(command_id: int, label: str, love: list[str], normal: list[str]) -> list[str]:
    out = [f";--- COM{command_id} {label}（追加10コマンド） ---", f"IF SELECTCOM == {command_id}"]
    if command_id in {60, 62, 76, 202, 258}:
        out += ["\tCALL AITE_YOBI, 49, ASSI", '\tLOCALS \'= @"%RESULTS%"']
    out += ["\tA = RAND:3", "\tIF TALENT:TARGET:85"]
    for index, line in enumerate(love):
        out += ["\t\tIF A == 0" if index == 0 else "\t\tELSEIF A == 1" if index == 1 else "\t\tELSE", f"\t\t\tPRINTFORMW 「{line}」"]
    out += ["\t\tENDIF", "\tELSE"]
    for index, line in enumerate(normal):
        out += ["\t\tIF A == 0" if index == 0 else "\t\tELSEIF A == 1" if index == 1 else "\t\tELSE", f"\t\t\tPRINTFORMW 「{line}」"]
    out += ["\t\tENDIF", "\tENDIF", "ENDIF", ""]
    return out


def main() -> None:
    if MARKER in COM_PATH.read_bytes().decode("cp932"):
        print("CHAR49のRAND3/追加10ブロックは適用済みです。")
        return
    if set(NEW_COMMANDS) != {60, 62, 76, 78, 79, 84, 86, 202, 258, 318}:
        raise RuntimeError("NEW_COMMANDS id mismatch")
    text = normalize(COM_PATH.read_bytes().decode("cp932"))
    lines = text.split("\n")
    mods = build_mods(lines)
    used: set[int] = set()
    for start, end, _ in mods:
        if any(i in used for i in range(start, end)):
            raise RuntimeError("overlapping modifications")
        used.update(range(start, end))
    for start, end, replacement in sorted(mods, reverse=True):
        lines[start:end] = replacement
    marker_index = next(i for i, line in enumerate(lines) if line.startswith("@CHAR_VIRGIN_49"))
    return_index = next(i for i in range(marker_index - 1, -1, -1) if lines[i].strip() == "RETURN 0")
    block = [MARKER, "; 追加10コマンド：恋慕はTALENT:TARGET:85、助手相手はAITE_YOBIで解決。", ""]
    for command_id, (label, love, normal) in NEW_COMMANDS.items():
        block.extend(render_new_command(command_id, label, love, normal))
    lines[return_index:return_index] = block
    result = "\n".join(lines).rstrip("\n") + "\n"
    encoded = result.encode("cp932")
    if not BACKUP_PATH.exists():
        BACKUP_PATH.parent.mkdir(parents=True, exist_ok=True)
        BACKUP_PATH.write_bytes(COM_PATH.read_bytes())
    COM_PATH.write_bytes(encoded.replace(b"\r\n", b"\n").replace(b"\n", b"\r\n"))
    print(f"CHAR49: RAND3化 simple={len(SIMPLE_IDS)}, state={len(STATE_IDS)}, custom=10; added={len(NEW_COMMANDS)}")


if __name__ == "__main__":
    main()
