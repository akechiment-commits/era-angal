def if_end(lines: list[str], start: int, limit: int) -> int:
    depth = 1
    for i in range(start + 1, limit):
        stripped = lines[i].lstrip()
        if stripped.startswith("IF "):
            depth += 1
        elif stripped == "ENDIF":
            depth -= 1
            if depth == 0:
                return i
    raise RuntimeError(f"IF at line {start + 1} has no matching ENDIF")


def if_else(lines: list[str], start: int, end: int) -> int:
    depth = 1
    for i in range(start + 1, end):
        stripped = lines[i].lstrip()
        if stripped.startswith("IF "):
            depth += 1
        elif stripped == "ENDIF":
            depth -= 1
        elif stripped == "ELSE" and depth == 1:
            return i
    raise RuntimeError(f"IF at line {start + 1} has no matching ELSE")


def command_start(lines: list[str], number: int) -> int:
    needle = f"IF SELECTCOM == {number}"
    hits = [i for i, line in enumerate(lines) if line == needle]
    if len(hits) != 1:
        raise RuntimeError(f"expected one top-level {needle}, got {len(hits)}")
    return hits[0]


def command_end(lines: list[str], start: int) -> int:
    for i in range(start + 1, len(lines)):
        if re.match(r"^IF SELECTCOM == \d+$", lines[i]):
            return i
        if lines[i] == "RETURN 0":
            return i
    return len(lines)


def talent_start(lines: list[str], start: int, end: int) -> int:
    hits = [i for i in range(start, end) if re.match(r"^\t+IF TALENT:TARGET:153\s*$", lines[i])]
    if len(hits) != 1:
        raise RuntimeError(f"expected one TALENT branch at line {start + 1}, got {len(hits)}")
    return hits[0]


def print_statement(lines: list[str], start: int, end: int) -> tuple[int, int]:
    first = next((i for i in range(start, end) if "PRINTFORM" in lines[i]), None)
    if first is None:
        raise RuntimeError(f"no PRINTFORM between lines {start + 1} and {end}")
    last = first
    while "」" not in lines[last] and last + 1 < end:
        last += 1
    if "」" not in lines[last]:
        raise RuntimeError(f"unclosed PRINTFORM at line {first + 1}")
    return first, last + 1


def wrap_print_statement(
    lines: list[str], first: int, last: int, alternatives: tuple[str, str]
) -> None:
    old = lines[first:last]
    indent = old[0][: len(old[0]) - len(old[0].lstrip())]
    body = [f"{indent}\t{x.lstrip()}" for x in old]
    lines[first:last] = [
        f"{indent}IF A == 0",
        *body,
        f"{indent}ELSEIF A == 1",
        f'{indent}\tPRINTFORMW 「{alternatives[0]}」',
        f"{indent}ELSE",
        f'{indent}\tPRINTFORMW 「{alternatives[1]}」',
        f"{indent}ENDIF",
    ]


def wrap_talent(lines: list[str], start: int, end: int, extras: tuple[str, str, str, str]) -> None:
    tstart = talent_start(lines, start, end)
    tend = if_end(lines, tstart, end)
    outer_else = if_else(lines, tstart, tend)
    first, last = print_statement(lines, outer_else + 1, tend)
    wrap_print_statement(lines, first, last, (extras[2], extras[3]))

    end += 6
    tstart = talent_start(lines, start, end)
    tend = if_end(lines, tstart, end)
    outer_else = if_else(lines, tstart, tend)
    first, last = print_statement(lines, tstart + 1, outer_else)
    wrap_print_statement(lines, first, last, (extras[0], extras[1]))


def add_rand_standard(lines: list[str], number: int) -> None:
    start = command_start(lines, number)
    end = command_end(lines, start)
    if any("RAND:" in line for line in lines[start:end]):
        raise RuntimeError(f"COM{number} already has RAND")
    lines.insert(start + 1, "\tA = RAND:3")
    wrap_talent(lines, start, end + 1, SIMPLE_EXTRA[number])


def add_rand_equipment(lines: list[str], number: int) -> None:
    start = command_start(lines, number)
    end = command_end(lines, start)
    if any("RAND:" in line for line in lines[start:end]):
        raise RuntimeError(f"COM{number} already has RAND")
    lines.insert(start + 1, "\tA = RAND:3")
    end += 1
    equip = next(i for i in range(start, end) if lines[i].lstrip() == f"IF TEQUIP:{number}")
    outer_else = if_else(lines, equip, end)
    # TEQUIPのELSE側にも通常項目と同じTALENT分岐がある。
    # その内側のENDIFを上限にすると、if_endが終端を探索できないため、
    # コマンド全体を上限として渡す。
    wrap_talent(lines, outer_else, end, EQUIP_EXTRA[number]["off"])

    start = command_start(lines, number)
    end = command_end(lines, start)
    equip = next(i for i in range(start, end) if lines[i].lstrip() == f"IF TEQUIP:{number}")
    outer_else = if_else(lines, equip, end)
    wrap_talent(lines, equip, outer_else, EQUIP_EXTRA[number]["on"])


def scenario_start(lines: list[str], number: int) -> int:
    hits = [
        i for i, line in enumerate(lines)
        if re.match(rf"^\s*(?:IF|ELSEIF) SELECTCOM == {number}$", line)
    ]
    if len(hits) != 1:
        raise RuntimeError(f"expected one scenario SELECTCOM {number}, got {len(hits)}")
    return hits[0]


def scenario_end(lines: list[str], start: int) -> int:
    for i in range(start + 1, len(lines)):
        if re.match(r"^\s*ELSEIF SELECTCOM == \d+$", lines[i]):
            return i
        if lines[i].startswith("ENDIF"):
            return i
    raise RuntimeError(f"scenario at line {start + 1} has no end")


def add_rand_scenario(lines: list[str], number: int) -> None:
    start = scenario_start(lines, number)
    end = scenario_end(lines, start)
    if any("RAND:" in line for line in lines[start:end]):
        raise RuntimeError(f"COM{number} already has RAND")
    lines.insert(start + 1, "\tA = RAND:3")
    wrap_talent(lines, start, end + 1, CUSTOM_EXTRA[number])


