def validate(text: str) -> None:
    # 原作には「私語」「私物」などの一般語があるため、漢字の私全体は禁じない。
    if "わたし" in text or "俺" in text:
        raise RuntimeError("かえで口上に一人称の揺れが混入")
    if "~" in text:
        raise RuntimeError("半角チルダが混入")
    if text.count("A = RAND:3") < 190:
        raise RuntimeError("RAND3 additions are incomplete")


def main() -> None:
    current = SOURCE.read_bytes().decode("cp932")
    if not BACKUP.exists():
        raise SystemExit(f"missing backup: {BACKUP}")
    text = BACKUP.read_bytes().decode("cp932") if MARKER in current else current
    text = text.replace("\r\n", "\n").replace("\r", "\n")
    lines = text.split("\n")

    equipment = set(EQUIP_EXTRA)
    for number in sorted(SIMPLE_EXTRA):
        if number not in equipment:
            add_rand_standard(lines, number)
    for number in sorted(equipment):
        add_rand_equipment(lines, number)
    for number in sorted(CUSTOM_EXTRA, reverse=True):
        add_rand_scenario(lines, number)

    return_index = next(i for i, line in enumerate(lines) if line == "RETURN 0")
    lines[return_index:return_index] = ["", *render_additional()]
    result = "\n".join(lines)
    validate(result)
    SOURCE.write_bytes(result.replace("\n", "\r\n").encode("cp932"))
    print(
        f"updated {SOURCE} | standard={len(SIMPLE_EXTRA)} equipment={len(EQUIP_EXTRA)} "
        f"custom={len(CUSTOM_EXTRA)} additional={len(ADDITIONAL10)}"
    )


if __name__ == "__main__":
    main()
