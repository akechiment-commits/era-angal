def prepare_com60(text: str) -> str:
    start, end = section_spans(text)[60]
    block = text[start:end]
    if "CALL AITE_YOBI, 18, ASSI" not in block:
        block = re.sub(
            r"^(IF SELECTCOM == 60)\n",
            r'\1\n\tCALL AITE_YOBI, 18, ASSI\n\tLOCALS \'= @"%RESULTS%"\n',
            block,
            count=1,
            flags=re.MULTILINE,
        )
    block = block.replace("この子も照れてるみたいだよお", "%LOCALS%も照れてるみたいだよお")
    block = block.replace("相手の子のほうが固まってるう", "%LOCALS%のほうが固まってるう")
    return replace_block(text, 60, block)


def main() -> int:
    source = SOURCE.read_text(encoding="utf-8")
    if not source.startswith("# ひめの（全1241件）"):
        raise RuntimeError("ひめの.txt の原作見出しを確認できません")
    raw = TARGET.read_bytes().decode("cp932")
    text = raw.replace("\r\n", "\n")
    before = text

    text = prepare_com60(text)
    for com, variants in STANDARD_VARIANTS.items():
        text = process_simple(text, com, variants)
    for com, variants in CUSTOM_VARIANTS.items():
        text = process_custom(text, com, variants)
    for com, variants in EQUIPMENT_VARIANTS.items():
        text = process_equipment(text, com, variants)

    missing = []
    for com in [*STANDARD_VARIANTS, *CUSTOM_VARIANTS, *EQUIPMENT_VARIANTS]:
        start, end = section_spans(text)[com]
        if "A = RAND:" not in text[start:end]:
            missing.append(com)
    if missing:
        raise RuntimeError(f"RAND3未整備が残っています: {missing}")
    if text == before:
        print("変更なし")
        return 0

    BACKUP.parent.mkdir(parents=True, exist_ok=True)
    if not BACKUP.exists():
        shutil.copy2(TARGET, BACKUP)
    TARGET.write_bytes(text.replace("\n", "\r\n").encode("cp932"))
    print(
        f"CHAR18: 標準{len(STANDARD_VARIANTS)}枠・独自{len(CUSTOM_VARIANTS)}枠・"
        f"装着{len(EQUIPMENT_VARIANTS)}枠をRAND3化、COM60助手呼称を補完"
    )
    print("backup:", BACKUP)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
