"""CHAR03ちよ側の他CHARとの長文完全一致を、本人の原作声へ再構成する。"""

from pathlib import Path


ROOT = Path(__file__).resolve().parents[3]
TARGET = ROOT / "ERB" / "CHAR" / "CHAR_03_小野ちよ_COM.ERB"
ENCODING = "cp932"


REWRITES = {
    "んっ……ごく……。こ、これで終わりですか？　もう見ないでください……":
        "ごく……っ。喉が熱いですぅ……。お兄ちゃん先輩、そんなに見つめられたら、恥ずかしくて顔を上げられません……",
    "んっ……もう、何も考えたくありません。こんなこと、忘れさせてください……":
        "ごく……っ。もういっぱいですぅ……。お兄ちゃん先輩、次はゆっくりにしてくださいね……？",
    "ひっ……口に戻さないでください。もう、十分ですよね……っ":
        "ふぇ……また戻ってくるんですか？　わたし、ちゃんと飲みましたから、もう勘弁してくださいぃ……っ",
    "んっ……口移し……っ。こんなの、恥ずかしくて……んんっ……":
        "ふぇ……お兄ちゃん先輩の唇が近いと、飲み物よりどきどきしちゃいますぅ……。こぼさないように、ゆっくりお願いします……♪",
    "ん……指を……っ。こんなこと、恥ずかしくてできません……":
        "んぅ……お兄ちゃん先輩の指、わたしが舐めるんですかぁ？　えへへ……ちゃんと気持ちよくできるように、がんばりますね……♪",
    "ひっ……先端を当てますね。痛かったら、すぐに言ってください……っ":
        "先輩、深呼吸してくださいね。わたし、合図を聞きながら、そっと進めますから……♪",
    "え……見せるんですか？　そ、そんなの……見ちゃいますけど……":
        "ふぇ……お兄ちゃん先輩、ほんとうに見せてくれるんですか？　あの、変じゃないですから……最後まで、見てますね……♪",
}


def main() -> None:
    text = TARGET.read_bytes().decode(ENCODING)
    for old, new in REWRITES.items():
        count = text.count(old)
        if count != 1:
            raise RuntimeError(f"置換対象の出現数が不正です: {count}件 / {old}")
        text = text.replace(old, new, 1)
    TARGET.write_bytes(text.encode(ENCODING))
    print(f"CHAR03 cross-CHAR rewrite: {len(REWRITES)} lines")


if __name__ == "__main__":
    main()
