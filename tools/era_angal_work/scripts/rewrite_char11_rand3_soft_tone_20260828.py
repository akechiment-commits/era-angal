def find_end(lines: list[str], start: int) -> int:
    depth = 0
    for index in range(start, len(lines)):
        stripped = lines[index].strip()
        if re.match(r"^IF(?:\s|\()", stripped):
            depth += 1
        elif stripped == "ENDIF":
            depth -= 1
            if depth == 0:
                return index + 1
    raise RuntimeError(f"ENDIF not found: line {start + 1}")


def rewrite_branch_lines(block: list[str], variants: tuple[str, ...]) -> list[str]:
    if len(variants) % 4 != 0:
        raise RuntimeError(f"分岐数が不正です: {len(variants)}")
    result = list(block)
    relation = -1
    active: tuple[int, int, str] | None = None
    replaced_branches: set[tuple[int, int]] = set()
    replaced = 0
    for index, line in enumerate(block):
        if re.match(r"^\t+IF A == 0$", line):
            relation += 1
            match = re.match(r"^(\t+)IF A == 0$", line)
            active = (relation, 0, match.group(1))
        elif active and (match := re.match(r"^(\t+)ELSEIF A == 1$", line)) and match.group(1) == active[2]:
            active = (active[0], 1, active[2])
        elif active and line == active[2] + "ELSE":
            active = (active[0], 2, active[2])
        elif active and active[1] in (1, 2) and "PRINTFORM" in line:
            relation_index, branch, indent = active
            if (relation_index, branch) in replaced_branches:
                continue
            offset = relation_index * 2 + branch - 1
            if offset >= len(variants):
                raise RuntimeError(f"分岐位置が不正です: relation={relation_index}, branch={branch}")
            result[index] = indent + "\tPRINTFORMW " + variants[offset]
            replaced += 1
            replaced_branches.add((relation_index, branch))
    expected = (len(variants) // 2) * 2
    if replaced != expected:
        raise RuntimeError(f"RAND3追加文の置換数が不一致: expected={expected}, actual={replaced}")
    return result


def rewrite_simple(lines: list[str], command: int, variants: tuple[str, ...]) -> None:
    marker = f"IF SELECTCOM == {command}"
    starts = [i for i, line in enumerate(lines) if line == marker]
    if len(starts) != 1:
        raise RuntimeError(f"COM{command}: SELECTCOM blocks={len(starts)}")
    start = starts[0]
    end = find_end(lines, start)
    lines[start:end] = rewrite_branch_lines(lines[start:end], variants)


def rewrite_custom(lines: list[str]) -> None:
    section_start = next(i for i, line in enumerate(lines) if line == ";--- COM280-284 独自ウフフ ---")
    section_end = next(i for i in range(section_start + 1, len(lines)) if lines[i] == ";==============================================================")
    selector = re.compile(r"^(?:IF|ELSEIF) SELECTCOM == (\d+)$")
    positions = [
        (i, int(match.group(1)))
        for i in range(section_start, section_end)
        if (match := selector.match(lines[i]))
    ]
    for position, (start, command) in enumerate(positions):
        end = positions[position + 1][0] if position + 1 < len(positions) else section_end
        variants = CUSTOM_VARIANTS[command]
        lines[start:end] = rewrite_branch_lines(lines[start:end], variants)
        delta = len(lines[start:end]) - (end - start)
        if delta:
            positions = [(i + delta if i > start else i, c) for i, c in positions]
            section_end += delta


