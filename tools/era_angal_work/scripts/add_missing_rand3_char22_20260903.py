def with_assistant_name_22(block: str) -> str:
    if "CALL AITE_YOBI, 22, ASSI" not in block:
        block = re.sub(
            r"^(?P<head>(?:IF|ELSEIF) SELECTCOM == \d+)\n",
            lambda m: (
                f"{m.group('head')}\n"
                "\tCALL AITE_YOBI, 22, ASSI\n"
                '\tLOCALS \'= @"%RESULTS%"\n'
            ),
            block,
            count=1,
            flags=re.MULTILINE,
        )
    elif "LOCALS '= @\"%RESULTS%\"" not in block:
        block = re.sub(
            r"^(?P<call>\tCALL AITE_YOBI, 22, ASSI)\n",
            "\\g<call>\n\tLOCALS '= @\"%RESULTS%\"\n",
            block,
            count=1,
            flags=re.MULTILINE,
        )
    return block


def process_assistant(text: str, command: int, variants) -> str:
    start, end = section_spans(text)[command]
    block = text[start:end]
    block = add_rand_assignment(block)
    block = with_assistant_name_22(block)
    block = wrap_talent_branches(block, list(variants) if isinstance(variants, list) else [variants])
    return replace_block(text, command, block)


def prepare_com60(text: str) -> str:
    start, end = section_spans(text)[60]
    block = text[start:end]
    block = with_assistant_name_22(block)
    block = block.replace("別の方", "%LOCALS%")
    block = block.replace("今の相手", "%LOCALS%")
    block = block.replace("唇やわらかいし", "%LOCALS%の唇、やわらかいし")
    block = block.replace("先に照れたほう", "%LOCALS%とあたし、先に照れたほう")
    return replace_block(text, 60, block)


def prepare_com56(text: str) -> str:
    start, end = section_spans(text)[56]
    block = text[start:end].replace("%LOCALS%", "%CALLNAME:ASSI%")
    return replace_block(text, 56, block)


def process_com17(text: str, variants) -> str:
    start = text.index("IF SELECTCOM == 17\n")
    end = text.index("RETURN 0", start)
    block = text[start:end]
    block = add_rand_assignment(block)
    block = wrap_talent_branches(block, list(variants))
    return text[:start] + block + text[end:]


def main() -> int:
    source = SOURCE.read_text(encoding="utf-8-sig")
    if not source.startswith("# いかり（全1287件）"):
        raise RuntimeError("いかり原作テキストのヘッダー確認に失敗しました")
    BACKUP.parent.mkdir(parents=True, exist_ok=True)
    if not BACKUP.exists():
        shutil.copy2(TARGET, BACKUP)
    text = BACKUP.read_bytes().decode("cp932").replace("\r\n", "\n")

    text = prepare_com60(text)
    for command, variants in STANDARD_VARIANTS.items():
        if command in ASSISTANT_COM:
            text = process_assistant(text, command, variants)
        else:
            text = process(text, command, variants)
    for command, variants in CUSTOM_VARIANTS.items():
        text = process(text, command, variants)
    for command, variants in EQUIPMENT_VARIANTS.items():
        if command == 17:
            text = process_com17(text, variants)
        else:
            text = process(text, command, list(variants))

    text = prepare_com56(text)
    text = apply_hair_viewpoint(text)
    text = apply_light_orgasm(text)
    text = text.replace("LOCALS " + chr(92) + "'= @\"%RESULTS%\"", "LOCALS '= @\"%RESULTS%\"")
    expected = [*STANDARD_VARIANTS, *CUSTOM_VARIANTS, *EQUIPMENT_VARIANTS]
    spans = section_spans(text)
    missing = [command for command in expected if "A = RAND:3" not in text[spans[command][0]:spans[command][1]]]
    if missing:
        raise RuntimeError(f"RAND3未整備が残っています: {missing}")

    TARGET.write_bytes(text.replace("\n", "\r\n").encode("cp932"))
    print("CHAR22: 標準64・独自10・装着6をRAND3化、COM60助手呼称を補完")
    return 0


