def command_block(text: str, command: int) -> tuple[int, int]:
    start_match = re.search(rf"(?m)^IF SELECTCOM == {command}\n", text)
    if start_match is None:
        raise RuntimeError(f"COM{command} が見つかりません")
    start = start_match.start()
    next_match = re.search(r"(?m)^IF SELECTCOM == \d+\n", text[start_match.end():])
    end = start_match.end() + next_match.start() if next_match else len(text)
    return start, end


def replace_in_command(text: str, command: int, old: str, new: str) -> str:
    start, end = command_block(text, command)
    block = text[start:end]
    count = block.count(old)
    if count == 1:
        block = block.replace(old, new, 1)
        return text[:start] + block + text[end:]
    if count == 0 and new in block:
        return text
    raise RuntimeError(f"COM{command}: 対象文の出現数が {count} です: {old}")


