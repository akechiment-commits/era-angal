def toggle_voice_block(out, indent, love, normal):
    inner = indent + "\t"
    branch = inner + "\t"
    out += [f"{indent}A = RAND:3", f"{indent}IF TALENT:TARGET:153"]
    out += [f"{inner}IF A == 0", f"{branch}PRINTFORMW 「{love[0]}」", f"{inner}ELSEIF A == 1", f"{branch}PRINTFORMW 「{love[1]}」", f"{inner}ELSE", f"{branch}PRINTFORMW 「{love[2]}」", f"{inner}ENDIF"]
    out += [f"{indent}ELSE", f"{inner}IF A == 0", f"{branch}PRINTFORMW 「{normal[0]}」", f"{inner}ELSEIF A == 1", f"{branch}PRINTFORMW 「{normal[1]}」", f"{inner}ELSE", f"{branch}PRINTFORMW 「{normal[2]}」", f"{inner}ENDIF", f"{indent}ENDIF"]


def toggle_block(cid, header, on_love, on_normal, off_love, off_normal):
    out = [header, f"IF SELECTCOM == {cid}", f"\tIF TEQUIP:{cid}", "\t\t;--- 装着中 ---"]
    toggle_voice_block(out, "\t\t", on_love, on_normal)
    out += ["\tELSE", "\t\t;--- 取り外し ---"]
    toggle_voice_block(out, "\t\t", off_love, off_normal)
    out += ["\tENDIF", "ENDIF"]
    return out


