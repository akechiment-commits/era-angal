def selector_id(line):
    m = re.match(r";--- COM(\d+)(?:\s|$)", line)
    return int(m.group(1)) if m else None


def standard_block(cid, love, normal, header):
    out = [header, f"IF SELECTCOM == {cid}", "\tA = RAND:3", "\tIF TALENT:TARGET:153"]
