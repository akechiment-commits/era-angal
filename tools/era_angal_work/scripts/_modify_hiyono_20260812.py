def replace_lines(lines, start, end, new_lines):
    return lines[:start] + new_lines + lines[end:]


def find_header(lines, cid):
    pat = re.compile(rf"^;--- COM{cid}(?:\s|$)")
    for i, line in enumerate(lines):
        if pat.match(line):
            return i
    raise RuntimeError(f"header not found: COM{cid}")


def next_com_header(lines, start):
    for i in range(start + 1, len(lines)):
        if lines[i].startswith(";--- COM"):
            return i
    return len(lines)


def rewrite_standard(lines, cid):
    st = find_header(lines, cid)
    en = next_com_header(lines, st)
    header = lines[st]
    love, normal = BRANCHES[cid]
    return replace_lines(lines, st, en, standard_block(cid, love, normal, header))


def rewrite_custom(lines, start_marker, end_marker, data, title):
    st = next(i for i, line in enumerate(lines) if line.startswith(start_marker))
    en = next(i for i in range(st + 1, len(lines)) if lines[i].startswith(end_marker))
    out = [start_marker]
    for cid in sorted(data):
        scene, love, normal = data[cid]
        out += custom_scene_block(cid, scene, love, normal)
        out.append("")
    out += [end_marker]
    return replace_lines(lines, st, en, out)


