import re, glob
files=[p for p in glob.glob('ERB/CHAR/CHAR_*_COM.ERB') if re.search(r'CHAR_(\d+)_',p)]
def num(p): return int(re.search(r'CHAR_(\d+)_',p).group(1))
CLAR=';  ※プレイヤー(転校生)は常に男性。相手は助手か他の女子で、転校生ではない（転校生は見る/命じる側）'

a63=a200=0
for p in files:
    t=open(p,'rb').read().decode('cp932'); ch=False
    o63=';  ※女性同士が性器を合わせるプレイ\r\nIF SELECTCOM == 63'
    if o63 in t and CLAR not in t.split('IF SELECTCOM == 63')[0][-200:]:
        t=t.replace(o63,';  ※女性同士が性器を合わせるプレイ\r\n'+CLAR+'\r\nIF SELECTCOM == 63'); a63+=1; ch=True
    o200=';--- COM200 乳の揉み合い ---\r\nIF SELECTCOM == 200'
    if o200 in t:
        t=t.replace(o200,';--- COM200 乳の揉み合い ---\r\n;  ▼ 女性同士が乳を揉み合うプレイ\r\n'+CLAR+'\r\nIF SELECTCOM == 200'); a200+=1; ch=True
    if ch: open(p,'wb').write(t.encode('cp932'))
print('注釈追加: COM63 %dファイル / COM200 %dファイル'%(a63,a200))

def fix_com(n, com, koi, tu):
    p=[x for x in files if num(x)==n][0]
    t=open(p,'rb').read().decode('cp932'); L=t.split('\r\n')
    i=[k for k,l in enumerate(L) if re.match(r'IF\s+SELECTCOM\s*==\s*%d\b'%com,l.strip())][0]
    slot=[]
    for j in range(i,len(L)):
        s=L[j].strip()
        if j>i and (re.match(r'IF\s+SELECTCOM\s*==',s) or s.startswith('@') or s.startswith(';--- COM')): break
        if re.search(r'PRINTFORM[LW]\s*「[^」]*」',L[j]): slot.append(j)
    assert len(slot)==2,(n,com,len(slot))
    for j,new in zip(slot,[koi,tu]): L[j]=re.sub(r'「[^」]*」','「'+new+'」',L[j],count=1)
    nt='\r\n'.join(L); assert '~' not in nt
    open(p,'wb').write(nt.encode('cp932'))

