def validate_lines(text: str) -> None:
    if "私" in text or "俺" in text:
        raise RuntimeError("San file contains forbidden first-person drift")
    if "~" in text:
        raise RuntimeError("San file contains half-width tilde")
    for line in text.splitlines():
        if "PRINTFORMW 「" in line and "」" not in line:
            raise RuntimeError(f"unclosed quote: {line}")
    if text.count("IF ") < text.count("ENDIF"):
        raise RuntimeError("IF/ENDIF count is inverted")


def main() -> None:
    current = SOURCE.read_bytes().decode("cp932")
    if MARKER in current:
        if not BACKUP.exists():
            raise SystemExit("RAND3 marker exists but the San baseline backup is missing")
        text = BACKUP.read_bytes().decode("cp932")
    else:
        text = current
    text = text.replace("\r\n", "\n").replace("\r", "\n")
    lines = text.split("\n")

    standard = sorted(SIMPLE_EXTRA)
    equipment = sorted(EQUIP_EXTRA)
    custom = sorted(CUSTOM_EXTRA)
    for number in standard:
        add_rand_standard(lines, number)
    for number in equipment:
        add_rand_equipment(lines, number)
    for number in custom:
        add_rand_custom(lines, number)

    # The first RETURN 0 after COM17 closes @KOJO_MESSAGE_COM_57.  New
    # SELECTCOM branches must be before that return; putting them after a
    # later orgasm label would leave them unreachable.
    com17 = command_start(lines, 17)
    return_index = next(i for i in range(com17, len(lines)) if lines[i] == "RETURN 0")
    lines[return_index:return_index] = ["", *render_additional()]
    result = "\n".join(lines).replace("\n\n\n", "\n\n")
    validate_lines(result)
    SOURCE.write_bytes(result.replace("\n", "\r\n").encode("cp932"))
    print(
        f"updated {SOURCE} | standard={len(standard)} equipment={len(equipment)} "
        f"custom={len(custom)} additional={len(ADDITIONAL10)}"
    )


if __name__ == "__main__":
    main()
