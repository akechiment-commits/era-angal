def command_end(lines: list[str], start: int) -> int:
    depth = 1
    for i in range(start + 1, len(lines)):
        stripped = lines[i].lstrip()
        if stripped.startswith("ELSEIF SELECTCOM") and depth == 1:
            return i
        if stripped.startswith("IF "):
            depth += 1
        elif stripped == "ENDIF":
            depth -= 1
            if depth == 0:
                return i + 1
    raise RuntimeError(f"SELECTCOM at line {start + 1} has no end")


def if_end(lines: list[str], start: int) -> int:
    depth = 1
    for i in range(start + 1, len(lines)):
        stripped = lines[i].lstrip()
        if stripped.startswith("IF "):
            depth += 1
        elif stripped == "ENDIF":
            depth -= 1
            if depth == 0:
                return i + 1
    raise RuntimeError(f"IF at line {start + 1} has no end")


def if_else(lines: list[str], start: int, end: int) -> int:
    depth = 1
    for i in range(start + 1, end):
        stripped = lines[i].lstrip()
        if stripped.startswith("IF "):
            depth += 1
        elif stripped == "ELSE" and depth == 1:
            return i
        elif stripped == "ENDIF":
            depth -= 1
    raise RuntimeError(f"IF at line {start + 1} has no matching ELSE")


