def read_lines() -> list[str]:
    return TARGET.read_bytes().decode("cp932").splitlines()


def write_lines(lines: list[str]) -> None:
    TARGET.write_bytes("\r\n".join(lines).encode("cp932") + b"\r\n")


def select_ranges(lines: list[str]) -> dict[int, tuple[int, int]]:
    starts: list[tuple[int, int]] = []
    for index, line in enumerate(lines):
        if line.startswith("IF SELECTCOM ==") or line.startswith("ELSEIF SELECTCOM =="):
            starts.append((index, int(line.split("==", 1)[1].strip())))
    return {
        command: (start, starts[pos + 1][0] if pos + 1 < len(starts) else len(lines))
        for pos, (start, command) in enumerate(starts)
    }


def print_units(block: list[str], start: int, end: int) -> list[list[int]]:
    units: list[list[int]] = []
    index = start
    while index < end:
        if re.search(r"PRINTFORM[LMW]\s+「", block[index]):
            unit = [index]
            if "PRINTFORML" in block[index] and index + 1 < end and "PRINTFORMW" in block[index + 1]:
                unit.append(index + 1)
            units.append(unit)
            index = unit[-1] + 1
        else:
            index += 1
    return units


def wrap_one(block: list[str], start: int, end: int, extra1: str, extra2: str) -> list[str]:
    units = print_units(block, start, end)
    if len(units) != 1:
        raise RuntimeError(f"対象分岐の台詞数が不正です: {units}")
    unit = units[0]
    first = block[unit[0]]
    indent = first[: len(first) - len(first.lstrip())]
    replacement = [
        indent + "IF A == 0",
        indent + "\t" + first.lstrip(),
        indent + "ELSEIF A == 1",
        indent + "\tPRINTFORMW " + extra1,
        indent + "ELSE",
        indent + "\tPRINTFORMW " + extra2,
        indent + "ENDIF",
    ]
    block[unit[0] : unit[-1] + 1] = replacement
    return block


def add_simple_rand3(lines: list[str]) -> list[str]:
    for command in sorted(SIMPLE_COMMANDS, reverse=True):
        start, end = select_ranges(lines)[command]
        block = lines[start:end]
        if any("A = RAND:3" in line for line in block):
            continue
        if sum("IF TALENT:TARGET:153" in line for line in block) != 1:
            raise RuntimeError(f"COM{command}の恋人分岐が不正です")
        block.insert(1, "\tA = RAND:3")
        talent = next(i for i, line in enumerate(block) if line == "\tIF TALENT:TARGET:153")
        relation_else = next(i for i in range(talent + 1, len(block)) if block[i] == "\tELSE")
        relation_end = next(i for i in range(relation_else + 1, len(block)) if block[i] == "\tENDIF")
        values = OTHER_VARIANTS[command]
        block = wrap_one(block, talent + 1, relation_else, values[0], values[1])
        talent = next(i for i, line in enumerate(block) if line == "\tIF TALENT:TARGET:153")
        relation_else = next(i for i in range(talent + 1, len(block)) if block[i] == "\tELSE")
        relation_end = next(i for i in range(relation_else + 1, len(block)) if block[i] == "\tENDIF")
        block = wrap_one(block, relation_else + 1, relation_end, values[2], values[3])
        lines[start:end] = block
    return lines


def wrap_equipment_state(block: list[str], state_start: int, values: tuple[str, str, str, str]) -> list[str]:
    talent = next(i for i in range(state_start, len(block)) if block[i] == "\t\tIF TALENT:TARGET:153")
    relation_else = next(i for i in range(talent + 1, len(block)) if block[i] == "\t\tELSE")
    relation_end = next(i for i in range(relation_else + 1, len(block)) if block[i] == "\t\tENDIF")
    block = wrap_one(block, talent + 1, relation_else, values[0], values[1])
    talent = next(i for i in range(state_start, len(block)) if block[i] == "\t\tIF TALENT:TARGET:153")
    relation_else = next(i for i in range(talent + 1, len(block)) if block[i] == "\t\tELSE")
    relation_end = next(i for i in range(relation_else + 1, len(block)) if block[i] == "\t\tENDIF")
    block = wrap_one(block, relation_else + 1, relation_end, values[2], values[3])
