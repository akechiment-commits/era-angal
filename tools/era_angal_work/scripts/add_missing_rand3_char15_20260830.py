        block = lines[start:end]
        if any("A = RAND:3" in line for line in block):
            continue
        on = next(i for i, line in enumerate(block) if line == f"\tIF TEQUIP:{command}")
        off = next(i for i in range(on + 1, len(block)) if block[i] == "\tELSE")
        block.insert(off + 1, "\t\tA = RAND:3")
        block.insert(on + 1, "\t\tA = RAND:3")
        values = EQUIPMENT_VARIANTS[command]
        on = next(i for i, line in enumerate(block) if line == f"\tIF TEQUIP:{command}")
        off = next(i for i in range(on + 1, len(block)) if block[i] == "\tELSE")
        on_end = off
        block = wrap_equipment_state(block, on, values[0:4])
        on = next(i for i, line in enumerate(block) if line == f"\tIF TEQUIP:{command}")
        off = next(i for i in range(on + 1, len(block)) if block[i] == "\tELSE")
        block = wrap_equipment_state(block, off + 1, values[4:8])
