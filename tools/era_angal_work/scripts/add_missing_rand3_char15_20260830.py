def add_com60_assistant(lines: list[str]) -> list[str]:
    start, end = select_ranges(lines)[60]
    block = lines[start:end]
    if not any("CALL AITE_YOBI, 15, ASSI" in line for line in block):
        block[1:1] = ["\tCALL AITE_YOBI, 15, ASSI", "\tLOCALS '= @\"%RESULTS%\"", ""]
    prints = [i for i, line in enumerate(block) if re.search(r"PRINTFORM[LMW]\s+「", line)]
    if len(prints) != 6:
        raise RuntimeError(f"COM60の台詞数が不正です: {len(prints)}")
    for index, replacement in zip(prints, COM60_DIALOGUES):
        indent = block[index][: len(block[index]) - len(block[index].lstrip())]
        block[index] = indent + "PRINTFORMW " + replacement
    lines[start:end] = block
    return lines


