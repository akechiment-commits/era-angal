def main() -> None:
    lines = read_lines()
    before = list(lines)
    lines = add_simple_rand3(lines)
    lines = add_equipment_rand3(lines)
    lines = add_custom_rand3(lines)
    lines = add_com60_assistant(lines)
    lines = fix_viewpoint_meta(lines)
    if lines == before:
        print("変更なし: CHAR15のRAND3・独自10・装着6・COM60助手呼称は既に反映済み")
