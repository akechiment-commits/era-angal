def section_spans(text: str) -> dict[int, tuple[int, int]]:
    headings = list(re.finditer(r"(?m)^(?:IF|ELSEIF) SELECTCOM == (\d+)\s*$", text))
    result: dict[int, tuple[int, int]] = {}
    for index, heading in enumerate(headings):
        end = headings[index + 1].start() if index + 1 < len(headings) else len(text)
        result[int(heading.group(1))] = (heading.start(), end)
    return result


def main() -> int:
    source = SOURCE.read_text(encoding="utf-8-sig")
    if not source.startswith("# しずく（全2689件）"):
        raise RuntimeError("しずく原作テキストのヘッダー確認に失敗しました")

    text = TARGET.read_bytes().decode("cp932").replace("\r\n", "\n")
    for command in sorted(EXTRA10, reverse=True):
        spans = section_spans(text)
        start, end = spans[command]
        block = text[start:end]
        lines = block.split("\n")
        print_indices = [index for index, line in enumerate(lines) if re.match(r"^\s*PRINTFORM(?:L|W)?\b", line)]
        if len(print_indices) != 6:
            raise RuntimeError(f"COM{command}: 既存6枝の検出数が {len(print_indices)} 件です")
        for index, value in zip(print_indices, EXTRA10[command]):
            indent = lines[index][: len(lines[index]) - len(lines[index].lstrip())]
            lines[index] = f'{indent}PRINTFORMW 「{value}」'
        replacement = "\n".join(lines)
        text = text[:start] + replacement + text[end:]

    TARGET.write_bytes(text.replace("\n", "\r\n").encode("cp932"))
    print("CHAR20追加10コマンド再構成完了: COM60/62/76/78/79/84/86/202/258/318")
    return 0


