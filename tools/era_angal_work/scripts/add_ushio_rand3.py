def amplify_existing_cry(text: str) -> str:
    for phrase in AMPLIFY_EXISTING_CRY:
        if text.count(phrase) != 1:
            raise RuntimeError(f"既存口上の泣き声対象が見つからないか重複: {phrase}")
        text = text.replace(phrase, phrase.replace("しくしく", "しくしくしく"))
    return text


