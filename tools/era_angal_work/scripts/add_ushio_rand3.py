def command_start(lines: list[str], number: int) -> int:
    pattern = re.compile(rf"^(?:IF|ELSEIF) SELECTCOM == {number}\s*$")
    found = [i for i, line in enumerate(lines) if pattern.match(line)]
    if len(found) != 1:
        raise RuntimeError(f"SELECTCOM {number}: expected one header, got {len(found)}")
    return found[0]


def command_end(lines: list[str], start: int) -> int:
    depth = 1
    for i in range(start + 1, len(lines)):
        stripped = lines[i].lstrip()
        if stripped.startswith("ELSEIF SELECTCOM") and depth == 1:
            return i
        if stripped.startswith("IF "):
            depth += 1
        elif stripped == "ENDIF":
            depth -= 1
            if depth == 0:
                return i + 1
    raise RuntimeError(f"SELECTCOM at line {start + 1} has no end")


def if_end(lines: list[str], start: int, limit: int | None = None) -> int:
    depth = 1
    stop = len(lines) if limit is None else limit
    for i in range(start + 1, stop):
        stripped = lines[i].lstrip()
        if stripped.startswith("IF "):
            depth += 1
        elif stripped == "ENDIF":
            depth -= 1
            if depth == 0:
                return i + 1
    raise RuntimeError(f"IF at line {start + 1} has no matching ENDIF")


def if_else(lines: list[str], start: int, end: int) -> int:
    depth = 1
    for i in range(start + 1, end):
        stripped = lines[i].lstrip()
        if stripped.startswith("IF "):
            depth += 1
        elif stripped == "ELSE" and depth == 1:
            return i
        elif stripped == "ENDIF":
            depth -= 1
    raise RuntimeError(f"IF at line {start + 1} has no matching ELSE")


def talent_start(lines: list[str], start: int, end: int) -> int:
    found = [
        i for i in range(start, end)
        if re.match(r"^\t+IF TALENT:TARGET:\d+\s*$", lines[i])
    ]
    if len(found) != 1:
        raise RuntimeError(f"expected one TALENT branch at {start + 1}, got {len(found)}")
    return found[0]


def print_statement(lines: list[str], start: int, end: int) -> tuple[int, int]:
    first = next((i for i in range(start, end) if "PRINTFORM" in lines[i]), None)
    if first is None:
        raise RuntimeError(f"no PRINTFORM statement between {start + 1} and {end}")
    last = first
    while "」" not in lines[last] and last + 1 < end:
        last += 1
    if "」" not in lines[last]:
        raise RuntimeError(f"unclosed PRINTFORM statement at line {first + 1}")
    return first, last + 1


def wrap_print_statement(lines: list[str], first: int, last: int, alternatives: tuple[str, str]) -> None:
    old = lines[first:last]
    indent = old[0][: len(old[0]) - len(old[0].lstrip())]
    body = [f"{indent}\t{x.lstrip()}" for x in old]
    alternatives = tuple(soften_line(x) for x in alternatives)
    lines[first:last] = [
        f"{indent}IF A == 0",
        *body,
        f"{indent}ELSEIF A == 1",
        f'{indent}\tPRINTFORMW 「{alternatives[0]}」',
        f"{indent}ELSE",
        f'{indent}\tPRINTFORMW 「{alternatives[1]}」',
        f"{indent}ENDIF",
    ]


def wrap_talent(lines: list[str], start: int, end: int, extras: tuple[str, str, str, str]) -> None:
    # 先に通常側を包む。恋人側の位置がずれても再探索する。
    tstart = talent_start(lines, start, end)
    tend = if_end(lines, tstart, end)
    else_index = if_else(lines, tstart, tend)
    first, last = print_statement(lines, else_index + 1, tend - 1)
    wrap_print_statement(lines, first, last, (extras[2], extras[3]))

    end += 6
    tstart = talent_start(lines, start, end)
    tend = if_end(lines, tstart, end)
    else_index = if_else(lines, tstart, tend)
    first, last = print_statement(lines, tstart + 1, else_index)
    wrap_print_statement(lines, first, last, (extras[0], extras[1]))


