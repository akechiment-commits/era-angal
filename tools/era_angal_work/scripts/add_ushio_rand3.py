def validate(text: str) -> None:
    if "あたし" in text or "私" in text or "俺" in text:
        raise RuntimeError("うしお口上に一人称の揺れが混入")
    if "~" in text:
        raise RuntimeError("半角チルダが混入")
    if text.count("IF SELECTCOM ==") != 168:
        raise RuntimeError(f"unexpected SELECTCOM count: {text.count('IF SELECTCOM ==')}")
    if text.count("A = RAND:3") < 200:
        raise RuntimeError("RAND3 additions are incomplete")


def main() -> None:
    current = SOURCE.read_bytes().decode("cp932")
    if not BACKUP.exists():
        raise SystemExit(f"missing backup: {BACKUP}")
    if MARKER in current:
        text = BACKUP.read_bytes().decode("cp932")
    else:
        text = current
    text = amplify_existing_cry(text)
    text = text.replace("\r\n", "\n").replace("\r", "\n")
    lines = text.split("\n")

    for number in sorted(EXTRA):
        add_rand_standard(lines, number)
    for number in sorted(EQUIP_EXTRA):
        add_rand_equipment(lines, number)
    for number in sorted(CUSTOM_EXTRA):
        add_rand_custom(lines, number)

    com17 = command_start(lines, 17)
    return_index = next(i for i in range(com17, len(lines)) if lines[i] == "RETURN 0")
    lines[return_index:return_index] = ["", *render_additional()]
    result = "\n".join(lines)
    validate(result)
    SOURCE.write_bytes(result.replace("\n", "\r\n").encode("cp932"))
    print(
        f"updated {SOURCE} | standard={len(EXTRA)} equipment={len(EQUIP_EXTRA)} "
        f"custom={len(CUSTOM_EXTRA)} additional={len(ADDITIONAL10)}"
    )


if __name__ == "__main__":
    main()
