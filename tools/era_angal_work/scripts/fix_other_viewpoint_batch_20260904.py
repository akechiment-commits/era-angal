def main() -> int:
    BACKUP_DIR.mkdir(parents=True, exist_ok=True)
    changed = 0
    for number, case in CASES.items():
        source = ROOT / "tools/output" / f"{case['source']}.txt"
        if not source.read_text(encoding="utf-8-sig").startswith(f"# {case['source']}（全"):
            raise RuntimeError(f"原作ヘッダー確認失敗: {source}")
        target = next(ROOT.glob(f"ERB/CHAR/CHAR_{number:02d}_*_COM.ERB"))
        backup = BACKUP_DIR / target.name
        if not backup.exists():
            shutil.copy2(target, backup)
        text = target.read_bytes().decode("cp932").replace("\r\n", "\n")
        for old, new in case["rewrites"].items():
            count = text.count(old)
            if count == 0 and text.count(new) == 1:
                continue
            if count != 1:
                raise ValueError(f"CHAR{number:02d}視点置換対象が一意でない: {old!r} ({count})")
            text = text.replace(old, new)
            changed += 1
        target.write_bytes(text.replace("\n", "\r\n").encode("cp932"))
    print(f"その他の視点補正: {changed}件")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
