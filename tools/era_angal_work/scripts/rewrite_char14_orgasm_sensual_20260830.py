def main() -> None:
    lines = read_lines()
    _start, _end, units = orgasm_units(lines)
    if len(units) != len(SENSUAL_DIALOGUES):
        raise RuntimeError(f"絶頂台詞数が不一致です: 実ファイル={len(units)} 予定={len(SENSUAL_DIALOGUES)}")

    BACKUP.parent.mkdir(parents=True, exist_ok=True)
    if not BACKUP.exists():
        shutil.copy2(TARGET, BACKUP)

    for unit, dialogue in reversed(list(zip(units, SENSUAL_DIALOGUES))):
        first = lines[unit[0]]
        indent = first[: len(first) - len(first.lstrip())]
        lines[unit[0]] = indent + "PRINTFORMW " + dialogue
        for index in reversed(unit[1:]):
            del lines[index]
    write_lines(lines)
    print(f"CHAR14絶頂台詞を官能寄りに再改稿: {len(units)}件")


