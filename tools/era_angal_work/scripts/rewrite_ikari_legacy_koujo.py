def replace_com_lines(text: str, com: int, speeches: list[str]) -> str:
    pattern = re.compile(
        rf"(?ms)^IF SELECTCOM == {com}\r\n.*?(?=^IF SELECTCOM == |^;={{20,}}|\Z)"
    )
    match = pattern.search(text)
    if not match:
        raise RuntimeError(f"COM{com} block not found")
    block = match.group(0)
    print_re = re.compile(
        r"(?m)^(\s*)PRINTFORML\s+[^\r\n]*\r?\n\s*PRINTFORMW\s+[^\r\n]*\r?$|^(\s*)PRINTFORMW\s+[^\r\n]*\r?$"
    )
    found = list(print_re.finditer(block))
    if len(found) != len(speeches):
        raise RuntimeError(f"COM{com}: expected {len(speeches)} print lines, found {len(found)}")
    iterator = iter(speeches)
    block = print_re.sub(
        lambda m: f'{m.group(1) or m.group(2)}PRINTFORMW 「{next(iterator)}」', block
    )
    return text[: match.start()] + block + text[match.end() :]


def emit_random_pair(lover: list[str], normal: list[str], indent: str = "") -> list[str]:
    out = [f"{indent}A = RAND:3", f"{indent}IF TALENT:TARGET:153"]
    for i, speech in enumerate(lover):
        branch = "IF A == 0" if i == 0 else ("ELSEIF A == 1" if i == 1 else "ELSE")
        out.extend((f"{indent}\t{branch}", f"{indent}\t\tPRINTFORMW 「{speech}」"))
    out.extend((f"{indent}\tENDIF", f"{indent}ELSE"))
    for i, speech in enumerate(normal):
        branch = "IF A == 0" if i == 0 else ("ELSEIF A == 1" if i == 1 else "ELSE")
        out.extend((f"{indent}\t{branch}", f"{indent}\t\tPRINTFORMW 「{speech}」"))
    out.extend((f"{indent}\tENDIF", f"{indent}ENDIF"))
    return out


def build_ejac_function(name: str, groups: list[list[str]]) -> str:
    if len(groups) != 8 or any(len(group) != 3 for group in groups):
        raise RuntimeError(f"{name}: ejaculation data must be eight groups of three")
    out = [f"@{name}", "; 全面改稿版：量・初回/複数回・恋人/通常を維持", "IF TFLAG:302 >= 2"]
    out.append("\tIF TFLAG:711 == 1")
    out.extend(emit_random_pair(groups[0], groups[1], "\t\t"))
    out.append("\tELSE")
    out.extend(emit_random_pair(groups[2], groups[3], "\t\t"))
