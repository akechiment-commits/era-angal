def main() -> None:
    text = PATH.read_bytes().decode("cp932")
    missing = []
    for old, new in REWRITES.items():
        count = text.count(old)
        if count == 0:
            continue
        if count != 1:
            missing.append((old, count))
            continue
        text = text.replace(old, new, 1)
    if missing:
        raise RuntimeError(f"置換対象の出現数が不一致: {missing[:5]}（合計{len(missing)}件）")
    PATH.write_bytes(text.encode("cp932"))
    print(f"CHAR07: 呼称始まりを個別リライト {len(REWRITES)}件")


if __name__ == "__main__":
    main()
