def header_span(text: str, command: int, lower: int = 0, upper: int | None = None) -> tuple[int, int]:
    upper = len(text) if upper is None else upper
    pattern = re.compile(rf"^;--- COM{command}(?:\s|$)", re.MULTILINE)
    match = pattern.search(text, lower, upper)
    if not match:
        raise ValueError(f"CHAR25のCOM{command}見出しが見つかりません")
    next_heading = re.search(r"^;--- COM", text[match.end():upper], re.MULTILINE)
    end = match.end() + next_heading.start() if next_heading else upper
    next_return = re.search(r"^RETURN 0\s*$", text[match.end():end], re.MULTILINE)
    if next_return:
        end = match.end() + next_return.start()
    return match.start(), end


def print_text(line: str) -> str:
    match = re.match(r"^\s*PRINTFORM(?:L|W)?\s+(.*)$", line)
    if not match:
        raise ValueError(f"PRINTFORMWを読めません: {line!r}")
    return match.group(1)


