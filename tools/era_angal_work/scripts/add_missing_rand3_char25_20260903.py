def expand_standard(text: str) -> str:
    lower = text.index("; その他コマンド（恋人/通常 各1行）")
    upper = text.index(";==============================================================\n; 装着アイテム", lower)
    for command in STANDARD_TARGETS:
        start, end = header_span(text, command, lower, upper)
        block = text[start:end]
        selector = re.search(r"^IF SELECTCOM == \d+\s*$", block, re.MULTILINE)
        if not selector:
            raise ValueError(f"CHAR25 COM{command}のSELECTCOMが見つかりません")
        prints = [line for line in block[selector.end():].splitlines() if re.match(r"^\s*PRINTFORM(?:L|W)?\s+", line)]
        if len(prints) != 2:
            raise ValueError(f"CHAR25 COM{command}の一行分岐が2台詞ではありません: {len(prints)}")
        lover0, normal0 = map(print_text, prints)
        lover1, lover2, normal1, normal2 = STANDARD_VARIANTS[command]
        prefix = block[:selector.start()]
        new_block = prefix + f"IF SELECTCOM == {command}\n" + rand3_relation(lover0, lover1, lover2, normal0, normal1, normal2) + "\nENDIF\n"
        text = text[:start] + new_block + text[end:]
        upper += len(new_block) - len(block)
    return text


def custom_segment(text: str, command: int, lower: int, upper: int) -> tuple[int, int]:
    pattern = re.compile(rf"^(?:IF|ELSEIF) SELECTCOM == {command}\s*$", re.MULTILINE)
    match = pattern.search(text, lower, upper)
    if not match:
        raise ValueError(f"CHAR25独自COM{command}のSELECTCOMが見つかりません")
    next_selector = re.search(r"^(?:ELSEIF|ENDIF) SELECTCOM ==", text[match.end():upper], re.MULTILINE)
    # ELSEIF SELECTCOM は上の正規表現では拾えるが、最後のENDIFは拾わない。
    next_command = re.search(r"^ELSEIF SELECTCOM ==", text[match.end():upper], re.MULTILINE)
    if next_command:
        return match.start(), match.end() + next_command.start()
    end_outer = re.search(r"^ENDIF\s*$", text[match.end():upper], re.MULTILINE)
    if not end_outer:
        raise ValueError(f"CHAR25独自COM{command}の終端が見つかりません")
    return match.start(), match.end() + end_outer.end()


def custom_relation(lines: list[str], talent_index: int, variants: tuple[str, str, str, str]) -> str:
    try:
        normal_index = next(i for i in range(talent_index + 1, len(lines)) if lines[i].strip() == "ELSE")
        end_index = next(i for i in range(normal_index + 1, len(lines)) if lines[i].strip() == "ENDIF")
    except StopIteration as exc:
        raise ValueError("CHAR25独自COMの関係分岐を読めません") from exc

    def old_prints(start: int, end: int) -> list[str]:
        return [line.strip() for line in lines[start:end] if re.match(r"^\s*PRINTFORM(?:L|W)?\s+", line)]

    lover_old = old_prints(talent_index + 1, normal_index)
    normal_old = old_prints(normal_index + 1, end_index)
    if not lover_old or not normal_old:
        raise ValueError("CHAR25独自COMの既存台詞が空です")

    lover1, lover2, normal1, normal2 = variants

    def old_lines(values: list[str]) -> list[str]:
        return [f"\t\t\t{value}" for value in values]

    result = [
        "\tIF TALENT:TARGET:153",
        "\t\tA = RAND:3",
        "\t\tIF A == 0",
        *old_lines(lover_old),
        "\t\tELSEIF A == 1",
        f"\t\t\tPRINTFORMW {lover1}",
        "\t\tELSE",
        f"\t\t\tPRINTFORMW {lover2}",
        "\t\tENDIF",
        "\tELSE",
        "\t\tA = RAND:3",
        "\t\tIF A == 0",
        *old_lines(normal_old),
        "\t\tELSEIF A == 1",
        f"\t\t\tPRINTFORMW {normal1}",
        "\t\tELSE",
        f"\t\t\tPRINTFORMW {normal2}",
        "\t\tENDIF",
        "\tENDIF",
    ]
    return "\n".join(result)


def expand_custom_group(text: str, first: int, last: int) -> str:
    lower = text.index(f";--- COM{first}-{last}")
    upper = text.index(";--- COM", lower + 1)
    group = text[lower:upper]
    trailing_newline = group.endswith("\n")
    lines = group.splitlines()
    selectors = [
        (index, int(match.group(1)))
        for index, line in enumerate(lines)
        if (match := re.match(r"^(?:IF|ELSEIF) SELECTCOM == ([0-9]+)\s*$", line.strip()))
        and first <= int(match.group(1)) <= last
    ]
    if len(selectors) != last - first + 1:
        raise ValueError(f"CHAR25独自COM{first}-{last}のSELECTCOM数が不正です: {len(selectors)}")
    for position in range(len(selectors) - 1, -1, -1):
        start, command = selectors[position]
        end = selectors[position + 1][0] if position + 1 < len(selectors) else len(lines)
        segment = lines[start:end]
        talent_index = next(i for i, line in enumerate(segment) if line.strip() == "IF TALENT:TARGET:153")
        prefix = segment[:talent_index]
        replacement = prefix + custom_relation(segment, talent_index, CUSTOM_VARIANTS[command]).splitlines()
        if position == len(selectors) - 1:
            replacement.append("ENDIF")
        lines[start:end] = replacement
    rebuilt = "\n".join(lines)
    if trailing_newline:
        rebuilt += "\n"
    return text[:lower] + rebuilt + text[upper:]


