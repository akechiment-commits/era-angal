def equipment_relation(on_lover: str, on_normal: str, off_lover: str, off_normal: str, variants: dict[str, tuple[str, str]]) -> str:
    def three(old: str, extra: tuple[str, str]) -> list[str]:
        return [
            "\t\t\tIF A == 0",
            f"\t\t\t\tPRINTFORMW {old}",
            "\t\t\tELSEIF A == 1",
            f"\t\t\t\tPRINTFORMW {extra[0]}",
            "\t\t\tELSE",
            f"\t\t\t\tPRINTFORMW {extra[1]}",
            "\t\t\tENDIF",
        ]

    def state(old_lover: str, old_normal: str, key: str) -> list[str]:
        return [
            "\tIF TALENT:TARGET:153",
            *three(old_lover, variants[f"{key}_lover"]),
            "\tELSE",
            *three(old_normal, variants[f"{key}_normal"]),
            "\tENDIF",
        ]

    return "\n".join(
        [
            "\tA = RAND:3",
            "\tIF TEQUIP:CURRENT",
            *state(on_lover, on_normal, "on"),
            "\tELSE",
            *state(off_lover, off_normal, "off"),
            "\tENDIF",
        ]
    ).replace("TEQUIP:CURRENT", "TEQUIP:__COMMAND__")


def expand_equipment(text: str) -> str:
    lower = text.index(";--- COM11 バイブ")
    upper = text.index(";=== TSUYURI MISSING COMMAND TRIAL START ===")
    for command, variants in EQUIPMENT_VARIANTS.items():
        start, end = header_span(text, command, lower, upper)
        block = text[start:end]
        selector = re.search(r"^IF SELECTCOM == \d+\s*$", block, re.MULTILINE)
        if not selector:
            raise ValueError(f"CHAR25装着COM{command}のSELECTCOMが見つかりません")
        prints = [print_text(line) for line in block[selector.end():].splitlines() if re.match(r"^\s*PRINTFORM(?:L|W)?\s+", line)]
        if len(prints) != 4:
            raise ValueError(f"CHAR25装着COM{command}の既存台詞数が4ではありません: {len(prints)}")
        prefix = block[:selector.start()]
        body = equipment_relation(prints[0], prints[1], prints[2], prints[3], variants)
        body = body.replace("__COMMAND__", str(command))
        new_block = prefix + f"IF SELECTCOM == {command}\n" + body + "\nENDIF\n"
        text = text[:start] + new_block + text[end:]
        upper += len(new_block) - len(block)
    return text


