ALREADY_REWRITTEN = {
    "「ダーリンがわたしを見ながら触ると、手伝ってないのに一緒にしてる気分になるね」":
    "「手を動かすダーリンを見てると、わたしの名前を呼ばせたくなるなぁ。ね、目を合わせたまま続けて？」",
}


def main() -> int:
    text = TARGET.read_bytes().decode("cp932").replace("\r\n", "\n")
    for old, new in REWRITES.items():
        count = text.count(old)
        if count == 0 and text.count(new) == 1:
            continue
        if count == 0 and text.count(ALREADY_REWRITTEN.get(old, "")) == 1:
            text = text.replace(ALREADY_REWRITTEN[old], new)
            continue
        if count != 1:
            raise ValueError(f"CHAR24置換対象が一意でない: {old!r} ({count})")
        text = text.replace(old, new)
    TARGET.write_bytes(text.replace("\n", "\r\n").encode("cp932"))
    print("CHAR24: COM60助手呼称とCOM131視点を補正")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
