def shorten_ichika(value: str) -> str:
    """いちかの原作にない間延びした定型を、短い原作寄りの語尾へ整える。"""
    for old, new in (
        ("なっちゃいます", "なります"),
        ("しちゃいます", "します"),
        ("ですねぇ", "ですね"),
        ("ですね～", "ですね"),
        ("ですよぉ～っ", "ですよ"),
        ("ですよぉ", "ですよ"),
        ("ですぅ～っ", "です"),
        ("ですぅ", "です"),
        ("です～っ", "です"),
        ("です～", "です"),
        ("ます～っ", "ます"),
        ("ます～", "ます"),
        ("ねぇ", "ね"),
        ("ね～", "ね"),
    ):
        value = value.replace(old, new)
    return value


def shorten_existing_text(lines: list[str]) -> None:
    """原作にない、CHAR12既存文の過剰な間延び定型だけを短くする。"""
    replacements = (
        ("なっちゃいます", "なります"),
        ("しちゃいます", "します"),
        ("ですよぉ～っ", "ですよ"),
        ("ですよぉ～", "ですよ"),
        ("ですよぉ", "ですよ"),
        ("ですぅ～っ", "です"),
        ("ですぅ", "です"),
        ("ですねぇ", "ですね"),
        ("です～っ", "です"),
        ("です～", "です"),
        ("ます～っ", "ます"),
        ("ます～", "ます"),
        ("ですっ", "です"),
        ("ますっ", "ます"),
        ("ですよっ", "ですよ"),
    )
    for index, line in enumerate(lines):
        for old, new in replacements:
            line = line.replace(old, new)
        lines[index] = line


