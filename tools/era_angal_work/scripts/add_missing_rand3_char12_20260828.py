def find_end(lines: list[str], start: int) -> int:
    depth = 0
    for index in range(start, len(lines)):
        stripped = lines[index].strip()
        if re.match(r"^IF(?:\s|\()", stripped):
            depth += 1
        elif stripped == "ENDIF":
            depth -= 1
            if depth == 0:
                return index + 1
    raise RuntimeError(f"ENDIF not found: line {start + 1}")


def relation_lines(
    love_original: list[str],
    normal_original: list[str],
    additions: tuple[str, ...],
    base: str,
) -> list[str]:
    love1, love2, normal1, normal2 = additions
    keep = lambda value: [base + "\t\t" + line.strip() for line in value if line.strip()]
    return [
        base + "IF TALENT:TARGET:153",
        base + "\tIF A == 0",
        *keep(love_original),
        base + "\tELSEIF A == 1",
        base + f"\t\tPRINTFORMW {love1}",
        base + "\tELSE",
        base + f"\t\tPRINTFORMW {love2}",
        base + "\tENDIF",
        base + "ELSE",
        base + "\tIF A == 0",
        *keep(normal_original),
        base + "\tELSEIF A == 1",
        base + f"\t\tPRINTFORMW {normal1}",
        base + "\tELSE",
        base + f"\t\tPRINTFORMW {normal2}",
        base + "\tENDIF",
        base + "ENDIF",
    ]


def rewrite_rand3_branches(block: list[str], additions: tuple[str, ...]) -> list[str]:
    if len(additions) != 4:
        raise RuntimeError(f"RAND3追加文の数が不正です: {len(additions)}")
    result = list(block)
    relation = -1
    active: tuple[int, int, str] | None = None
    replaced_branches: set[tuple[int, int]] = set()
    replaced = 0
    for index, line in enumerate(block):
        if re.match(r"^\t+IF A == 0$", line):
            relation += 1
            match = re.match(r"^(\t+)IF A == 0$", line)
            active = (relation, 0, match.group(1))
        elif active and (match := re.match(r"^(\t+)ELSEIF A == 1$", line)) and match.group(1) == active[2]:
            active = (active[0], 1, active[2])
        elif active and line == active[2] + "ELSE":
            active = (active[0], 2, active[2])
        elif active and active[1] in (1, 2) and "PRINTFORM" in line:
            relation_index, branch, indent = active
            if (relation_index, branch) in replaced_branches:
                continue
            offset = relation_index * 2 + branch - 1
            if offset >= len(additions):
                raise RuntimeError(f"RAND3分岐位置が不正です: relation={relation_index}, branch={branch}")
            result[index] = indent + "\tPRINTFORMW " + additions[offset]
            replaced_branches.add((relation_index, branch))
            replaced += 1
    if replaced != len(additions):
        raise RuntimeError(f"RAND3追加文の置換数が不一致です: expected={len(additions)}, actual={replaced}")
    return result


def rewrite_simple(lines: list[str], command: int, additions: tuple[str, ...]) -> None:
    starts = [i for i, line in enumerate(lines) if line == f"IF SELECTCOM == {command}"]
    if len(starts) != 1:
        raise RuntimeError(f"COM{command}: SELECTCOM blocks={len(starts)}")
    start = starts[0]
    end = find_end(lines, start)
    block = lines[start:end]
    if any("A = RAND:3" in line for line in block):
        lines[start:end] = rewrite_rand3_branches(block, additions)
        return
    talent = next(i for i, line in enumerate(block) if line.strip() == "IF TALENT:TARGET:153")
    talent_end = find_end(block, talent)
    relation_else = next(i for i in range(talent + 1, talent_end) if block[i].strip() == "ELSE")
    love = block[talent + 1 : relation_else]
    normal = block[relation_else + 1 : talent_end - 1]
    if not any("PRINTFORM" in line for line in love) or not any("PRINTFORM" in line for line in normal):
        raise RuntimeError(f"COM{command}: relation PRINTFORM missing")
    replacement = block[:talent] + ["\tA = RAND:3"]
    replacement.extend(relation_lines(love, normal, additions, "\t"))
    replacement.extend(block[talent_end:])
    lines[start:end] = replacement


def rewrite_equipment(lines: list[str], command: int, states: dict[str, tuple[str, ...]]) -> None:
    starts = [i for i, line in enumerate(lines) if line == f"IF SELECTCOM == {command}"]
    if len(starts) != 1:
        raise RuntimeError(f"COM{command}: SELECTCOM blocks={len(starts)}")
    start = starts[0]
    end = find_end(lines, start)
    block = lines[start:end]
    on_start = next(i for i, line in enumerate(block) if line == f"\tIF TEQUIP:{command}")
    outer_end = find_end(block, on_start)
    state_else = next(i for i in range(on_start + 1, outer_end) if block[i] == "\tELSE")
    state_blocks = {
        "on": block[on_start:state_else],
        "off": block[state_else:outer_end],
    }
    for key in ("off", "on"):
        state_block = state_blocks[key]
        if any("A = RAND:3" in line for line in state_block):
            state_blocks[key] = rewrite_rand3_branches(state_block, states[key])
            continue
        talent = next(i for i, line in enumerate(state_block) if line.strip() == "IF TALENT:TARGET:153")
        talent_end = find_end(state_block, talent)
        relation_else = next(i for i in range(talent + 1, talent_end) if state_block[i].strip() == "ELSE")
        love = state_block[talent + 1 : relation_else]
        normal = state_block[relation_else + 1 : talent_end - 1]
        replacement = state_block[:talent] + ["\t\tA = RAND:3"]
        replacement.extend(relation_lines(love, normal, states[key], "\t\t"))
        replacement.extend(state_block[talent_end:])
        state_blocks[key] = replacement
    block[on_start:state_else] = state_blocks["on"]
    shift = len(state_blocks["on"]) - (state_else - on_start)
    off_start = state_else + shift
    block[off_start:outer_end + shift] = state_blocks["off"]
    lines[start:end] = block


def rewrite_custom_scene(block: list[str], additions: tuple[str, ...]) -> list[str]:
    talent = next(i for i, line in enumerate(block) if line.strip() == "IF TALENT:TARGET:153")
    talent_end = find_end(block, talent)
    relation_else = next(i for i in range(talent + 1, talent_end) if block[i].strip() == "ELSE")
    love = block[talent + 1 : relation_else]
    normal = block[relation_else + 1 : talent_end - 1]
    prefix = [line for line in block[:talent] if line.strip() != "A = RAND:3"] + ["\tA = RAND:3"]
    prefix.extend(relation_lines(love, normal, additions, "\t"))
    prefix.extend(block[talent_end:])
    return prefix


def rewrite_custom(lines: list[str]) -> None:
    section_start = next(i for i, line in enumerate(lines) if line == ";--- COM280-284 独自ウフフ ---")
    section_end = next(i for i in range(section_start + 1, len(lines)) if lines[i] == ";==============================================================")
    if not any(re.match(r"^(?:IF|ELSEIF) SELECTCOM == \d+$", lines[i]) for i in range(section_start, section_end)):
        raise RuntimeError("custom SELECTCOM blocks not found")
    selectors = [
        i
        for i in range(section_start, section_end)
        if re.match(r"^(?:IF|ELSEIF) SELECTCOM == \d+$", lines[i])
    ]
    blocks = [
        lines[start : (selectors[pos + 1] if pos + 1 < len(selectors) else section_end)]
        for pos, start in enumerate(selectors)
    ]
    clean = len(selectors) == 10 and all(block.count("\tA = RAND:3") == 1 for block in blocks)
    cursor = section_start
    while cursor < section_end:
        if not re.match(r"^(?:IF|ELSEIF) SELECTCOM == \d+$", lines[cursor]):
            cursor += 1
            continue
        start = cursor
        end = next(
            (i for i in range(start + 1, section_end) if re.match(r"^(?:IF|ELSEIF) SELECTCOM == \d+$", lines[i])),
            section_end,
        )
        command = int(re.search(r"(\d+)$", lines[start]).group(1))
        scene = lines[start:end]
        replacement = rewrite_rand3_branches(scene, CUSTOM_VARIANTS[command]) if clean else rewrite_custom_scene(scene, CUSTOM_VARIANTS[command])
        lines[start:end] = replacement
        section_end += len(replacement) - (end - start)
        cursor = start + len(replacement)


def add_custom_annotations(lines: list[str]) -> None:
    section_start = next(i for i, line in enumerate(lines) if line == ";--- COM280-284 独自ウフフ ---")
    section_end = next(i for i in range(section_start + 1, len(lines)) if lines[i] == ";==============================================================")
    selectors = [
        i
        for i in range(section_start, section_end)
        if re.match(r"^(?:IF|ELSEIF) SELECTCOM == \d+$", lines[i])
    ]
    for start in reversed(selectors):
        command = int(re.search(r"(\d+)$", lines[start]).group(1))
        if start > 0 and lines[start - 1] == CUSTOM_ANNOTATIONS[command]:
            continue
        lines[start:start] = [CUSTOM_ANNOTATIONS[command]]


