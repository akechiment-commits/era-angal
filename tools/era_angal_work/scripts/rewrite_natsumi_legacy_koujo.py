def build_custom_chain(data: dict[int, tuple[list[str], list[str]]]) -> str:
    out: list[str] = []
    for i, com in enumerate(sorted(data)):
        out.append(f"{'IF' if i == 0 else 'ELSEIF'} SELECTCOM == {com}")
        lover, normal = data[com]
        out.extend(emit_random_pair(lover, normal, "\t"))
    out.append("ENDIF")
    return "\r\n".join(out)


def build_ejac_function(name: str, groups: list[list[str]]) -> str:
    if len(groups) != 8 or any(len(group) != 3 for group in groups):
        raise RuntimeError(f"{name}: ejaculation data must be eight groups of three")
    out = [f"@{name}", "; 全面改稿版：量・初回/複数回・恋人/通常を維持", "IF TFLAG:302 >= 2", "\tIF TFLAG:711 == 1"]
    out.extend(emit_random_pair(groups[0], groups[1], "\t\t"))
    out.append("\tELSE")
    out.extend(emit_random_pair(groups[2], groups[3], "\t\t"))
    out.extend(("\tENDIF", "ELSE", "\tIF TFLAG:711 == 1"))
    out.extend(emit_random_pair(groups[4], groups[5], "\t\t"))
    out.append("\tELSE")
    out.extend(emit_random_pair(groups[6], groups[7], "\t\t"))
    out.extend(("\tENDIF", "ENDIF", "RETURN 0"))
    return "\r\n".join(out)


def build_orgasm_function() -> str:
    any_max = "NOWEX:0 >= 9 || NOWEX:1 >= 9 || NOWEX:2 >= 9 || NOWEX:3 >= 9 || NOWEX:6 >= 9"
    any_strong = "NOWEX:0 >= 2 || NOWEX:1 >= 2 || NOWEX:2 >= 2 || NOWEX:3 >= 2 || NOWEX:6 >= 2"
    all_max = "NOWEX:0 >= 9 && NOWEX:1 >= 9 && NOWEX:2 >= 9 && NOWEX:3 >= 9 && NOWEX:6 >= 9"

    def add_strength_chain(indent: str, tiers: list[tuple[str | None, str]]) -> None:
        for i, (condition, key) in enumerate(tiers):
            if condition is None:
                out.append(f"{indent}ELSE")
            else:
                out.append(f"{indent}{'IF' if i == 0 else 'ELSEIF'} {condition}")
            out.extend(emit_random_pair(*ORGASM_DATA[key], indent + "\t"))
        out.append(f"{indent}ENDIF")

    out = [
        "@CHAR_ORGASM_24",
        "; 全面改稿版：元の150枠（五重24＋複36＋単部位90）と強度勾配を維持",
        ";--- 五重絶頂 ---",
        "IF TFLAG:710 >= 5",
    ]
    add_strength_chain("\t", [
        (all_max, "five_ultimate"),
        (any_max, "five_strongest"),
        (any_strong, "five_strong"),
        (None, "five_normal"),
    ])

    out.extend((";--- 複絶頂 ---", "ELSEIF TFLAG:710 >= 2", "\tIF NOWEX:1 > 0"))
    add_strength_chain("\t\t", [
        (any_max, "multi_v_strongest"),
        (any_strong, "multi_v_strong"),
        (None, "multi_v_normal"),
    ])
    out.append("\tELSE")
    add_strength_chain("\t\t", [
        (any_max, "multi_other_strongest"),
        (any_strong, "multi_other_strong"),
        (None, "multi_other_normal"),
    ])
    out.append("\tENDIF")

    out.extend((";--- 単独部位絶頂 ---", "ELSE", "\tIF NOWEX:1 > 0"))
    single_parts = [
        (1, "v"),
        (2, "a"),
        (0, "c"),
        (3, "b"),
        (6, "m"),
    ]
    for i, (nowex, prefix) in enumerate(single_parts):
        if i:
            out.append(f"\tELSEIF NOWEX:{nowex} > 0" if i < len(single_parts) - 1 else "\tELSE")
        add_strength_chain("\t\t", [
            (f"NOWEX:{nowex} >= 9", f"{prefix}_strongest"),
            (f"NOWEX:{nowex} >= 2", f"{prefix}_strong"),
            (None, f"{prefix}_normal"),
        ])
    out.extend(("\tENDIF", "ENDIF", "RETURN 0"))
    return "\r\n".join(out)


def replace_function(text: str, name: str, replacement: str) -> str:
    pattern = re.compile(rf"(?ms)^@{name}\r\n.*?^RETURN 0\r\n")
    match = pattern.search(text)
    if not match:
        raise RuntimeError(f"function not found: {name}")
    return text[:match.start()] + replacement + "\r\n" + text[match.end():]


def trial_block(text: str) -> str:
    start_marker = ";=== NATSUMI MISSING COMMAND TRIAL START ==="
    end_marker = ";=== NATSUMI MISSING COMMAND TRIAL END ==="
    start = text.index(start_marker)
    end = text.index(end_marker, start) + len(end_marker)
    return text[start:end]


def ensure_viewpoint_notes(text: str) -> str:
    notes = {
        302: ";▼【視点】キャラ受け＝プレイヤーがキャラへプレゼントを渡し、キャラが受け取る側",
        303: ";▼【視点】キャラ受け＝プレイヤーがキャラへスキンシップを行う",
        306: ";▼【視点】キャラ受け＝プレイヤーがキャラの髪へ手櫛を入れる",
        307: ";▼【視点】キャラ受け＝プレイヤーがキャラの髪を櫛で梳かす",
        311: ";▼【視点】キャラ受け＝プレイヤーがキャラへ甘い言葉をかけ、キャラが受け止める側",
        312: ";▼【視点】キャラ受け＝プレイヤーがキャラの頭を撫でる",
        316: ";▼【視点】キャラ奉仕＝キャラがプレイヤーの髪を梳く",
    }
    for com, note in notes.items():
        header = re.compile(rf"(?m)^(;--- COM{com}\b[^\r\n]*\r\n)")
        match = header.search(text)
        if not match:
            raise RuntimeError(f"COM{com} header not found for viewpoint annotation")
        after = match.end()
        if text.startswith(note + "\r\n", after):
            continue
        text = text[:after] + note + "\r\n" + text[after:]
    return text


def main() -> None:
    text = TARGET.read_bytes().decode("cp932")
    preserved_trial = trial_block(text)
    simple = set(SIMPLE_EXTRAS)
    equipment = set(EQUIP_EXTRAS)
    for com, speeches in COM_LINES.items():
        if com not in simple and com not in equipment:
            text = replace_com_lines(text, com, speeches)
    for com in sorted(simple):
        text = replace_com_block(text, com, build_simple_com(com))
    for com in sorted(equipment):
        text = replace_com_block(text, com, build_equipment_com(com))
    text = replace_com_block(text, 280, build_ufufu_block(), "COM410")
    text = replace_com_block(text, 410, build_custom_chain(PURE_CUSTOM_LINES))
    for name, groups in EJAC_DATA.items():
        text = replace_function(text, name, build_ejac_function(name, groups))
    text = replace_function(text, "CHAR_ORGASM_24", build_orgasm_function())
    text = ensure_viewpoint_notes(text)
    if trial_block(text) != preserved_trial:
        raise RuntimeError("newly added ten-command trial block changed unexpectedly")
    text = text.replace("\r\n", "\n").replace("\r", "\n").replace("\n", "\r\n")
    TARGET.write_bytes(text.encode("cp932"))


if __name__ == "__main__":
    main()
