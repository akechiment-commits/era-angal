def replace_com_lines(text: str, com: int, speeches: list[str]) -> str:
    pattern = re.compile(rf"(?ms)^IF SELECTCOM == {com}\r\n.*?(?=^IF SELECTCOM == |^;={{20,}}|\Z)")
    match = pattern.search(text)
    if not match:
        raise RuntimeError(f"COM{com} block not found")
    block = match.group(0)
    print_re = re.compile(
        r"(?m)^(\s*)PRINTFORML\s+[^\r\n]*\r?\n\s*PRINTFORMW\s+[^\r\n]*\r?$|^(\s*)PRINTFORMW\s+[^\r\n]*\r?$"
    )
    found = list(print_re.finditer(block))
    if len(found) != len(speeches):
        raise RuntimeError(f"COM{com}: expected {len(speeches)} print lines, found {len(found)}")
    iterator = iter(speeches)
    block = print_re.sub(lambda m: f'{m.group(1) or m.group(2)}PRINTFORMW 「{next(iterator)}」', block)
    return text[:match.start()] + block + text[match.end():]


def replace_com_block(text: str, com: int, replacement: str, next_label: str = "COM") -> str:
    pattern = re.compile(rf"(?ms)^IF SELECTCOM == {com}\r\n.*?(?=\r\n;--- |\r\n;===|\Z)")
    match = pattern.search(text)
    if not match:
        raise RuntimeError(f"COM{com} outer block not found")
    return text[:match.start()] + replacement + "\r\n" + text[match.end():]


def emit_rand3(speeches: list[str], indent: str) -> list[str]:
    if len(speeches) != 3:
        raise RuntimeError("RAND branch must contain exactly three speeches")
    return [
        f"{indent}IF A == 0", f"{indent}\tPRINTFORMW 「{speeches[0]}」",
        f"{indent}ELSEIF A == 1", f"{indent}\tPRINTFORMW 「{speeches[1]}」",
        f"{indent}ELSE", f"{indent}\tPRINTFORMW 「{speeches[2]}」", f"{indent}ENDIF",
    ]


def emit_random_pair(lover: list[str], normal: list[str], indent: str = "") -> list[str]:
    out = [f"{indent}A = RAND:3", f"{indent}IF TALENT:TARGET:153"]
    out.extend(emit_rand3(lover, indent + "\t"))
    out.append(f"{indent}ELSE")
    out.extend(emit_rand3(normal, indent + "\t"))
    out.append(f"{indent}ENDIF")
    return out


def build_simple_com(com: int) -> str:
    base = COM_LINES[com]
    if len(base) != 2:
        raise RuntimeError(f"COM{com}: simple base must contain two speeches")
    lover_extra, normal_extra = SIMPLE_EXTRAS[com]
    out = [f"IF SELECTCOM == {com}"]
    out.extend(emit_random_pair([base[0], *lover_extra], [base[1], *normal_extra], "\t"))
    out.append("ENDIF")
    return "\r\n".join(out)


def build_equipment_com(com: int) -> str:
    base = COM_LINES[com]
    if len(base) != 4:
        raise RuntimeError(f"COM{com}: equipment base must contain four speeches")
    il, inn, rl, rn = EQUIP_EXTRAS[com]
    out = [f"IF SELECTCOM == {com}", "\tA = RAND:3", f"\tIF TEQUIP:{com}", "\t\tIF TALENT:TARGET:153"]
    out.extend(emit_rand3([base[0], *il], "\t\t\t"))
    out.append("\t\tELSE")
    out.extend(emit_rand3([base[1], *inn], "\t\t\t"))
    out.extend(("\t\tENDIF", "\tELSE", "\t\tIF TALENT:TARGET:153"))
    out.extend(emit_rand3([base[2], *rl], "\t\t\t"))
    out.append("\t\tELSE")
    out.extend(emit_rand3([base[3], *rn], "\t\t\t"))
    out.extend(("\t\tENDIF", "\tENDIF", "ENDIF"))
    return "\r\n".join(out)


