"""CHAR07 高原ちあきの同一RAND:3内で着地点が近い枝を分離する。"""

from pathlib import Path


TARGET = Path(__file__).resolve().parents[1] / "ERB/CHAR/CHAR_07_高原ちあき_COM.ERB"

REWRITES = {
    "「んっ、お、お兄ちゃん先輩～! こ、これ難しい体勢ですよ～!?」": "「うひゃっ、先輩、動くたびに足がつりそうです！　あたしを支えたまま、ゆっくりにしてくださいよ～っ！」",
    "「ひゃあっ、お尻はノーマークです！　ラクロスでも守りきれないですよぉ～っ！」": "「ひゃあっ、そこは急に来たら反則です！　あたし、ボールなら追えますけど、これは追いかけられないですよぉ～っ！」",
    "「あたしがお嫁さんって、配役が大胆すぎます！　本当にしてくれるんですか～っ!?」": "「えっ、配役だけじゃなくて本当に？　そんなの、あたし家族に報告する前に逃げちゃいますよ～っ！」",
    "「こんなところ見せるなんて聞いてないです！　お兄ちゃん先輩、プライバシーはどこですか～っ！」": "「ちょ、ちょっと待ってください！　見るならせめて、終わったあとに笑わないって約束してくださいよ～っ！」",
    "「お、お兄ちゃん先輩～! そこは……うう、変な感じです～!」": "「お尻まで来ると、あたし、ラクロスのボールみたいに跳ねちゃいます～っ！」",
    "「こ、これを飲むんですか!?　先輩、あたしが心の準備をする時間もください～っ！」": "「飲むなら味と効果を先に教えてください！　知らないまま口にするの、部活の後輩だって嫌ですよ～っ！」",
    "「お口に出してくれたぶん、あたしのお腹にちゃんと届きましたよ……えへへ♪」": "「ごくっ……。お口から渡してもらったの、ちゃんと飲み込みましたよ♪　そんな嬉しそうに見られると、もっと欲しくなっちゃいます……♪」",
    "「先輩には、あたしの恥ずかしいところまで全部知られてますね……もう隠せないです♪」": "「ここまで知られてるなら、もう隠しても無駄ですね……。でも、先輩以外には絶対に見せないですから♪」",
    "「あたしが%CALLNAME:ASSI%にするんですか!?　攻め方なんて教わってないですよ～っ！」": "「%CALLNAME:ASSI%にするなら、まずあたしが手本を見せないと？　えっ、先輩が見てる前でですか～っ！」",
}


def main() -> None:
    text = TARGET.read_bytes().decode("cp932")
    for old, new in REWRITES.items():
        count = text.count(old)
        if count != 1:
            raise SystemExit(f"置換対象が一意でない: {count}件: {old}")
        text = text.replace(old, new, 1)
    data = text.encode("cp932")
    if data.count(b"\r\n") != data.count(b"\n"):
        raise SystemExit("CRLF検査失敗")
    TARGET.write_bytes(data)
    print(f"CHAR07: RAND枝 {len(REWRITES)}件を分離")


if __name__ == "__main__":
    main()
