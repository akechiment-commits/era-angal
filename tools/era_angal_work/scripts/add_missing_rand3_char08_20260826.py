def main() -> None:
    raw = PATH.read_bytes().decode("cp932").replace("\r\n", "\n")
    lines = raw.splitlines()
    for command, additions in EXTRA_SIMPLE.items():
        rewrite_simple(lines, command, additions)
    for command, states in EQUIPMENT_EXTRA.items():
        rewrite_equipment(lines, command, states)

    for command in (23, 56, 60, 61, 63, 65, 66, 68, 160, 188, 189, 192, 193, 194, 195, 196, 200, 203):
        add_assistant_alias(lines, command)

    # 助手名・%LOCALS%から始めた追加文にも、台詞の括弧を付ける。
    generated = set(value for values in EXTRA_SIMPLE.values() for value in values)
    generated.update(value for states in EQUIPMENT_EXTRA.values() for values in states.values() for value in values)
    for value in generated:
        if not value.startswith("「"):
            continue
        inner = value[1:-1]
        for i, line in enumerate(lines):
            if line.strip() == "PRINTFORMW " + inner:
                indent = line[: len(line) - len(line.lstrip())]
                lines[i] = indent + "PRINTFORMW " + value

    # COM60は助手枠なので、助手名を全分岐の視界に置く。
    com60_start = next(i for i, line in enumerate(lines) if line == "IF SELECTCOM == 60")
    com60_end = find_end(lines, com60_start)
    for i in range(com60_start, com60_end):
        lines[i] = lines[i].replace("相手の子", "%LOCALS%").replace("ふたりとも", "%LOCALS%と先輩")
        lines[i] = lines[i].replace("%LOCALS%と先輩目ぇ開けてた", "%LOCALS%も先輩も目ぇ開けてた")

    rewrite_custom(lines)
    rewrite_com306_307(lines)
    rewrite_com316(lines)
    result = "\n".join(lines).rstrip("\n") + "\n"
    PATH.write_bytes(result.replace("\n", "\r\n").encode("cp932"))
    print("CHAR08: 標準64枠・装着6枠・独自10枠を個別RAND3化、助手呼称とCOM306/307/316視点を是正")


