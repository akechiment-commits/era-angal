def find_end(lines: list[str], start: int) -> int:
    depth = 0
    for index in range(start, len(lines)):
        stripped = lines[index].strip()
        if re.match(r"^IF(?:\s|\()", stripped):
            depth += 1
        elif stripped == "ENDIF":
            depth -= 1
            if depth == 0:
                return index + 1
    raise RuntimeError(f"ENDIF not found: line {start + 1}")


def render_relation(love_original: list[str], normal_original: list[str], additions: tuple[str, ...], base: str = "\t") -> list[str]:
    love1, love2, normal1, normal2 = additions
    return [
        base + "IF TALENT:TARGET:153",
        base + "\tIF A == 0",
        *(base + "\t\t" + line.strip() for line in love_original),
        base + "\tELSEIF A == 1",
        base + f"\t\tPRINTFORMW {love1}",
        base + "\tELSE",
        base + f"\t\tPRINTFORMW {love2}",
        base + "\tENDIF",
        base + "ELSE",
        base + "\tIF A == 0",
        *(base + "\t\t" + line.strip() for line in normal_original),
        base + "\tELSEIF A == 1",
        base + f"\t\tPRINTFORMW {normal1}",
        base + "\tELSE",
        base + f"\t\tPRINTFORMW {normal2}",
        base + "\tENDIF",
        base + "ENDIF",
    ]


def rewrite_simple(lines: list[str], command: int, additions: tuple[str, ...]) -> None:
    starts = [i for i, line in enumerate(lines) if line == f"IF SELECTCOM == {command}"]
    if len(starts) != 1:
        raise RuntimeError(f"COM{command}: SELECTCOM blocks={len(starts)}")
    start = starts[0]
    end = find_end(lines, start)
    block = lines[start:end]
    if any("A = RAND:3" in line for line in block):
        return
    talent = next(i for i, line in enumerate(block) if line.strip() == "IF TALENT:TARGET:153")
    talent_end = find_end(block, talent)
    else_index = next(i for i in range(talent + 1, talent_end) if block[i].strip() == "ELSE")
    love = [line for line in block[talent + 1 : else_index] if "PRINTFORM" in line]
    normal = [line for line in block[else_index + 1 : talent_end - 1] if "PRINTFORM" in line]
    if not love or not normal:
        raise RuntimeError(f"COM{command}: relation PRINTFORM missing")
    replacement = block[:talent] + ["\tA = RAND:3"]
    replacement.extend(render_relation(love, normal, additions))
    replacement.extend(block[talent_end:])
    lines[start:end] = replacement


def rewrite_equipment(lines: list[str], command: int, states: dict[str, tuple[str, ...]]) -> None:
    starts = [i for i, line in enumerate(lines) if line == f"IF SELECTCOM == {command}"]
    if len(starts) != 1:
        raise RuntimeError(f"COM{command}: SELECTCOM blocks={len(starts)}")
    start = starts[0]
    end = find_end(lines, start)
    block = lines[start:end]
    if any("A = RAND:3" in line for line in block):
        return
    for state_index, state in enumerate(("on", "off")):
        marker = f"\tIF TEQUIP:{command}" if state_index == 0 else "\tELSE"
        state_start = next(i for i, line in enumerate(block) if line == marker)
        state_end = find_end(block, state_start)
        state_block = block[state_start:state_end]
        talent = next(i for i, line in enumerate(state_block) if line.strip() == "IF TALENT:TARGET:153")
        talent_end = find_end(state_block, talent)
        else_index = next(i for i in range(talent + 1, talent_end) if state_block[i].strip() == "ELSE")
        love = [line for line in state_block[talent + 1 : else_index] if "PRINTFORM" in line]
        normal = [line for line in state_block[else_index + 1 : talent_end - 1] if "PRINTFORM" in line]
        if len(love) != 1 or len(normal) != 1:
            raise RuntimeError(f"COM{command} {state}: expected one original love/normal line")
        replacement = state_block[:talent] + ["\t\tA = RAND:3"]
        replacement.extend(render_relation(love, normal, states[state], base="\t\t"))
        replacement.extend(state_block[talent_end:])
        block[state_start:state_end] = replacement
    lines[start:end] = block


def add_assistant_alias(lines: list[str], command: int) -> None:
    marker = f"IF SELECTCOM == {command}"
    starts = [i for i, line in enumerate(lines) if line == marker]
    if len(starts) != 1:
        raise RuntimeError(f"COM{command}: SELECTCOM blocks={len(starts)}")
    start = starts[0]
    if any("CALL AITE_YOBI, 8, ASSI" in line for line in lines[start : start + 8]):
        return
    lines[start + 1 : start + 1] = [
        "\tCALL AITE_YOBI, 8, ASSI",
        '\tLOCALS \'= @"%RESULTS%"',
    ]


