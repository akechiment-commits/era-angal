def main() -> None:
    original = TARGET.read_bytes().decode("cp932")
    BACKUP.parent.mkdir(parents=True, exist_ok=True)
    shutil.copy2(TARGET, BACKUP)
    text = original

    for old, new in EXACT_REPLACEMENTS.items():
        count = text.count(old)
        if count != 1:
            raise SystemExit(f"exact replacement count mismatch: {count}: {old}")
        text = text.replace(old, new)

    for old, new in OTHER_REPLACEMENTS.items():
        count = text.count(old)
        if count < 1:
            raise SystemExit(f"replacement not found: {old}")
        text = text.replace(old, new)

    for old, new in PRONOUN_REPLACEMENTS[:-1]:
        text = text.replace(old, new)

    # 「好きみたい」の一部を呼称と誤認しない。原作外の呼称として残り得る
    # 独立した「きみ」だけを対象にする。
    text = re.sub(r"(?<!好)きみ(?!たい)", "転校生くん", text)

    remaining = {term: text.count(term) for term in ("きみ", "興味深い", "実験", "生理現象", "観測", "データ")}
    if any(remaining.values()):
        raise SystemExit(f"unsupported terms remain: {remaining}")

    # 元ファイルの改行コードを維持して書き戻す。
    TARGET.write_bytes(text.encode("cp932"))
    print(f"backup={BACKUP}")
    print(f"bytes_before={len(original.encode('cp932'))}")
    print(f"bytes_after={len(TARGET.read_bytes())}")
    print(f"remaining={remaining}")


if __name__ == "__main__":
    main()
