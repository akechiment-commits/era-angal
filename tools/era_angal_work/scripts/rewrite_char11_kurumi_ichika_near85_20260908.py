"""CHAR11 氷野くるみに残るCHAR12との0.85台類似台詞を再構成する。"""

from pathlib import Path


TARGET = Path(__file__).resolve().parents[1] / "ERB/CHAR/CHAR_11_氷野くるみ_COM.ERB"

REWRITES = {
    "「先輩に咥えられながら一緒にされると、どこまでが自分の声か分からなくなります……でも嬉しいです♪」": "「先輩に咥えられながら、わたしのほうも同時に……っ。声の観察どころか、頭の中が真っ白です～♪」",
    "「手の動きに合わせて先輩の顔が変わるの、近くで見ると面白いです……もっと見せてほしいです♪」": "「手を動かすたび、先輩の顔がくるくる変わりますね～♪　わたしの『実験』、成功してるみたいです☆」",
    "「やっと落ち着きました……でも、歩くたびに思い出しちゃいそうです～っ♪」": "「やっと落ち着きました～……。でも、歩くたびに足がふわふわしますねぇ♪」",
    "「胸の奥まで引かれると、楽器みたいに身体が震えます……音が出そうですねぇ♪」": "「胸の奥まで引かれると、息が音に変わりそうです……。先輩、もっと近くで聞きますか♪」",
    "「そんなふうに言われると、わたし、怒るより先に身体が反応しちゃいます……ふしぎです♪」": "「そんなふうに言われると、わたし、間違いを指摘されたみたいに困っちゃいます～……でも、身体は正直なんですね♪」",
    "「知らないひとが多いところでも、先輩の隣なら景色を楽しめますねぇ♪」": "「知らないひとがおおい場所でも、先輩がいるなら安心です～♪　途中で植物さんを見つけたら寄り道してもいいですか？」",
    "「湯気の向こうで先輩と笑うと、いつものお風呂が温室みたいに特別になりますねぇ♪」": "「湯気の向こうで先輩と笑うと、温室で植物さんと過ごしてるみたいです～♪」",
    "「先輩の顔も一緒に残るなら、記録にしてもいいですよ。身体だけなのは嫌ですけど、先輩と一緒なら少しだけ♪」": "「先輩の顔も一緒に残るなら、記録にしてもいいですよ～♪　あとで観察日誌に貼っておきたいです」",
}


def main() -> None:
    text = TARGET.read_bytes().decode("cp932")
    for old, new in REWRITES.items():
        count = text.count(old)
        if count != 1:
            raise SystemExit(f"置換対象が一意でない: {count}件: {old}")
        text = text.replace(old, new, 1)
    data = text.encode("cp932")
    if data.count(b"\r\n") != data.count(b"\n"):
        raise SystemExit("CRLF検査失敗")
    TARGET.write_bytes(data)
    print(f"CHAR11: 0.85台の高類似 {len(REWRITES)}件を再構成")


if __name__ == "__main__":
    main()
