def with_assistant_name_23(block: str) -> str:
    if "CALL AITE_YOBI, 23, ASSI" not in block:
        block = re.sub(
            r"^(?P<head>(?:IF|ELSEIF) SELECTCOM == \d+)\n",
            lambda m: (
                f"{m.group('head')}\n"
                "\tCALL AITE_YOBI, 23, ASSI\n"
                '\tLOCALS \'= @"%RESULTS%"\n'
            ),
            block,
            count=1,
            flags=re.MULTILINE,
        )
    elif "LOCALS '= @\"%RESULTS%\"" not in block:
        block = re.sub(
            r"^(?P<call>\tCALL AITE_YOBI, 23, ASSI)\n",
            "\\g<call>\n\tLOCALS '= @\"%RESULTS%\"\n",
            block,
            count=1,
            flags=re.MULTILINE,
        )
    return block


def process_assistant(text: str, command: int, variants) -> str:
    start, end = section_spans(text)[command]
    block = text[start:end]
    block = add_rand_assignment(block)
    block = with_assistant_name_23(block)
    block = wrap_talent_branches(block, list(variants) if isinstance(variants, list) else [variants])
    return replace_block(text, command, block)


