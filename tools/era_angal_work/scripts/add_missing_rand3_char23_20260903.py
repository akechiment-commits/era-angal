def prepare_extra10_tone(text: str) -> str:
    for command, rewrites in EXTRA10_TONE_REWRITES.items():
        start, end = section_spans(text)[command]
        block = text[start:end]
        for old, new in rewrites.items():
            if block.count(old) != 1:
                raise ValueError(f"CHAR23追加10の置換対象が一意でない: COM{command} {old}")
            block = block.replace(old, new)
        text = replace_block(text, command, block)
    return text


def prepare_hair_viewpoint(text: str) -> str:
    start, end = section_spans(text)[316]
    block = text[start:end]
    if "; 視点：TARGETがPLAYERの髪を梳く。PLAYERは梳かれる側" not in block:
        block = "; 視点：TARGETがPLAYERの髪を梳く。PLAYERは梳かれる側\n" + block
    text = replace_block(text, 316, block)
    return text


def main() -> int:
    source = SOURCE.read_text(encoding="utf-8-sig")
    if not source.startswith("# こはる（全1128件）"):
        raise RuntimeError("こはる原作テキストのヘッダー確認に失敗しました")
    BACKUP.parent.mkdir(parents=True, exist_ok=True)
    if not BACKUP.exists():
        shutil.copy2(TARGET, BACKUP)
    text = BACKUP.read_bytes().decode("cp932").replace("\r\n", "\n")

    text = prepare_com60(text)
    for command, variants in STANDARD_VARIANTS.items():
        if command in ASSISTANT_COM:
            text = process_assistant(text, command, variants)
        else:
            text = process(text, command, variants)
    for command, variants in CUSTOM_VARIANTS.items():
        text = process(text, command, variants)
    for command, variants in EQUIPMENT_VARIANTS.items():
        text = process(text, command, list(variants))

    text = prepare_com56(text)
    text = prepare_extra10_tone(text)
    text = prepare_hair_viewpoint(text)
    text = apply_existing_rewrites(text)
    text = text.replace("LOCALS " + chr(92) + "'= @\"%RESULTS%\"", "LOCALS '= @\"%RESULTS%\"")
    expected = [*STANDARD_VARIANTS, *CUSTOM_VARIANTS, *EQUIPMENT_VARIANTS]
    spans = section_spans(text)
    missing = [command for command in expected if "A = RAND:3" not in text[spans[command][0]:spans[command][1]]]
    if missing:
        raise RuntimeError(f"RAND3未整備が残っています: {missing}")

    TARGET.write_bytes(text.replace("\n", "\r\n").encode("cp932"))
    print("CHAR23: 標準64・独自10・装着6をRAND3化、COM60助手呼称を補完")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
