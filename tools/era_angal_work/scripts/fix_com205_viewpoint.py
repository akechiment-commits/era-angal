import re, glob, sys

def find_file(num):
    g=[p for p in glob.glob('ERB/CHAR/CHAR_*_COM.ERB')
       if re.search(r'CHAR_0*%d_'%num,p) and int(re.search(r'CHAR_(\d+)_',p).group(1))==num]
    assert len(g)==1,(num,g); return g[0]

def fix_com(path, com, new_koi, new_tu):
    raw=open(path,'rb').read(); t=raw.decode('cp932'); lines=t.split('\r\n')
    idx=[k for k,l in enumerate(lines) if re.match(r'IF\s+SELECTCOM\s*==\s*%d\b'%com,l.strip())]
    assert idx,(path,com,'no block')
    i=idx[0]; slot=[]
    for j in range(i, len(lines)):
        s=lines[j].strip()
        if j>i and (re.match(r'IF\s+SELECTCOM\s*==',s) or s.startswith('@') or s.startswith(';--- COM')): break
        if re.search(r'PRINTFORM[LW]\s*「[^」]*」',lines[j]): slot.append(j)
    assert len(slot)==2,(path,com,'slots',len(slot))
    for j,new in zip(slot,[new_koi,new_tu]):
        lines[j]=re.sub(r'「[^」]*」','「'+new+'」',lines[j],count=1)
    nt='\r\n'.join(lines)
    assert '~' not in nt
    open(path,'wb').write(nt.encode('cp932'))

