def main() -> None:
    raw = TARGET.read_bytes()
    text = raw.decode(ENCODING)

    for old, new in REWRITES.items():
        count = text.count(old)
        if count != 1:
            raise RuntimeError(f"置換対象の出現数が不正です: {count}件 / {old}")
        text = text.replace(old, new, 1)

    # ぎん原作の主人公呼称は「あんた」「転校生くん」が中心。
    # 「君咲学院」の固有名詞だけは保持し、対象呼称の「君」は「あんた」へ戻す。
    before_target_kimi = len(re.findall(r"君(?!咲)", text))
    if before_target_kimi < 150:
        raise RuntimeError(f"呼称置換対象が想定より少ないため中止します: {before_target_kimi}件")
    text, changed_kimi = re.subn(r"君(?!咲)", "あんた", text)
    if re.search(r"君(?!咲)", text):
        raise RuntimeError("対象呼称の君が残っています")

    TARGET.write_bytes(text.encode(ENCODING))
    print(f"CHAR50 residual rewrite: {len(REWRITES)} exact lines, target-kimi {changed_kimi} occurrences")


if __name__ == "__main__":
    main()
