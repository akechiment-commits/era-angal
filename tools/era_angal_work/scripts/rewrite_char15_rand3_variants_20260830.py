def print_units(block: list[str], start: int, end: int) -> list[list[int]]:
    units: list[list[int]] = []
    index = start
    while index < end:
        if "PRINTFORM" in block[index] and "「" in block[index]:
            unit = [index]
            if "PRINTFORML" in block[index] and index + 1 < end and "PRINTFORMW" in block[index + 1]:
                unit.append(index + 1)
            units.append(unit)
            index = unit[-1] + 1
        else:
            index += 1
    return units


def replace_variant_units(block: list[str], start: int, end: int, variant1: str, variant2: str) -> None:
    units = print_units(block, start, end)
    if len(units) != 3:
        raise RuntimeError(f"RAND3追加分岐の台詞数が不正です: {units}")
    for unit, replacement in zip((units[1], units[2]), (variant1, variant2)):
        first = block[unit[0]]
        indent = first[: len(first) - len(first.lstrip())]
        block[unit[0]] = indent + "PRINTFORMW " + replacement
        for index in reversed(unit[1:]):
            del block[index]


def relation_sections(block: list[str]) -> tuple[int, int, int]:
    talent = next(i for i, line in enumerate(block) if line == "\tIF TALENT:TARGET:153")
    relation_else = next(i for i in range(talent + 1, len(block)) if block[i] == "\tELSE")
    relation_end = next(i for i in range(relation_else + 1, len(block)) if block[i] == "\tENDIF")
    return talent, relation_else, relation_end


def rewrite_simple(lines: list[str]) -> list[str]:
    if set(NEW_OTHER) != set(OTHER_VARIANTS):
        raise RuntimeError(f"標準RAND3の対象キーが不一致です: 新={sorted(NEW_OTHER)} 旧={sorted(OTHER_VARIANTS)}")
    for command in sorted(NEW_OTHER, reverse=True):
        start, end = select_ranges(lines)[command]
        block = lines[start:end]
        talent, relation_else, relation_end = relation_sections(block)
        values = NEW_OTHER[command]
        replace_variant_units(block, talent + 1, relation_else, values[0], values[1])
        talent, relation_else, relation_end = relation_sections(block)
        replace_variant_units(block, relation_else + 1, relation_end, values[2], values[3])
        lines[start:end] = block
    return lines


