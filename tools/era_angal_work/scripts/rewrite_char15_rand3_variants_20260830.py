def restore_custom_a0_continuations(lines: list[str]) -> list[str]:
    """初回RAND3化で欠落した独自10の既存A=0続行行を、RAND3化前バックアップから戻す。"""
    if not RAND3_BASE_BACKUP.exists():
        raise RuntimeError(f"独自10の復元元バックアップがありません: {RAND3_BASE_BACKUP}")
    old_lines = RAND3_BASE_BACKUP.read_bytes().decode("cp932").splitlines()
    for command in sorted(CUSTOM_COMMANDS, reverse=True):
        start, end = select_ranges(lines)[command]
        old_start, old_end = select_ranges(old_lines)[command]
        block = lines[start:end]
        old_block = old_lines[old_start:old_end]
        current_talent = next(i for i, line in enumerate(block) if line == "\tIF TALENT:TARGET:153")
        old_talent = next(i for i, line in enumerate(old_block) if line == "\tIF TALENT:TARGET:153")
        current_else = next(i for i in range(current_talent + 1, len(block)) if block[i] == "\tELSE")
        old_else = next(i for i in range(old_talent + 1, len(old_block)) if old_block[i] == "\tELSE")

        # 後半を先に戻すと、前半の行番号がずれない。
        for current_begin, current_end, old_begin, old_end in (
            (current_else + 1, len(block), old_else + 1, len(old_block)),
            (current_talent + 1, current_else, old_talent + 1, old_else),
        ):
            current_units = print_units(block, current_begin, current_end)
            old_units = print_units(old_block, old_begin, old_end)
            if not current_units or not old_units:
                raise RuntimeError(f"COM{command}の独自A=0台詞を検出できません")
            current_a0 = current_units[0]
            old_a0 = old_units[0]
            if len(old_a0) == 2 and len(current_a0) == 1:
                indent = block[current_a0[0]][: len(block[current_a0[0]]) - len(block[current_a0[0]].lstrip())]
                block.insert(current_a0[0] + 1, indent + old_block[old_a0[1]].lstrip())
        lines[start:end] = block
    return lines


