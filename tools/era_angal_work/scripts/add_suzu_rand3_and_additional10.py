def _insert_additional(lines: list[str]) -> int:
    anchors = {
        60: ";--- COM61 クンニ ---",
        62: ";--- COM63 貝あわせ ---",
        76: ";--- COM80 イラマチオ ---",
        78: ";--- COM80 イラマチオ ---",
        79: ";--- COM80 イラマチオ ---",
        84: ";--- COM85 放尿 ---",
        86: ";--- COM90 アナル愛撫させる ---",
        202: ";--- COM203 クスコされる ---",
        258: ";--- COM390 ゲームセンター ---",
        318: ";--- COM320 学食に行く ---",
    }
    inserted = 0
    # 同一アンカーへ複数挿入する場合は、数値順になるよう逆順で差し込む。
    for anchor, command_ids in {
        anchor: [command_id for command_id, value in anchors.items() if value == anchor]
        for anchor in set(anchors.values())
    }.items():
        if not command_ids:
            continue
        command_ids = sorted(command_ids, reverse=True)
        anchor_index = next(
            (i for i, line in enumerate(lines) if line == anchor or line.startswith(anchor)),
            None,
        )
        if anchor_index is None:
            raise ValueError(f"追加COMの配置アンカーが見つからない: {anchor}")
        for command_id in command_ids:
            marker = f";--- COM{command_id} "
            if any(line.startswith(marker) for line in lines):
                continue
            lines[anchor_index:anchor_index] = _additional_block(command_id) + [""]
            inserted += 1
    return inserted


def _relocate_existing_additional(lines: list[str]) -> None:
    """初回版で注釈と対象ヘッダの間に入った追加枠を正しい位置へ戻す。"""
    targets = {
        76: ";--- COM80 ",
        78: ";--- COM80 ",
        79: ";--- COM80 ",
        84: ";--- COM85 ",
        86: ";--- COM90 ",
        202: ";--- COM203 ",
        258: ";--- COM390 ",
        318: ";--- COM320 ",
    }
    # 初回版の移動処理が終端ENDIFを一行残した場合の後始末。
    # 対象コメント直前だけを確認し、通常の口上のENDIFは触らない。
    orphan_counts = {79: 3, 84: 1, 86: 1, 202: 1, 258: 1, 318: 1}
    for command_id, count in orphan_counts.items():
        marker = f";--- COM{command_id} "
        target_index = next((i for i, line in enumerate(lines) if line.startswith(marker)), None)
        if target_index is None or target_index < count:
            continue
        start = target_index - count
        if lines[start:target_index] == ["ENDIF"] * count:
            if start > 0 and lines[start - 1] == "":
                start -= 1
            del lines[start:target_index]
    # 現行ファイルでは追加枠の移動自体は完了済み。以後は注釈位置を再移動しない。
    return
    # 同じ注釈へ入れる枠は、最後に処理したものが先頭へ来るため逆順。
    for command_id in sorted(targets, reverse=True):
        marker = f";--- COM{command_id} "
        start = next((i for i, line in enumerate(lines) if line.startswith(marker)), None)
        if start is None:
            continue
        header = next(i for i in range(start, len(lines)) if lines[i] == f"IF SELECTCOM == {command_id}")
        if not any("RAND:3" in line for line in lines[header : header + 30]):
            continue
        finish = next(i for i in range(header + 1, len(lines)) if lines[i] == "ENDIF") + 1
        if finish < len(lines) and lines[finish] == "":
            finish += 1
        block = lines[start:finish]
        del lines[start:finish]
        target = targets[command_id]
        target_index = next(
            (i for i, line in enumerate(lines) if line.startswith(target)),
            None,
        )
        if target_index is None:
            raise ValueError(f"追加COM{command_id}の移動先注釈が見つからない: {target}")
        lines[target_index:target_index] = block


def _normalize_additional_order(lines: list[str]) -> None:
    """COM80前の追加枠を通常の番号順へ揃える。"""
    command_ids = [76, 78, 79]
    extracted: dict[int, list[str]] = {}
    ranges: list[tuple[int, int, int]] = []
    for command_id in command_ids:
        marker = f";--- COM{command_id} "
        start = next(i for i, line in enumerate(lines) if line.startswith(marker))
        header = next(i for i in range(start, len(lines)) if lines[i] == f"IF SELECTCOM == {command_id}")
        finish = next(i for i in range(header + 1, len(lines)) if lines[i] == "ENDIF") + 1
        if finish < len(lines) and lines[finish] == "":
            finish += 1
        ranges.append((start, finish, command_id))
        extracted[command_id] = lines[start:finish]
    for start, finish, _ in sorted(ranges, reverse=True):
        del lines[start:finish]
    target = next(i for i, line in enumerate(lines) if line.startswith(";--- COM80 "))
    ordered: list[str] = []
    for command_id in command_ids:
        block = extracted[command_id]
        ordered.extend(block)
        if not block or block[-1] != "":
            ordered.append("")
    lines[target:target] = ordered


def _ensure_additional_closures(lines: list[str]) -> None:
    """追加枠の最終ENDIFを各コマンド直後へ補う。"""
    for command_id in ADDITIONAL:
        header = next(i for i, line in enumerate(lines) if line == f"IF SELECTCOM == {command_id}")
        next_comment = next(
            i for i in range(header + 1, len(lines)) if lines[i].startswith(";--- COM")
        )
        probe = next_comment - 1
        while probe >= 0 and lines[probe] == "":
            probe -= 1
        if probe >= 0 and lines[probe] == "\tENDIF":
            lines.insert(next_comment, "ENDIF")


