def _headers(lines: list[str]) -> list[tuple[int, int]]:
    result = []
    for index, line in enumerate(lines):
        match = re.match(r"^\s*(?:IF|ELSEIF) SELECTCOM == (\d+)", line)
        if match:
            result.append((index, int(match.group(1))))
    return result


def _block_ranges(lines: list[str]) -> list[tuple[int, int, int]]:
    headers = _headers(lines)
    return [
        (index, next_index, command_id)
        for (index, command_id), (next_index, _) in zip(
            headers, headers[1:] + [(len(lines), -1)]
        )
    ]


def _indent_body(body: list[str]) -> list[str]:
    return ["\t" + line if line else line for line in body]


def _wrap_talent_branch(block: list[str], variants: tuple[str, ...], talent_indent: str) -> list[str]:
    talent = next(i for i, line in enumerate(block) if line == f"{talent_indent}IF TALENT:TARGET:153")
    alternate = next(i for i in range(talent + 1, len(block)) if block[i] == f"{talent_indent}ELSE")
    end = next(i for i in range(alternate + 1, len(block)) if block[i] == f"{talent_indent}ENDIF")
    love_body = block[talent + 1 : alternate]
    normal_body = block[alternate + 1 : end]
    wrapped = [
        block[talent],
        f"{talent_indent}\tIF A == 0",
        *_indent_body(love_body),
        f"{talent_indent}\tELSEIF A == 1",
        f"{talent_indent}\t\tPRINTFORMW {variants[0]}",
        f"{talent_indent}\tELSE",
        f"{talent_indent}\t\tPRINTFORMW {variants[1]}",
        f"{talent_indent}\tENDIF",
        block[alternate],
        f"{talent_indent}\tIF A == 0",
        *_indent_body(normal_body),
        f"{talent_indent}\tELSEIF A == 1",
        f"{talent_indent}\t\tPRINTFORMW {variants[2]}",
        f"{talent_indent}\tELSE",
        f"{talent_indent}\t\tPRINTFORMW {variants[3]}",
        f"{talent_indent}\tENDIF",
        block[end],
    ]
    return block[:talent] + wrapped + block[end + 1 :]


def _wrap_simple_blocks(lines: list[str]) -> tuple[list[str], int]:
    applied = 0
    for start, end, command_id in reversed(_block_ranges(lines)):
        if command_id not in VARIANTS:
            continue
        block = lines[start:end]
        if any("RAND:" in line for line in block):
            continue
        if not any(line.strip() == "IF TALENT:TARGET:153" for line in block):
            continue
        talent_index = next(i for i, line in enumerate(block) if line.strip() == "IF TALENT:TARGET:153")
        talent_indent = block[talent_index][: -len(block[talent_index].lstrip())]
        block = _wrap_talent_branch(block, VARIANTS[command_id], talent_indent)
        block.insert(talent_index, f"{talent_indent}A = RAND:3")
        lines[start:end] = block
        applied += 1
    return lines, applied


