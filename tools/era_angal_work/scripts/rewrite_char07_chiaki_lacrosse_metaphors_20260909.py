def main() -> int:
    lines = TARGET.read_bytes().decode("cp932").splitlines()
    for line_number, new_line in REPLACEMENTS.items():
        index = line_number - 1
        current = lines[index]
        if MARKERS[line_number] not in current:
            raise RuntimeError(f"unexpected line {line_number}: {current}")
        indentation = current[: len(current) - len(current.lstrip())]
        lines[index] = indentation + new_line
    TARGET.write_bytes(("\r\n".join(lines) + "\r\n").encode("cp932"))
    print(f"rewrote {len(REPLACEMENTS)} overused lacrosse-metaphor lines")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
