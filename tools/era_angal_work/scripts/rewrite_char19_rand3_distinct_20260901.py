def miken_voice(value: str) -> str:
    """みけ原作の短い語尾へ戻す。過度な母音引き伸ばしを追加枝へ出力しない。"""
    for old, new in (
        ("だねえ", "だよ"),
        ("ですねえ", "ですよ"),
        ("ますねえ", "ますよ"),
        ("だよお", "だよ"),
        ("ですよお", "ですよ"),
        ("ますよお", "ますよ"),
        ("ねえ", "ね"),
        ("ねぇ", "ね"),
        ("よお", "よ"),
        ("よぉ", "よ"),
        ("なあ", "な"),
        ("なぁ", "な"),
    ):
        value = value.replace(old, new)
    return value


