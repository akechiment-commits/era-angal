def main() -> None:
    raw = TARGET.read_bytes()
    text = raw.decode("cp932")
    BACKUP.parent.mkdir(parents=True, exist_ok=True)
    shutil.copy2(TARGET, BACKUP)
    for old, new in REPLACEMENTS:
        marker = f"「{old}」"
        if text.count(marker) != 1:
            raise RuntimeError(f"expected one occurrence, got {text.count(marker)}: {old}")
        text = text.replace(marker, f"「{new}」", 1)
    TARGET.write_bytes(text.replace("\r\n", "\n").replace("\n", "\r\n").encode("cp932"))
    print(f"rewritten={len(REPLACEMENTS)}")
    print(f"backup={BACKUP}")


if __name__ == "__main__":
    main()
