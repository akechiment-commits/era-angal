def apply_light_orgasm(text: str) -> str:
    start = text.index("; 絶頂したとき  @CHAR_ORGASM_22")
    end = text.index("RETURN 0", start)
    block = text[start:end]
    for old, new in LIGHT_ORGASM_REWRITES.items():
        if block.count(old) != 1:
            raise ValueError(f"軽い絶頂台詞の置換対象が一意でない: {old}")
        block = block.replace(old, new)
    return text[:start] + block + text[end:]
