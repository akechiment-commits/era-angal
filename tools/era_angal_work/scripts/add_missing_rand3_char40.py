def main() -> None:
    raw = COM_PATH.read_bytes()
    text = base.normalize(raw.decode("cp932"))
    if MARKER in text:
        print("CHAR40のRAND3/追加10ブロックは適用済みです。無変更で終了します。")
        return

    base.COM_PATH = COM_PATH
    base.BACKUP_PATH = BACKUP_PATH
    base.MARKER = MARKER
    base.EXTRA = EXTRA
    base.STATE_EXTRA = STATE_EXTRA
    base.CUSTOM_EXTRA = CUSTOM_EXTRA
    base.SIMPLE_IDS = set(EXTRA)
    base.STATE_IDS = set(STATE_EXTRA)
    base.CUSTOM_IDS = set(CUSTOM_EXTRA)
    base.CUSTOM_GROUPS = [(280, 284), (410, 414)]
    base.NEW_ASSISTANT_COMS = NEW_ASSISTANT_COMS

    lines = text.split("\n")
    modifications = base.simple_modifications(lines)
    com66_start, _, _ = next(item for item in base.command_ranges(lines) if item[2] == 66)
    modifications.append(
        (com66_start + 1, com66_start + 1, ["\tCALL AITE_YOBI, 40, ASSI", '\tLOCALS \'= @"%RESULTS%"'])
    )
    modifications.extend(base.state_modifications(lines))
    modifications.extend(base.custom_modifications(lines))
    virgin_index = next(i for i, line in enumerate(lines) if line.strip() == "@CHAR_VIRGIN_40")
    return_index = next(i for i in range(virgin_index - 1, -1, -1) if lines[i].strip() == "RETURN 0")
    modifications.append((return_index, return_index, render_new_block()))

    updated = lines[:]
    for start, end, replacement in sorted(modifications, key=lambda item: item[0], reverse=True):
        updated[start:end] = replacement
    result = "\n".join(updated).rstrip("\n") + "\n"
    encoded = result.encode("cp932")
    if not BACKUP_PATH.exists():
        BACKUP_PATH.parent.mkdir(parents=True, exist_ok=True)
        BACKUP_PATH.write_bytes(raw)
    COM_PATH.write_bytes(encoded.replace(b"\r\n", b"\n").replace(b"\n", b"\r\n"))
    print("CHAR40 夜霧はやて: 未分岐64枠・装着6枠・独自10枠をRAND:3化し、追加10コマンドを挿入しました。")


if __name__ == "__main__":
    main()
