def polish_orgasm_text(text: str) -> str:
    # 絶頂中も一人称は原作の「るり」を基本とする。
    text = text.replace("あたし", "るり").replace("わたし", "るり")
    # 三点リーダーを連ねず、早口の息継ぎは読点・短い断句で出す。
    text = text.replace("……", "、").replace("…", "")
    text = text.replace("るるる、っ", "るるる！")
    text = text.replace("るるる！、", "るるる！")
    text = text.replace("、っ", "っ").replace("、♪", "♪").replace("、☆", "☆")
    text = text.replace("、、", "、").replace("、。", "。").replace("、！", "！").replace("、？", "？")
    # 名前を一人称の代用品として機械的に挿入しない。主語は省略し、
    # 「るりの」「るりに」など、文中で意味を持つ用例だけ残す。
    text = text.replace("るり、", "")
    text = text.replace("るりと一緒に", "一緒に")
    text = re.sub(r"、+$", "", text)
    return text


