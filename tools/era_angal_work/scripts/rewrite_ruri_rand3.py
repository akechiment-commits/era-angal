def normalise_rururu(text: str) -> str:
    # 旧生成分に残った音便・促音を、原作で使う固定形へ戻す。
    # 旧生成分の「る、るるる」は、文頭や句読点直後の崩れだけを直す。
    # 「残ってる、るるる」のような自然な「るるる」は巻き込まない。
    text = re.sub(r"(^|[、。！？　])る、るるる(?=[っぅ、。！？…♪☆])", r"\1るるる", text)
    text = re.sub(r"(^|[、。！？　])る、るるぅ(?=[っぅ、。！？…♪☆])", r"\1るるる", text)
    text = text.replace("るるるっ", "るるる").replace("るるるぅ", "るるる")
    text = text.replace("るるっっ", "るるる").replace("るるぅっ", "るるる")
    text = re.sub(r"(^|[「、。！？　…])るるっ(?=[っぅ、。！？…♪☆」\n])", r"\1るるる", text)
    text = re.sub(r"(^|[「、。！？　…])るるぅ(?=[っぅ、。！？…♪☆」\n])", r"\1るるる", text)
    text = re.sub(r"(^|[ \t\n])るるっ(?=[っぅ、。！？…♪☆」\n])", r"\1るるる", text)
    text = re.sub(r"(^|[ \t\n])るるぅ(?=[っぅ、。！？…♪☆」\n])", r"\1るるる", text)
    # 旧口上に混ざっていた、固定音と単語の結合による誤植も除去する。
    text = text.replace("るるるり", "るり")
    text = text.replace("委ねるるるて", "委ねるのは")
    text = text.replace("るるるて", "るのは")
    text = text.replace("ちゅるるっ", "ちゅっ")
    text = text.replace("ちゅるるる", "ちゅっ")
    text = text.replace("ぬるるる", "ぬるぬると")
    return text


def validate(text: str) -> None:
    forbidden = ["るるっ", "るるぅ", "るるるっ", "るるるぅ", "るるるる", "るるるり", "るるるて"]
    for word in forbidden:
        if word in text:
            raise RuntimeError(f"forbidden Ruri variation remains: {word}")
    if "~" in text:
        raise RuntimeError("half-width tilde remains")
    orgasm_match = re.search(r"^@CHAR_ORGASM_58\s*$", text, re.MULTILINE)
    if not orgasm_match:
        raise RuntimeError("@CHAR_ORGASM_58 label is missing")
    orgasm_start = orgasm_match.start()
    next_label = re.search(r"^@(?!CHAR_ORGASM_58\s*$)", text[orgasm_match.end():], re.MULTILINE)
    orgasm_end = orgasm_match.end() + next_label.start() if next_label else len(text)
    orgasm = text[orgasm_start:orgasm_end]
    if orgasm.count("るるる") > 2:
        raise RuntimeError(f"orgasm section still overuses るるる: {orgasm.count('るるる')}")
    for line in text.splitlines():
        if "PRINTFORMW 「" in line and "」" not in line and not line.rstrip().endswith("、"):
            raise RuntimeError(f"unclosed quote: {line}")
    if text.count("IF ") < text.count("ENDIF"):
        raise RuntimeError("IF/ENDIF count is inverted")
    for number in STANDARD:
        block = re.search(rf"IF SELECTCOM == {number}\b.*?(?=\n(?:;---|IF SELECTCOM|@CHAR_))", text, re.S)
        if not block or "A = RAND:3" not in block.group(0):
            raise RuntimeError(f"COM{number} missing RAND:3")


