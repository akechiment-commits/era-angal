def polish_sexual_line(text: str, serial: int) -> str:
    """性愛コマンドの三点リーダーを、息継ぎとして少量だけ残す。"""
    runs = list(re.finditer(r"…+", text))
    if not runs:
        return text

    # 先頭の短い息だけ、文の内容に応じて一部を残す。それ以外は読点か
    # 言い切りに直し、各台詞に機械的な「…」が並ばないようにする。
    keep = None
    lead = re.match(r"^(?:あ|ん|ひ|ふ|ちゅ|ごく|るるる)……", text)
    if lead and (sum(ord(ch) for ch in text) + serial) % 4 == 0:
        keep = runs[0]
    pieces: list[str] = []
    cursor = 0
    for run in runs:
        pieces.append(text[cursor:run.start()])
        pieces.append("…" if keep is run else "、")
        cursor = run.end()
    pieces.append(text[cursor:])
    text = "".join(pieces)
    text = re.sub(r"、+$", "", text)
    text = text.replace("、、", "、")
    text = text.replace("、っ", "っ").replace("、♪", "♪").replace("、☆", "☆")
    text = text.replace("、。", "。").replace("、！", "！").replace("、？", "？")
    text = re.sub(r"^[、]+", "", text)
    return text


