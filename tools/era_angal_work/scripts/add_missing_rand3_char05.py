SIMPLE_IDS = set(EXTRA)


def normalize(text: str) -> str:
    return text.replace("\r\n", "\n").replace("\r", "\n")


def find_end(lines: list[str], start: int) -> int:
    depth = 0
    for index in range(start, len(lines)):
        stripped = lines[index].strip()
        if re.match(r"^IF(?:\s|\()", stripped):
            depth += 1
        elif stripped == "ENDIF":
            depth -= 1
            if depth == 0:
                return index + 1
    raise RuntimeError(f"ENDIF not found: {start + 1}")


def render_branch(base: str, original: list[str], extra1: str, extra2: str) -> list[str]:
    if not original:
        raise RuntimeError("branch has no original PRINTFORM")
    out = [base + "IF A == 0"]
    out.extend(base + "\t" + line.strip() for line in original)
    out.extend((base + "ELSEIF A == 1", base + f'\tPRINTFORMW 「{extra1}」', base + "ELSE", base + f'\tPRINTFORMW 「{extra2}」', base + "ENDIF"))
    return out


def build_simple(lines: list[str], start: int, end: int, command: int) -> list[str]:
    block = lines[start:end]
    talent_index = next(i for i, line in enumerate(block) if line.strip() == "IF TALENT:TARGET:153")
    talent_end = find_end(block, talent_index)
    else_index = next(i for i in range(talent_index + 1, talent_end) if block[i].strip() == "ELSE")
    love = [line for line in block[talent_index + 1 : else_index] if "PRINTFORM" in line]
    normal = [line for line in block[else_index + 1 : talent_end - 1] if "PRINTFORM" in line]
    love1, love2, normal1, normal2 = EXTRA[command]
    base = block[talent_index][: len(block[talent_index]) - len(block[talent_index].lstrip())]
    replacement = [base + "A = RAND:3"]
    replacement.extend(render_branch(base, love, love1, love2))
    replacement.append(base + "ELSE")
    replacement.extend(render_branch(base, normal, normal1, normal2))
    replacement.append("ENDIF")
    return block[:talent_index] + replacement + block[talent_end:]


def main() -> None:
    text = normalize(COM_PATH.read_bytes().decode("cp932"))
    lines = text.split("\n")
    markers = [(index, int(match.group(1))) for index, line in enumerate(lines) if (match := re.match(r"^IF SELECTCOM == (\d+)$", line))]
    starts = {command: index for index, command in markers}
    missing = sorted(SIMPLE_IDS - set(starts))
    if missing:
        raise RuntimeError(f"missing command blocks: {missing}")
    mods = []
    for command in sorted(SIMPLE_IDS):
        start = starts[command]
        end = find_end(lines, start)
        if any(line.strip() == "A = RAND:3" for line in lines[start:end]):
            continue
        mods.append((start, end, build_simple(lines, start, end, command)))
    used: set[int] = set()
    for start, end, _ in mods:
        if any(index in used for index in range(start, end)):
            raise RuntimeError("overlapping command modifications")
        used.update(range(start, end))
    for start, end, replacement in sorted(mods, reverse=True):
        lines[start:end] = replacement
    result = "\n".join(lines).rstrip("\n") + "\n"
    COM_PATH.write_bytes(result.replace("\n", "\r\n").encode("cp932"))
    print(f"CHAR05 standard RAND3 added this run: {len(mods)}")


if __name__ == "__main__":
    main()
