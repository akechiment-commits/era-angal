def rewrite_com() -> int:
    raw = COM_PATH.read_bytes()
    text = raw.decode("cp932")
    lines = text.splitlines()
    for line_no, (marker, replacement) in COM_REWRITES.items():
        index = line_no - 1
        if index >= len(lines):
            raise RuntimeError(f"COMの行番号が範囲外です: {line_no}")
        old_line = lines[index]
        if marker not in old_line or "PRINTFORMW" not in old_line:
            raise RuntimeError(f"COMの想定文が見つかりません: {line_no}: {marker}")
        prefix = old_line[: old_line.index("PRINTFORMW")]
        lines[index] = prefix + "PRINTFORMW " + replacement
    COM_PATH.write_bytes(("\r\n".join(lines) + "\r\n").encode("cp932"))
    return len(COM_REWRITES)


