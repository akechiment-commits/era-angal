def toggle_body(command: int, equip: int, on_love: list[str], on_normal: list[str], off_love: list[str], off_normal: list[str], comments: list[str] | None = None) -> str:
    def relation(lines: list[str], love: list[str], normal: list[str], indent: str) -> None:
        lines.append(f"{indent}IF TALENT:TARGET:153")
        for i, text in enumerate(love):
            if i < 2:
                lines.append(f"{indent}\t{'IF' if i == 0 else 'ELSEIF'} A == {i}")
            else:
                lines.append(f"{indent}\tELSE")
            lines.append(f"{indent}\t\tPRINTFORMW {q(text)}")
        lines.append(f"{indent}\tENDIF")
        lines.append(f"{indent}ELSE")
        for i, text in enumerate(normal):
            if i < 2:
                lines.append(f"{indent}\t{'IF' if i == 0 else 'ELSEIF'} A == {i}")
            else:
                lines.append(f"{indent}\tELSE")
            lines.append(f"{indent}\t\tPRINTFORMW {q(text)}")
        lines.append(f"{indent}\tENDIF")
        lines.append(f"{indent}ENDIF")

    lines = []
    if comments:
        lines.extend(f";  {line}" for line in comments)
    lines += [f"IF SELECTCOM == {command}", f"\tIF TEQUIP:{equip}", "\t\t;装着", "\t\tA = RAND:3"]
    relation(lines, on_love, on_normal, "\t\t")
    lines += ["\tELSE", "\t\t;取り外し", "\t\tA = RAND:3"]
    relation(lines, off_love, off_normal, "\t\t")
    lines += ["\tENDIF", "ENDIF"]
    return "\n".join(lines)


