def replace_command(text: str, command: int, body: str) -> str:
    marker = re.compile(rf"(?m)^;--- COM{command}(?!\d)[^\r\n]*\r?\n")
    m = marker.search(text)
    if not m:
        raise RuntimeError(f"COM{command} marker not found")
    next_m = re.search(r"(?m)^;--- COM", text[m.end():])
    end = m.end() + next_m.start() if next_m else len(text)
    marker_line = text[m.start():m.end()].rstrip("\r\n")
    replacement = marker_line + "\n" + body + "\n\n"
    return text[:m.start()] + replacement + text[end:]


