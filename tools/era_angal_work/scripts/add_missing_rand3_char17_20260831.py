ASSISTANT_COM = {61, 63, 65, 160, 188, 189, 196, 200, 203}


def section_spans(text: str) -> dict[int, tuple[int, int]]:
    headings = list(re.finditer(r"(?m)^(?:IF|ELSEIF) SELECTCOM == (\d+)\s*$", text))
    result: dict[int, tuple[int, int]] = {}
    for index, heading in enumerate(headings):
        end = headings[index + 1].start() if index + 1 < len(headings) else len(text)
        result[int(heading.group(1))] = (heading.start(), end)
    return result


def add_rand_assignment(block: str) -> str:
    if "A = RAND:" in block:
        return block
    return re.sub(
        r"^(?P<head>(?:IF|ELSEIF) SELECTCOM == \d+)\n",
        r"\g<head>\n\tA = RAND:3\n",
        block,
        count=1,
        flags=re.MULTILINE,
    )


def indent_body(body: str, prefix: str) -> str:
    return "\n".join(prefix + line if line else line for line in body.split("\n"))


def wrap_talent_branches(block: str, variant_sets: list[tuple[str, str, str, str]]) -> str:
    pattern = re.compile(
        r"(?ms)^(?P<indent>\t+)IF TALENT:TARGET:153\n"
        r"(?P<lover>.*?)(?=\n(?P=indent)ELSE\n)"
        r"\n(?P=indent)ELSE\n"
        r"(?P<normal>.*?)\n(?P=indent)ENDIF"
    )
    matches = list(pattern.finditer(block))
    if not matches:
        raise ValueError("TALENT:TARGET:153 の単純分岐を検出できません")
    if len(matches) != len(variant_sets):
        raise ValueError(f"分岐数が不一致: detected={len(matches)} expected={len(variant_sets)}")

    for match, variants in reversed(list(zip(matches, variant_sets))):
        indent = match.group("indent")
        lover_body = match.group("lover")
        normal_body = match.group("normal")
        lover1, lover2, normal1, normal2 = variants

        def branch(body: str, first: str, second: str) -> str:
            inner = indent + "\t"
            line_indent = indent + "\t\t"
            return "\n".join(
                [
                    f"{inner}IF A == 0",
                    indent_body(body, line_indent),
                    f"{inner}ELSEIF A == 1",
                    f"{line_indent}{first}",
                    f"{inner}ELSE",
                    f"{line_indent}{second}",
                    f"{inner}ENDIF",
                ]
            )

        replacement = "\n".join(
            [
                f"{indent}IF TALENT:TARGET:153",
                branch(lover_body, lover1, lover2),
                f"{indent}ELSE",
                branch(normal_body, normal1, normal2),
                f"{indent}ENDIF",
            ]
        )
        block = block[: match.start()] + replacement + block[match.end() :]
    return block


