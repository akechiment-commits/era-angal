def marker_span(text: str, command: int):
    start = re.search(rf"(?m)^;--- COM{command}(?![0-9])[^\r\n]*\r?\n", text)
    if not start:
        raise RuntimeError(f"missing marker COM{command}")
    following = re.search(r"(?m)^;--- COM[^\r\n]*\r?\n", text[start.end():])
    end = start.end() + following.start() if following else len(text)
    return start.start(), end, text[start.start():start.end()]


def section_span(text: str, marker_pattern: str, next_pattern: str):
    start = re.search(marker_pattern, text)
    if not start:
        raise RuntimeError(f"missing section {marker_pattern}")
    following = re.search(next_pattern, text[start.end():])
    end = start.end() + following.start() if following else len(text)
    return start.start(), end, text[start.start():start.end()]


