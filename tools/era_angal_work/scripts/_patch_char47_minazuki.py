def replace_section(text: str, marker_pattern: str, next_pattern: str, body: str):
    start, end, _ = section_span(text, marker_pattern, next_pattern)
    block = text[start:end]
    if "A = RAND:3" in block:
        return text
    marker_end = block.index("\n", block.index(";---")) + 1
    prefix = block[:marker_end]
    return text[:start] + prefix + body + "\r\n\r\n" + text[end:]


