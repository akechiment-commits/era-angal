def _add_rand3_equipment(lines: list[str], command: int) -> None:
    start = _find_select(lines, command)
    end = _matching_endif(lines, start)
    block = lines[start : end + 1]
    if any("RAND:" in line for line in block):
        raise ValueError(f"装着COM{command}はすでにRAND済みです")
    block.insert(1, "\tA = RAND:3")
    talents = [i for i, line in enumerate(block) if line.strip() == "IF TALENT:TARGET:153"]
    if len(talents) != 2:
        raise ValueError(f"装着COM{command}のTALENT分岐数が想定外です: {talents}")
    for state_index, talent in reversed(list(enumerate(talents))):
        state = "on" if state_index == 0 else "off"
        block = _wrap_specific_talent(block, talent, EQUIPMENT[command][state])
    lines[start : end + 1] = block


