def _leading(line: str) -> str:
    return line[: len(line) - len(line.lstrip())]


def _find_select(lines: list[str], command: int) -> int:
    target = f"IF SELECTCOM == {command}"
    for index, line in enumerate(lines):
        if line.strip() == target:
            return index
    raise ValueError(f"SELECTCOM {command} が見つかりません")


def _matching_endif(lines: list[str], start: int) -> int:
    depth = 0
    for index in range(start, len(lines)):
        stripped = lines[index].strip()
        if stripped.startswith("IF "):
            depth += 1
        elif stripped == "ENDIF":
            depth -= 1
            if depth == 0:
                return index
    raise ValueError(f"SELECTCOM {start + 1} のENDIFが見つかりません")


def _talent_parts(block: list[str]) -> tuple[int, int, int, int]:
    talent = next(i for i, line in enumerate(block) if line.strip() == "IF TALENT:TARGET:153")
    indent = _leading(block[talent])
    alternate = next(i for i in range(talent + 1, len(block)) if block[i] == f"{indent}ELSE")
    finish = next(i for i in range(alternate + 1, len(block)) if block[i] == f"{indent}ENDIF")
    love_prints = [i for i in range(talent + 1, alternate) if "PRINTFORM" in block[i]]
    normal_prints = [i for i in range(alternate + 1, finish) if "PRINTFORM" in block[i]]
    if len(love_prints) != 1 or len(normal_prints) != 1:
        raise ValueError(f"TALENT分岐のPRINTFORM数が想定外です: {love_prints}/{normal_prints}")
    return talent, alternate, finish, love_prints[0], normal_prints[0]


def _correct_a0(block: list[str], command: int) -> None:
    if command not in A0_CORRECTIONS:
        return
    talent, alternate, _, love_print, normal_print = _talent_parts(block)
    love, normal = A0_CORRECTIONS[command]
    block[love_print] = f"{_leading(block[love_print])}PRINTFORMW 「{love}」"
    block[normal_print] = f"{_leading(block[normal_print])}PRINTFORMW 「{normal}」"


def _wrap_talent(block: list[str], variants: tuple[str, str, str, str]) -> list[str]:
    talent, alternate, finish, love_print, normal_print = _talent_parts(block)
    indent = _leading(block[talent])
    print_indent = indent + "\t"
    wrapped = [
        block[talent],
        f"{indent}\tIF A == 0",
        "\t" + block[love_print],
        f"{indent}\tELSEIF A == 1",
        f"{print_indent}PRINTFORMW 「{variants[0]}」",
        f"{indent}\tELSE",
        f"{print_indent}PRINTFORMW 「{variants[1]}」",
        f"{indent}\tENDIF",
        block[alternate],
        f"{indent}\tIF A == 0",
        "\t" + block[normal_print],
        f"{indent}\tELSEIF A == 1",
        f"{print_indent}PRINTFORMW 「{variants[2]}」",
        f"{indent}\tELSE",
        f"{print_indent}PRINTFORMW 「{variants[3]}」",
        f"{indent}\tENDIF",
        block[finish],
    ]
    return block[:talent] + wrapped + block[finish + 1 :]


def _add_rand3_simple(lines: list[str], command: int) -> None:
    start = _find_select(lines, command)
    end = _matching_endif(lines, start)
    block = lines[start : end + 1]
    if any("RAND:" in line for line in block):
        raise ValueError(f"COM{command} はすでにRAND済みです")
    _correct_a0(block, command)
    variants = ACTIVE_VARIANTS.get(command) or SPECIAL_VARIANTS.get(command) or _default_variants(command)
    block = _wrap_talent(block, variants)
    block.insert(1, "\tA = RAND:3")
    lines[start : end + 1] = block


