def _insert_additional(lines: list[str]) -> int:
    anchors = {
        60: ";--- COM61 ",
        62: ";--- COM63 ",
        76: ";--- COM80 ",
        78: ";--- COM80 ",
        79: ";--- COM80 ",
        84: ";--- COM85 ",
        86: ";--- COM90 ",
        202: ";--- COM203 ",
        258: ";--- COM390 ",
        318: ";--- COM320 ",
    }
    inserted = 0
    marker_added = False
    grouped: dict[str, list[int]] = {}
    for command, anchor in anchors.items():
        grouped.setdefault(anchor, []).append(command)
    for anchor, commands in grouped.items():
        index = next((i for i, line in enumerate(lines) if line.startswith(anchor)), None)
        if index is None:
            raise ValueError(f"COM{commands[0]}の配置アンカーが見つかりません: {anchor}")
        for command in sorted(commands, reverse=True):
            marker = f";--- COM{command} "
            if any(line.startswith(marker) for line in lines):
                continue
            prefix = []
            if not marker_added and not any(line == MARKER for line in lines):
                prefix = [MARKER, "; ちづるの恋愛体質・演劇部・緑化委員らしさを保った追加10コマンド。", ""]
                marker_added = True
            lines[index:index] = prefix + _additional_block(command)
            inserted += 1
    return inserted


def main() -> None:
    if not COM_PATH.exists():
        raise FileNotFoundError(COM_PATH)
    current_bytes = COM_PATH.read_bytes()
    current = current_bytes.decode(ENCODING)
    if MARKER in current:
        if not BACKUP_PATH.exists():
            raise RuntimeError("CHAR63は生成済みですが、再生成元バックアップがありません")
        original_bytes = BACKUP_PATH.read_bytes()
    else:
        original_bytes = current_bytes
        BACKUP_PATH.parent.mkdir(parents=True, exist_ok=True)
        if not BACKUP_PATH.exists():
            BACKUP_PATH.write_bytes(original_bytes)
    original = original_bytes.decode(ENCODING)
    lines = original.replace("\r\n", "\n").replace("\r", "\n").split("\n")
    if lines and lines[-1] == "":
        lines.pop()

    _replace_custom_sections(lines)
    for command in sorted(SIMPLE_COMMANDS, reverse=True):
        _add_rand3_simple(lines, command)
    for command in sorted(EQUIPMENT_COMMANDS, reverse=True):
        _add_rand3_equipment(lines, command)

    _insert_additional(lines)

    result = "\r\n".join(lines)
    if not result.endswith("\r\n"):
        result += "\r\n"
    COM_PATH.write_bytes(result.encode(ENCODING))
    print(f"CHAR63: RANDなし{len(SIMPLE_COMMANDS)}+装着{len(EQUIPMENT_COMMANDS)}+独自10をRAND:3化、追加10を実装、独自枠の場面を整合しました。バックアップ: {BACKUP_PATH}")


if __name__ == "__main__":
    main()
