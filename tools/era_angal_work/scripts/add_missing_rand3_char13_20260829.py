def cp932_lines() -> list[str]:
    return TARGET.read_bytes().decode("cp932").splitlines()


def write_cp932(lines: list[str]) -> None:
    TARGET.write_bytes("\r\n".join(lines).encode("cp932") + b"\r\n")


def command_ranges(lines: list[str]) -> dict[int, tuple[int, int]]:
    starts: list[tuple[int, int]] = []
    for index, line in enumerate(lines):
        match = re.match(r";--- COM(\d+)(?: |$)", line)
        if match:
            starts.append((index, int(match.group(1))))
    result: dict[int, tuple[int, int]] = {}
    for pos, (start, command) in enumerate(starts):
        end = starts[pos + 1][0] if pos + 1 < len(starts) else len(lines)
        result[command] = (start, end)
    return result


def wrap_relation_prints(block: list[str], additions: tuple[str, str, str, str]) -> list[str]:
    talent_positions = [i for i, line in enumerate(block) if re.match(r"^\tIF TALENT:TARGET:153\s*$", line)]
    if len(talent_positions) != 1:
        raise RuntimeError(f"恋人/通常ブロックを特定できません: {talent_positions}")
    talent = talent_positions[0]
    relation_else = next((i for i in range(talent + 1, len(block)) if block[i] == "\tELSE"), None)
    if relation_else is None:
        raise RuntimeError("恋人/通常のELSEがありません")
    relation_end = next((i for i in range(relation_else + 1, len(block)) if block[i] == "\tENDIF"), None)
    if relation_end is None:
        raise RuntimeError("通常分岐のENDIFがありません")

    def wrap(start: int, end: int, extra1: str, extra2: str) -> list[str]:
        prints = [i for i in range(start, end) if re.match(r"^\t\tPRINTFORMW\s+", block[i])]
        if len(prints) != 1:
            raise RuntimeError(f"対象分岐のPRINTFORMW数が不正です: {prints}")
        p = prints[0]
        original = block[p]
        return block[start:p] + [
            "\t\tIF A == 0",
            "\t\t\t" + original.lstrip(),
            "\t\tELSEIF A == 1",
            "\t\t\tPRINTFORMW " + extra1,
            "\t\tELSE",
            "\t\t\tPRINTFORMW " + extra2,
            "\t\tENDIF",
        ] + block[p + 1 : end]

    lover = wrap(talent + 1, relation_else, additions[0], additions[1])
    normal = wrap(relation_else + 1, relation_end, additions[2], additions[3])
    return (
        block[: talent + 1]
        + lover
        + [block[relation_else]]
        + normal
        + [block[relation_end]]
        + block[relation_end + 1 :]
    )


def add_rand3_to_other(lines: list[str]) -> list[str]:
    ranges = command_ranges(lines)
    for command, additions in sorted(OTHER_VARIANTS.items(), reverse=True):
        start, end = ranges[command]
        block = lines[start:end]
        if any("A = RAND:3" in line for line in block):
            continue
        selector = next(i for i, line in enumerate(block) if line == f"IF SELECTCOM == {command}")
        block.insert(selector + 1, "\tA = RAND:3")
        block = wrap_relation_prints(block, additions)
        lines[start:end] = block
        ranges = command_ranges(lines)
    return lines


def add_rand3_to_equipment(lines: list[str]) -> list[str]:
    for command, additions in sorted(EQUIPMENT_VARIANTS.items(), reverse=True):
        ranges = command_ranges(lines)
        start, end = ranges[command]
        block = lines[start:end]
        if any("A = RAND:3" in line for line in block):
            continue
        state_on = next(i for i, line in enumerate(block) if re.match(r"^\tIF TEQUIP:\d+\s*$", line))
        state_off = next(i for i, line in enumerate(block) if line == "\tELSE")
        for index in sorted((state_on + 1, state_off + 1), reverse=True):
            block.insert(index, "\t\tA = RAND:3")
        # Wrap the two relation pairs independently, with their respective state-specific additions.
        talent_indices = [i for i, line in enumerate(block) if line == "\t\tIF TALENT:TARGET:153"]
        if len(talent_indices) != 2:
            raise RuntimeError(f"COM{command} 装着状態の恋人分岐が不正です")
        # Work from the bottom to keep indexes stable.
        for index, talent in reversed(list(enumerate(talent_indices))):
            rel_else = next(i for i in range(talent + 1, len(block)) if block[i] == "\t\tELSE")
            rel_end = next(i for i in range(rel_else + 1, len(block)) if block[i] == "\t\tENDIF")
            def wrap_part(part_start: int, part_end: int, a1: str, a2: str) -> list[str]:
                prints = [i for i in range(part_start, part_end) if re.match(r"^\t\t\tPRINTFORMW\s+", block[i])]
                if len(prints) != 1:
                    raise RuntimeError(f"COM{command} 装着状態のPRINTFORMW数が不正です")
                p = prints[0]
                original = block[p]
                return block[part_start:p] + [
                    "\t\t\tIF A == 0",
                    "\t\t\t\t" + original.lstrip(),
                    "\t\t\tELSEIF A == 1",
                    "\t\t\t\tPRINTFORMW " + a1,
                    "\t\t\tELSE",
                    "\t\t\t\tPRINTFORMW " + a2,
                    "\t\t\tENDIF",
                ] + block[p + 1 : part_end]
            if index == 0:
                lover_vals = additions[0:2]
                normal_vals = additions[2:4]
            else:
                lover_vals = additions[4:6]
                normal_vals = EQUIPMENT_OFF_NORMAL[command]
            lover = wrap_part(talent + 1, rel_else, lover_vals[0], lover_vals[1])
            normal = wrap_part(rel_else + 1, rel_end, normal_vals[0], normal_vals[1])
            block[talent + 1 : rel_else] = lover
            shift = len(lover) - (rel_else - (talent + 1))
            rel_else += shift
            rel_end += shift
            block[rel_else + 1 : rel_end] = normal
        lines[start:end] = block
    return lines


