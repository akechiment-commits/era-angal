def normalize_print(line: str) -> str:
    return re.sub(r"^\s*PRINTFORM(?:L|W)?\s*", "", line).replace("「", "").replace("」", "")


def remove_equipment_duplicates(lines: list[str]) -> list[str]:
    for command, additions in EQUIPMENT_VARIANTS.items():
        start, end = command_ranges(lines)[command]
        print_indices = [i for i in range(start, end) if re.match(r"^\t+PRINTFORMW\s+", lines[i])]
        seen: dict[str, list[int]] = {}
        for index in print_indices:
            seen.setdefault(normalize_print(lines[index]), []).append(index)
        for indices in seen.values():
            if len(indices) < 2:
                continue
            index = indices[-1]
            indent = re.match(r"^\t+", lines[index]).group(0)
            if command in EQUIPMENT_OFF_NORMAL:
                replacement = EQUIPMENT_OFF_NORMAL[command][1]
            else:
                replacement = "「装備解除を確認っ。自分、次の任務までに調子を整えるであります！」"
            lines[index] = indent + "PRINTFORMW " + replacement
    return lines


