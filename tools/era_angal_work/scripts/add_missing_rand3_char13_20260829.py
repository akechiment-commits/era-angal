def main() -> None:
    lines = cp932_lines()
    original = list(lines)
    camera_missing = not any(
        line.strip() == "IF TEQUIP:53"
        for line in lines[command_ranges(lines)[3][0] : command_ranges(lines)[3][1]]
    )
    lines = replace_custom(lines)
    lines = add_rand3_to_other(lines)
    lines = add_rand3_to_equipment(lines)
    lines = ensure_assistant_aliases(lines)
    lines = remove_equipment_duplicates(lines)
    lines = repair_meta_lines(lines)
    lines = add_com3_camera_difference(lines)
    if lines == original:
        print("変更なし: CHAR13のRAND3と助手呼称は既に反映済み")
        return
    BACKUP.parent.mkdir(parents=True, exist_ok=True)
    if not BACKUP.exists():
        BACKUP.write_bytes(TARGET.read_bytes())
    if camera_missing and not CAMERA_BACKUP.exists():
        CAMERA_BACKUP.parent.mkdir(parents=True, exist_ok=True)
        CAMERA_BACKUP.write_bytes(TARGET.read_bytes())
    write_cp932(lines)
    print("更新: CHAR13の標準RAND3、装着6枠、独自10、助手呼称を補完")


if __name__ == "__main__":
    main()
