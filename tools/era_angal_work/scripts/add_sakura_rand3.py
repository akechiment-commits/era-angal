def command_start(lines: list[str], number: int) -> int:
    pattern = re.compile(rf"^(?:IF|ELSEIF) SELECTCOM == {number}\s*$")
    found = [i for i, line in enumerate(lines) if pattern.match(line)]
    if len(found) != 1:
        raise RuntimeError(f"SELECTCOM {number}: expected one header, got {len(found)}")
    return found[0]


def command_end(lines: list[str], start: int) -> int:
    depth = 1
    for i in range(start + 1, len(lines)):
        stripped = lines[i].lstrip()
        if stripped.startswith("ELSEIF SELECTCOM") and depth == 1:
            return i
        if stripped.startswith("IF "):
            depth += 1
        elif stripped == "ENDIF":
            depth -= 1
            if depth == 0:
                return i + 1
    raise RuntimeError(f"SELECTCOM at line {start + 1} has no end")


def if_end(lines: list[str], start: int) -> int:
    depth = 1
    for i in range(start + 1, len(lines)):
        stripped = lines[i].lstrip()
        if stripped.startswith("IF "):
            depth += 1
        elif stripped == "ENDIF":
            depth -= 1
            if depth == 0:
                return i + 1
    raise RuntimeError(f"IF at line {start + 1} has no end")


def if_else(lines: list[str], start: int, end: int) -> int:
    depth = 1
    for i in range(start + 1, end):
        stripped = lines[i].lstrip()
        if stripped.startswith("IF "):
            depth += 1
        elif stripped == "ELSE" and depth == 1:
            return i
        elif stripped == "ENDIF":
            depth -= 1
    raise RuntimeError(f"IF at line {start + 1} has no matching ELSE")


def talent_start(lines: list[str], start: int, end: int) -> int:
    found = [
        i for i in range(start, end)
        if re.match(r"^\t+IF TALENT:TARGET:\d+\s*$", lines[i])
    ]
    if len(found) != 1:
        raise RuntimeError(f"expected one TALENT branch at {start + 1}, got {len(found)}")
    return found[0]


def wrap_print(lines: list[str], index: int, alternatives: tuple[str, str]) -> None:
    old = lines[index]
    indent = old[: len(old) - len(old.lstrip())]
    if not old.lstrip().startswith("PRINTFORMW"):
        raise RuntimeError(f"expected PRINTFORMW at line {index + 1}")
    lines[index:index + 1] = [
        f"{indent}IF A == 0",
        f"{indent}\t{old.lstrip()}",
        f"{indent}ELSEIF A == 1",
        f'{indent}\tPRINTFORMW 「{alternatives[0]}」',
        f"{indent}ELSE",
        f'{indent}\tPRINTFORMW 「{alternatives[1]}」',
        f"{indent}ENDIF",
    ]


def wrap_talent(lines: list[str], start: int, end: int, extras: tuple[str, str, str, str]) -> None:
    tstart = talent_start(lines, start, end)
    tend = if_end(lines, tstart)
    else_index = if_else(lines, tstart, tend)
    love = [i for i in range(tstart + 1, else_index) if lines[i].lstrip().startswith("PRINTFORMW")]
    normal = [i for i in range(else_index + 1, tend - 1) if lines[i].lstrip().startswith("PRINTFORMW")]
    if len(love) != 1 or len(normal) != 1:
        raise RuntimeError(f"expected one PRINTFORMW per branch at line {tstart + 1}")
    wrap_print(lines, normal[0], (extras[2], extras[3]))
    wrap_print(lines, love[0], (extras[0], extras[1]))


