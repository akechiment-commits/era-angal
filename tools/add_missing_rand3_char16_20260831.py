def ensure_local_annotations(text: str) -> str:
    """長いRAND3ブロックでも監査が拾えるよう、独自枠へ個別注釈を置く。"""
    labels = {
        62: "ダブル素股",
        280: "部室シチュエーション",
        281: "シャワー後シチュエーション",
        282: "用具室シチュエーション",
        283: "体育館裏シチュエーション",
        284: "道場シチュエーション",
        410: "弟妹とお出かけ",
        411: "ゲームセンター",
        412: "力比べ大会",
        413: "かわいい雑貨屋",
        414: "食べ放題",
    }
    for com, label in labels.items():
        pattern = re.compile(rf"(?m)^(?P<head>(?:IF|ELSEIF) SELECTCOM == {com})$")
        match = pattern.search(text)
        if not match:
            raise ValueError(f"COM{com} の見出しが見つかりません")
        before = text[max(0, match.start() - 120) : match.start()]
        if re.search(rf"(?m)^;.*\bCOM\s*{com}\b", before):
            continue
        text = text[: match.start()] + f";--- COM{com} {label} ---\n" + text[match.start() :]
    return text


def remove_explanatory_meta(text: str) -> str:
    replacements = {
        'PRINTFORMW 「わっ、%LOCALS%の熱が直接当たるっ……！　女の子同士でこんな近くになるなんて、あたい、まだ慣れないっす……！」':
        'PRINTFORMW 「わっ、%LOCALS%の熱が直接当たるっ……！　こんな近くで触れ合うの、あたい、まだ慣れないっす……！」',
        'PRINTFORMW 「ひゃうっ、%LOCALS%のを入れるんすか……！　あたい、女の子同士でこんなこと、恥ずかしくて力が抜けるっす……！」':
        'PRINTFORMW 「ひゃうっ、%LOCALS%のを入れるんすか……！　あたい、こんなふうに受け止めるの、恥ずかしくて力が抜けるっす……！」',
        'PRINTFORMW 「えっと、%LOCALS%の中を覗くんすね……。うう、女の子同士でも、ここまで見るのは緊張するっす……！」':
        'PRINTFORMW 「えっと、%LOCALS%の中を覗くんすね……。うう、ここまで見られると、あたいまで緊張するっす……！」',
    }
    for old, new in replacements.items():
        text = text.replace(old, new)
    return text


def main() -> int:
    source = SOURCE.read_text(encoding="utf-8")
    if not source.startswith("# いさみ（全1346件）"):
        raise RuntimeError("いさみ.txt の原作見出しを確認できません")
    raw = TARGET.read_bytes().decode("cp932")
    text = raw.replace("\r\n", "\n")

    before = text
    text = replace_com60(text)
    for com, variants in STANDARD_VARIANTS.items():
        text = process_simple(text, com, variants)
    for com, variants in CUSTOM_VARIANTS.items():
        text = process_custom(text, com, variants)
    for com, variant_sets in EQUIPMENT_VARIANTS.items():
        text = process_equipment(text, com, variant_sets)
    text = remove_explanatory_meta(text)
    text = ensure_local_annotations(text)

    remaining = []
    for com in [*STANDARD_VARIANTS, *CUSTOM_VARIANTS, *EQUIPMENT_VARIANTS]:
        start, end = section_spans(text)[com]
        if "A = RAND:" not in text[start:end]:
            remaining.append(com)
    if remaining:
        raise RuntimeError(f"RAND3未整備が残っています: {remaining}")

    if text == before:
        print("変更なし")
        return 0

    BACKUP.parent.mkdir(parents=True, exist_ok=True)
    if not BACKUP.exists():
        shutil.copy2(TARGET, BACKUP)
    TARGET.write_bytes(text.replace("\n", "\r\n").encode("cp932"))
    print(f"標準{len(STANDARD_VARIANTS)}枠・独自{len(CUSTOM_VARIANTS)}枠・装着{len(EQUIPMENT_VARIANTS)}枠をRAND3化、COM60助手呼称を補完")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
