def render_custom_section(header: str, note: str, scenes: list[list[str]]) -> list[str]:
    out = [";==============================================================", header, note]
    for index, scene in enumerate(scenes):
        if index:
            out.append("ELSE")
        out.extend(scene)
    out.append("ENDIF")
    return out


def rewrite_custom(lines: list[str]) -> None:
    # 先頭に残っていた一行だけの旧汎用COM280-284/410-414ブロックを除去する。
    custom_markers = [i for i, line in enumerate(lines) if line == ";--- COM280-284 独自ウフフ ---"]
    if len(custom_markers) >= 2:
        del lines[custom_markers[0] : custom_markers[1]]

    start = next(i for i, line in enumerate(lines) if line == ";--- COM280-284 独自ウフフ ---")
    ufu = [";--- COM280-284 独自ウフフ ---", ";  ※ウフフ中の独自カスタムコマンド（各キャラ固有の性的シチュエーション）"]
    for index, scene in enumerate(CUSTOM_UFUHU):
        if index == 0:
            ufu.extend(scene)
        else:
            ufu.append("ELSEIF " + scene[0].replace("IF ", "", 1))
            ufu.extend(scene[1:])
    ufu.append("ENDIF")

    pure_start = next(i for i in range(start + 1, len(lines)) if lines[i] == ";--- COM410-414 独自純愛 ---")
    section_end = next(i for i in range(pure_start + 1, len(lines)) if lines[i] == ";==============================================================")
    pure = [";--- COM410-414 独自純愛 ---", ";  ※純愛系の独自カスタムコマンド（ウフフ外・各キャラ固有のシチュエーション）"]
    for index, scene in enumerate(CUSTOM_PURELOVE):
        if index == 0:
            pure.extend(scene)
        else:
            pure.append("ELSEIF " + scene[0].replace("IF ", "", 1))
            pure.extend(scene[1:])
    pure.append("ENDIF")

    lines[start:section_end] = ufu + ["", ""] + pure


