def read_lines() -> list[str]:
    return TARGET.read_bytes().decode("cp932").splitlines()


def write_lines(lines: list[str]) -> None:
    TARGET.write_bytes("\r\n".join(lines).encode("cp932") + b"\r\n")


def orgasm_units(lines: list[str]) -> tuple[int, int, list[list[int]]]:
    start = next(i for i, line in enumerate(lines) if line == "@CHAR_ORGASM_14")
    end = next(i for i in range(start + 1, len(lines)) if lines[i] == "RETURN 0")
    units: list[list[int]] = []
    index = start + 1
    while index < end:
        if re.search(r"PRINTFORM[LMW]\s+「", lines[index]):
            unit = [index]
            if "PRINTFORML" in lines[index] and index + 1 < end and "PRINTFORMW" in lines[index + 1]:
                unit.append(index + 1)
            units.append(unit)
            index = unit[-1] + 1
        else:
            index += 1
    return start, end, units


def main() -> None:
    lines = read_lines()
    start, end, units = orgasm_units(lines)
    if len(units) != len(ORGASM_DIALOGUES):
        raise RuntimeError(f"絶頂台詞数が不一致です: 実ファイル={len(units)} 予定={len(ORGASM_DIALOGUES)}")
    BACKUP.parent.mkdir(parents=True, exist_ok=True)
    if not BACKUP.exists():
        shutil.copy2(TARGET, BACKUP)

    for unit, dialogue in reversed(list(zip(units, ORGASM_DIALOGUES))):
        first = lines[unit[0]]
        indent = first[: len(first) - len(first.lstrip())]
        lines[unit[0]] = indent + "PRINTFORMW " + dialogue
        for index in reversed(unit[1:]):
            del lines[index]
    write_lines(lines)
    print(f"CHAR14絶頂台詞を反応中心にリライト: {len(units)}件")


if __name__ == "__main__":
    main()
