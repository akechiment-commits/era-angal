# 出現順に置換
out = []
idx = 0
parts = text.split('「」')
for j, p in enumerate(parts):
    out.append(p)
    if j < len(parts) - 1:
        out.append('「' + L[idx] + '」')
        idx += 1
text2 = ''.join(out)

