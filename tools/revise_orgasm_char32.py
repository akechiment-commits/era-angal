def main() -> None:
    raw = TARGET.read_bytes()
    text = raw.decode("cp932")
    if MARKER in text:
        print("CHAR_32の絶頂口上校正は適用済みです。無変更で終了します。")
        return

    lines = text.replace("\r\n", "\n").split("\n")
    start = next(i for i, line in enumerate(lines) if line.strip() == "@CHAR_ORGASM_32")
    end = next(i for i, line in enumerate(lines[start + 1:], start + 1) if line.strip() == "@TRAIN_MESSAGE_B280_32")
    dialogue_indexes = [i for i in range(start, end) if "PRINTFORMW" in lines[i]]
    if len(dialogue_indexes) != len(LINES):
        raise RuntimeError(f"絶頂口上の本数が想定外です: {len(dialogue_indexes)} != {len(LINES)}")

    BACKUP.parent.mkdir(parents=True, exist_ok=True)
    if not BACKUP.exists():
        BACKUP.write_bytes(raw)

    for index, dialogue in zip(dialogue_indexes, LINES):
        prefix = lines[index].split("PRINTFORMW", 1)[0]
        lines[index] = f'{prefix}PRINTFORMW 「{dialogue}」'

    lines.insert(start, MARKER)
    output = "\r\n".join(lines)
    if not output.endswith("\r\n"):
        output += "\r\n"
    TARGET.write_bytes(output.encode("cp932"))
    print(f"CHAR_32の絶頂口上150本を反応中心に校正しました。バックアップ: {BACKUP}")


if __name__ == "__main__":
    main()
