def replace_logic(text: str, marker: str, new_logic: str, next_marker: str | None = None) -> str:
    start = text.find(marker)
    if start < 0:
        raise RuntimeError(f"marker not found: {marker}")
    logic_start = text.find("IF SELECTCOM", start)
    if logic_start < 0:
        raise RuntimeError(f"logic start not found: {marker}")
    if next_marker is None:
        next_pos = text.find(";--- COM", logic_start + 1)
        if next_pos < 0:
            raise RuntimeError(f"next marker not found: {marker}")
    else:
        next_pos = text.find(next_marker, logic_start + 1)
        if next_pos < 0:
            raise RuntimeError(f"next marker not found: {next_marker}")
    return text[:logic_start] + new_logic.rstrip() + "\n\n" + text[next_pos:]


def branch_block(num: int, love: list[str], normal: list[str]) -> str:
    assert len(love) == 3 and len(normal) == 3
    out = [f"IF SELECTCOM == {num}", "\tA = RAND:3", "\tIF TALENT:TARGET:153"]
    for i, line in enumerate(love):
        if i == 0:
            out.append("\t\tIF A == 0")
        elif i == 1:
            out.append("\t\tELSEIF A == 1")
        else:
            out.append("\t\tELSE")
        out.append(f"\t\t\tPRINTFORMW {line}")
    out += ["\t\tENDIF", "\tELSE"]
    for i, line in enumerate(normal):
        if i == 0:
            out.append("\t\tIF A == 0")
        elif i == 1:
            out.append("\t\tELSEIF A == 1")
        else:
            out.append("\t\tELSE")
        out.append(f"\t\t\tPRINTFORMW {line}")
    out += ["\t\tENDIF", "\tENDIF", "ENDIF"]
    return "\n".join(out)


def toggle_block(num: int, on_love: list[str], on_normal: list[str], off_love: list[str], off_normal: list[str]) -> str:
    assert all(len(x) == 3 for x in (on_love, on_normal, off_love, off_normal))

    def sub(love: list[str], normal: list[str]) -> list[str]:
        out = ["\t\tIF TALENT:TARGET:153"]
        for i, line in enumerate(love):
            out.append("\t\t\tIF A == 0" if i == 0 else "\t\t\tELSEIF A == 1" if i == 1 else "\t\t\tELSE")
            out.append(f"\t\t\t\tPRINTFORMW {line}")
        out.append("\t\t\tENDIF")
        out.append("\t\tELSE")
        for i, line in enumerate(normal):
            out.append("\t\t\tIF A == 0" if i == 0 else "\t\t\tELSEIF A == 1" if i == 1 else "\t\t\tELSE")
            out.append(f"\t\t\t\tPRINTFORMW {line}")
        out.append("\t\t\tENDIF")
        out.append("\t\tENDIF")
        return out

    out = [f"IF SELECTCOM == {num}", "\tIF TEQUIP:" + str(num)]
    out.append("\t\tA = RAND:3")
    out.extend(sub(on_love, on_normal))
    out += ["\tELSE", "\t\tA = RAND:3"]
    out.extend(sub(off_love, off_normal))
    out += ["\tENDIF", "ENDIF"]
    return "\n".join(out)


