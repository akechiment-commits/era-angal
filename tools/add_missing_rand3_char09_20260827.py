def normalize_assistant_alias(lines: list[str], command: int) -> None:
    start = next(i for i, line in enumerate(lines) if line == f"IF SELECTCOM == {command}")
    end = find_end(lines, start)
    block = lines[start:end]
    block = [
        line
        for line in block
        if not line.strip().startswith("CALL AITE_YOBI,")
        and not line.strip().startswith("LOCALS '= ")
    ]
    block[1:1] = [
        "\tCALL AITE_YOBI, 9, ASSI",
        '\tLOCALS \'= @"%RESULTS%"',
    ]
    lines[start:end] = block


