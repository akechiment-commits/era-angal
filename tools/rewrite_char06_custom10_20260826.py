def custom_block(number: int, data: dict[str, object]) -> str:
    lines = [f"IF SELECTCOM == {number}"]
    ground = data.get("ground")
    if ground:
        lines.append(f"\tPRINTFORMW {ground}")
    lines.extend(
        [
            "\tA = RAND:3",
            "\tIF TALENT:TARGET:153",
            "\t\tIF A == 0",
            f"\t\t\tPRINTFORMW {data['love'][0]}",
            "\t\tELSEIF A == 1",
            f"\t\t\tPRINTFORMW {data['love'][1]}",
            "\t\tELSE",
            f"\t\t\tPRINTFORMW {data['love'][2]}",
            "\t\tENDIF",
            "\tELSE",
            "\t\tIF A == 0",
            f"\t\t\tPRINTFORMW {data['normal'][0]}",
            "\t\tELSEIF A == 1",
            f"\t\t\tPRINTFORMW {data['normal'][1]}",
            "\t\tELSE",
            f"\t\t\tPRINTFORMW {data['normal'][2]}",
            "\t\tENDIF",
            "\tENDIF",
            "ENDIF",
            "",
        ]
    )
    return "\n".join(lines)


def main() -> None:
    text = PATH.read_bytes().decode("cp932").replace("\r\n", "\n")
    header = (
        ";==============================================================\n"
        "; 口上独自ウフフ（COM280-284）/ 口上独自純愛（COM410-414）\n"
        ";==============================================================\n"
    )
    starts = []
    offset = 0
    while True:
        found = text.find(header, offset)
        if found < 0:
            break
        starts.append(found)
        offset = found + len(header)
    if len(starts) != 2:
        raise RuntimeError(f"expected two old custom sections, found {len(starts)}")

    standard_header = (
        ";==============================================================\n"
        "; えっち系・よく使うコマンド（恋人/通常 各RAND:3）\n"
        ";==============================================================\n"
    )
    standard_start = text.find(standard_header, starts[1] + len(header))
    if standard_start < 0:
        raise RuntimeError("standard command section not found")

    section = [
        ";==============================================================",
        "; 口上独自ウフフ（COM280-284）/ 口上独自純愛（COM410-414）",
        ";==============================================================",
        "; 原作精読済み：部室／図書室／カーディガン／取材／猫／読書／物語／劇／クリスマス",
        "; あいかの一人称・距離感・文芸部／猫／足長おじさんの要素を場面ごとに分ける",
        "",
    ]
    for number in (280, 281, 282, 283, 284, 410, 411, 412, 413, 414):
        section.append(f";--- COM{number}")
        section.append(custom_block(number, CUSTOM[number]))
    replacement = "\n".join(section)
    text = text[: starts[0]] + replacement + "\n" + text[standard_start:]
    PATH.write_bytes(text.replace("\n", "\r\n").encode("cp932"))
    print("CHAR06 custom10 rewritten: 10 unique blocks; duplicate generic range removed")


if __name__ == "__main__":
    main()
