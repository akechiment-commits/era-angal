def command_start(lines: list[str], number: int) -> int:
    pattern = re.compile(rf"^(?:IF|ELSEIF) SELECTCOM == {number}\s*$")
    matches = [i for i, line in enumerate(lines) if pattern.match(line)]
    if len(matches) != 1:
        raise RuntimeError(f"SELECTCOM {number}: expected one start, got {len(matches)}")
    return matches[0]


def command_end(lines: list[str], start: int) -> int:
    depth = 1
    for i in range(start + 1, len(lines)):
        stripped = lines[i].lstrip()
        if stripped.startswith("ELSEIF SELECTCOM") and depth == 1:
            return i
        if stripped.startswith("IF "):
            depth += 1
        elif stripped == "ENDIF":
            depth -= 1
            if depth == 0:
                return i + 1
    raise RuntimeError(f"command at line {start + 1} has no end")


def if_end(lines: list[str], start: int) -> int:
    depth = 1
    for i in range(start + 1, len(lines)):
        stripped = lines[i].lstrip()
        if stripped.startswith("IF "):
            depth += 1
        elif stripped == "ENDIF":
            depth -= 1
            if depth == 0:
                return i + 1
    raise RuntimeError(f"IF at line {start + 1} has no end")


def if_else(lines: list[str], start: int, end: int) -> int:
    """Return the ELSE belonging to an IF, ignoring nested IF blocks."""
    depth = 1
    for i in range(start + 1, end):
        stripped = lines[i].lstrip()
        if stripped.startswith("IF "):
            depth += 1
        elif stripped == "ELSE" and depth == 1:
            return i
        elif stripped == "ENDIF":
            depth -= 1
    raise RuntimeError(f"IF at line {start + 1} has no matching ELSE")


def talent_start(lines: list[str], start: int, end: int) -> int:
    found = [
        i
        for i in range(start, end)
        if re.match(r"^\t+IF TALENT:TARGET:\d+\s*$", lines[i])
    ]
    if len(found) != 1:
        raise RuntimeError(f"expected one talent branch in lines {start + 1}-{end}, got {len(found)}")
    return found[0]


def wrap_print(lines: list[str], print_index: int, alternatives: tuple[str, str]) -> None:
    old = lines[print_index]
    indent = old[: len(old) - len(old.lstrip())]
    if not old.lstrip().startswith("PRINTFORMW"):
        raise RuntimeError(f"expected PRINTFORMW at line {print_index + 1}")
    base = old.lstrip()
    lines[print_index : print_index + 1] = [
        f"{indent}IF A == 0",
        f"{indent}\t{base}",
        f"{indent}ELSEIF A == 1",
        f'{indent}\tPRINTFORMW 「{alternatives[0]}」',
        f"{indent}ELSE",
        f'{indent}\tPRINTFORMW 「{alternatives[1]}」',
        f"{indent}ENDIF",
    ]


def wrap_talent(lines: list[str], start: int, end: int, extras: tuple[str, str, str, str]) -> None:
    tstart = talent_start(lines, start, end)
    tend = if_end(lines, tstart)
    depth = 1
    else_index = None
    for i in range(tstart + 1, tend - 1):
        stripped = lines[i].lstrip()
        if stripped.startswith("IF "):
            depth += 1
        elif stripped == "ENDIF":
            depth -= 1
        elif stripped == "ELSE" and depth == 1:
            else_index = i
            break
    if else_index is None:
        raise RuntimeError(f"talent branch at line {tstart + 1} has no ELSE")

    love_prints = [
        i for i in range(tstart + 1, else_index) if lines[i].lstrip().startswith("PRINTFORMW")
    ]
    normal_prints = [
        i for i in range(else_index + 1, tend - 1) if lines[i].lstrip().startswith("PRINTFORMW")
    ]
    if len(love_prints) != 1 or len(normal_prints) != 1:
        raise RuntimeError(
            f"expected one print per talent branch at line {tstart + 1}; "
            f"got love={len(love_prints)}, normal={len(normal_prints)}"
        )

    # Replace the later branch first so that the earlier index stays valid.
    wrap_print(lines, normal_prints[0], (extras[2], extras[3]))
    wrap_print(lines, love_prints[0], (extras[0], extras[1]))


def rewrite_normal_line(lines: list[str], number: int, content: str) -> None:
    start = command_start(lines, number)
    end = command_end(lines, start)
    tstart = talent_start(lines, start, end)
    tend = if_end(lines, tstart)
    else_index = next(i for i in range(tstart + 1, tend - 1) if lines[i].lstrip() == "ELSE")
    prints = [
        i for i in range(else_index + 1, tend - 1) if lines[i].lstrip().startswith("PRINTFORMW")
    ]
    if len(prints) != 1:
        raise RuntimeError(f"COM{number}: expected one normal PRINTFORMW, got {len(prints)}")
    indent = lines[prints[0]][: len(lines[prints[0]]) - len(lines[prints[0]].lstrip())]
    lines[prints[0]] = f'{indent}PRINTFORMW 「{content}」'


def add_standard(lines: list[str], number: int) -> None:
    start = command_start(lines, number)
    end = command_end(lines, start)
    if any("A = RAND:" in line for line in lines[start:end]):
        raise RuntimeError(f"COM{number} already has RAND")
    lines.insert(start + 1, "\tA = RAND:3")
    end += 1
    wrap_talent(lines, start, end, SIMPLE_EXTRA[number])


def add_custom(lines: list[str], number: int) -> None:
    start = command_start(lines, number)
    end = command_end(lines, start)
    if any("A = RAND:" in line for line in lines[start:end]):
        raise RuntimeError(f"custom COM{number} already has RAND")
    lines.insert(start + 1, "\tA = RAND:3")
    end += 1
    wrap_talent(lines, start, end, CUSTOM_EXTRA[number])


def add_equipment(lines: list[str], number: int) -> None:
    start = command_start(lines, number)
    end = command_end(lines, start)
    if any("A = RAND:" in line for line in lines[start:end]):
        raise RuntimeError(f"equipment COM{number} already has RAND")
    lines.insert(start + 1, "\tA = RAND:3")
    end += 1

    equip_start = next(i for i in range(start, end) if lines[i].lstrip() == f"IF TEQUIP:{number}")
    outer_else = if_else(lines, equip_start, end)
    remove_talent = talent_start(lines, outer_else, end)
    remove_end = if_end(lines, remove_talent)
    extra = EQUIP_EXTRA[number]

    wrap_talent(lines, outer_else, remove_end, extra["off"])

    # Recompute indices after the first insertion.
    start = command_start(lines, number)
    end = command_end(lines, start)
    equip_start = next(i for i in range(start, end) if lines[i].lstrip() == f"IF TEQUIP:{number}")
    outer_else = if_else(lines, equip_start, end)
    wrap_talent(lines, equip_start, outer_else, extra["on"])


