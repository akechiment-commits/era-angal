def rewrite_custom(lines: list[str]) -> None:
    start = next(i for i, line in enumerate(lines) if line == ";--- COM280-284 独自ウフフ ---")
    section_end = next(i for i in range(start + 1, len(lines)) if lines[i] == ";==============================================================")

    def compound(header: str, scenes: list[list[str]]) -> list[str]:
        out = [header, ";  ※各場面を恋人/通常それぞれRAND:3化"]
        for index, scene in enumerate(scenes):
            if index == 0:
                out.extend(scene)
            else:
                out.append("ELSEIF " + scene[0].replace("IF ", "", 1))
                out.extend(scene[1:])
        out.append("ENDIF")
        return out

    ufu = compound(";--- COM280-284 独自ウフフ ---", CUSTOM_UFUHU)
    pure = compound(";--- COM410-414 独自純愛 ---", CUSTOM_PURELOVE)
    lines[start:section_end] = ufu + ["", ""] + pure + [""]


def main() -> None:
    raw = PATH.read_bytes()
    text = raw.decode("cp932").replace("\r\n", "\n")
    lines = text.splitlines()

    for command, additions in EXTRA_SIMPLE.items():
        rewrite_simple(lines, command, additions)
    for command, states in EQUIPMENT_EXTRA.items():
        rewrite_equipment(lines, command, states)
    for command in sorted(ASSISTANT_COMMANDS):
        ensure_assistant_alias(lines, command)
    repair_com69_player_viewpoint(lines)
    repair_com60_text(lines)
    repair_com189_unique_text(lines)

    custom_start = next(i for i, line in enumerate(lines) if line == ";--- COM280-284 独自ウフフ ---")
    custom_end = next(i for i in range(custom_start + 1, len(lines)) if lines[i] == ";==============================================================")
    if "A = RAND:3" not in "\n".join(lines[custom_start:custom_end]):
        rewrite_custom(lines)

    result = "\n".join(lines).rstrip("\n") + "\n"
    encoded = result.replace("\n", "\r\n").encode("cp932")
    if encoded == raw:
        print("変更なし: CHAR11の対象RAND3は既に適用済み")
        return
    BACKUP.parent.mkdir(parents=True, exist_ok=True)
    BACKUP.write_bytes(raw)
    PATH.write_bytes(encoded)
    print("CHAR11: 未完了標準・装着・独自RAND3を一括補完")
    print(f"バックアップ: {BACKUP.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
