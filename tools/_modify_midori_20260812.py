def replace_block(text: str, cid: int, new: str) -> str:
    pat = re.compile(rf"^IF SELECTCOM == {cid}\s*$", re.M)
    matches = list(pat.finditer(text))
    if len(matches) != 1:
        raise RuntimeError(f"SELECTCOM {cid}: expected one block, got {len(matches)}")
    start = matches[0].start()
    tail = text[matches[0].end():]
    boundaries = [m.start() for m in (
        re.search(r"^IF SELECTCOM == \d+\s*$", tail, re.M),
        re.search(r"^RETURN 0\s*$", tail, re.M),
    ) if m]
    end = matches[0].end() + min(boundaries) if boundaries else len(text)
    return text[:start] + new + "\n\n" + text[end:]


