def scene_chain_block(scenes: dict[int, tuple[list[str], list[str]]]) -> str:
    """Build the five authored scene commands as independent RAND:3 branches."""
    out: list[str] = []
    for n, (cid, (lover, normal)) in enumerate(scenes.items()):
        out.append(f"IF SELECTCOM == {cid}" if n == 0 else f"ELSEIF SELECTCOM == {cid}")
        out += ["\tA = RAND:3", "\tIF TALENT:TARGET:153"]
        for i, line in enumerate(lover):
            out.append("\t\tIF A == 0" if i == 0 else ("\t\tELSEIF A == 1" if i == 1 else "\t\tELSE"))
            out.append(p(line))
        out += ["\t\tENDIF", "\tELSE"]
        for i, line in enumerate(normal):
            out.append("\t\tIF A == 0" if i == 0 else ("\t\tELSEIF A == 1" if i == 1 else "\t\tELSE"))
            out.append(p(line))
        out += ["\t\tENDIF", "\tENDIF"]
    out.append("ENDIF")
    return "\n".join(out)


