def load_original_custom_a0() -> dict[int, tuple[list[str], list[str]]]:
    """初回バックアップから独自10のA=0台詞を取り出し、既存文を保持する。"""
    if not BACKUP.exists():
        return {}
    lines = BACKUP.read_bytes().decode("cp932").splitlines()
    selectors = [(i, int(m.group(1))) for i, line in enumerate(lines) if (m := re.match(r"(?:IF|ELSEIF) SELECTCOM == (28[0-4]|41[0-4])$", line))]
    result: dict[int, tuple[list[str], list[str]]] = {}
    for pos, (start, command) in enumerate(selectors):
        end = selectors[pos + 1][0] if pos + 1 < len(selectors) else next((i for i in range(start + 1, len(lines)) if lines[i] == ";=============================================================="), len(lines))
        block = lines[start:end]
        talent = next(i for i, line in enumerate(block) if line == "\tIF TALENT:TARGET:153")
        relation_else = next(i for i in range(talent + 1, len(block)) if block[i] == "\tELSE")
        relation_end = next(i for i in range(relation_else + 1, len(block)) if block[i] == "\tENDIF")
        def prints(begin: int, finish: int) -> list[str]:
            return ["\t" + line for line in block[begin:finish] if re.match(r"^\t\tPRINTFORM[LMW]\s+", line)]
        result[command] = (prints(talent + 1, relation_else), prints(relation_else + 1, relation_end))
    return result


def replace_custom(lines: list[str]) -> list[str]:
    start = next(i for i, line in enumerate(lines) if line == ";--- COM280-284 独自ウフフ ---")
    end = next(i for i in range(start + 20, len(lines)) if lines[i] == ";==============================================================")
    return lines[:start] + custom_block() + lines[end:]


def ensure_assistant_aliases(lines: list[str]) -> list[str]:
    ranges = command_ranges(lines)
    for command in sorted(ASSISTANT_COMMANDS, reverse=True):
        start, end = ranges[command]
        block = lines[start:end]
        selector = next(i for i, line in enumerate(block) if line == f"IF SELECTCOM == {command}")
        if not any("CALL AITE_YOBI, 14, ASSI" in line for line in block):
            block[selector + 1 : selector + 1] = ["\tCALL AITE_YOBI, 14, ASSI", "\tLOCALS '= @\"%RESULTS%\"", ""]
        block = [line.replace("%CALLNAME:ASSI%", "%LOCALS%") for line in block]
        if command == 60:
            prints = [i for i, line in enumerate(block) if re.match(r"^\t+PRINTFORMW\s+", line)]
            if len(prints) != 6:
                raise RuntimeError(f"COM60の台詞数が不正です: {len(prints)}")
            replacements = [
                "「んっ、ちゅ……♪　%LOCALS%の唇、やわらかいだなぁ。転校生しゃん、見てるが？」",
                "「%LOCALS%とのキス、絵になるだなぁ……。でも、これはファンサじゃなくて、おらがしたかっただけ♪」",
                "「ちゅ……%LOCALS%との任務、完了だぁ。次は転校生しゃんとも、もっと長くしてぇな♪」",
                "「ほえ、%LOCALS%から？　では一回だけ……んっ、ちゅ♪」",
                "「あぅ、同時に笑ったら唇がずれちまっただ。%LOCALS%なら、もう一回してもいいが？」",
                "「緊張してるだか？　おら、舞台じゃねぇときはもっと近くにいられるだ。ほら、%LOCALS%、目ぇ閉じてなぁ♪」",
            ]
            for index, replacement in zip(prints, replacements):
                indent = re.match(r"^\t+", block[index]).group(0)
                block[index] = indent + "PRINTFORMW " + replacement
        lines[start:end] = block
        ranges = command_ranges(lines)
    return lines


def fix_com17_duplicate(lines: list[str]) -> list[str]:
    """COM17の装着解除時、恋人A=2と通常A=2が同文にならないようにする。"""
    ranges = command_ranges(lines)
    start, end = ranges[17]
    duplicate = "\t\t\t\tPRINTFORMW 「は、撤収完了だぁ。おら、次の任務までに調子を整えるだよ！」"
    replacement = "\t\t\t\tPRINTFORMW 「ふぅ……外れても熱が引かねぇだ。おら、次のステージまで休むだ……♪」"
    positions = [i for i in range(start, end) if lines[i] == duplicate]
    if len(positions) > 1:
        lines[positions[0]] = replacement
    return lines


def fix_char14_voice_meta(lines: list[str]) -> list[str]:
    """助手参加枠の観客メタと、ことり以外の一人称混入を除く。"""
    replacements = {
        "\t\t\tPRINTFORMW 「%LOCALS%と擦れると、おらの腰まで勝手に動くだ……。転校生しゃんに見られたら恥ずかしい♪」":
            "\t\t\tPRINTFORMW 「%LOCALS%と擦れると、おらの腰まで勝手に動くだ……。自分でも止められねぇだ……♪」",
        "\t\t\tPRINTFORMW 「これで、あたしたちの先のことを考えてるだなぁ……転校生しゃん、本気なんだ♪」":
            "\t\t\tPRINTFORMW 「これで、おらたちの先のことを考えてるだなぁ……転校生しゃん、本気なんだ♪」",
        "\t\t\tPRINTFORMW 「%LOCALS%をおらが開いて、転校生しゃんに見せるだ……。特別公開だなぁ♪」":
            "\t\t\tPRINTFORMW 「%LOCALS%をおらが開いて……。こんなところまで触るの、胸がどきどきするだ……♪」",
    }
    for old, new in replacements.items():
        lines = [new if line == old else line for line in lines]
    return lines


