out=[]
for ln in lines:
    m=re.search(r'SELECTCOM\s*==\s*(\d+)', ln)
    mge=re.search(r'SELECTCOM\s*>=\s*(\d+)', ln)
    if m: cur=int(m.group(1))
    elif mge: cur=int(mge.group(1))
    if '「」' in ln and cur in T and counts[cur] < len(T[cur]):
        ln=ln.replace('「」', '「'+T[cur][counts[cur]]+'」', 1)
        counts[cur]+=1
    out.append(ln)
for k in T:
    assert counts[k]==len(T[k]), f'COM{k}: {counts[k]}/{len(T[k])}'
