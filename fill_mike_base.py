# cp932 不可文字・半角チルダの事前チェック
for i, s in enumerate(lines):
    if '~' in s:
        raise SystemExit(f'半角チルダ混入 #{i+1}: {s}')
    try:
        s.encode('cp932')
    except UnicodeEncodeError as e:
        raise SystemExit(f'cp932不可 #{i+1}: {s} ({e})')

content = open(PATH, 'rb').read().decode('cp932')

n_empty = content.count('「」')
if n_empty != len(lines):
    raise SystemExit(f'空スロ数 {n_empty} != セリフ数 {len(lines)}')

# 文書順に空「」を1つずつ置換
idx = 0
def repl(m):
    global idx
    s = lines[idx]
    idx += 1
    return '「' + s + '」'

new = re.sub('「」', repl, content)
assert idx == len(lines), f'置換数 {idx} != {len(lines)}'
assert '「」' not in new, '空「」が残存'

data = new.encode('cp932')  # 失敗してもファイルは無傷
# CRLF維持確認
if b'\r\n' not in data:
    raise SystemExit('CRLFが無い（改行コード異常）')

with open(PATH, 'wb') as f:
    f.write(data)

print('OK: 全', len(lines), 'スロ記入。残り空「」:', new.count('「」'))
