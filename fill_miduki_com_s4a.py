raw=open(PATH,'rb').read().decode('cp932')
total=0
for com,strings in B:
    strings=[s.replace('〜','～') for s in strings]
    for s in strings:
        if '~' in s: sys.exit('半角~: '+s)
    si=raw.find(f'IF SELECTCOM == {com}\r')
    if si==-1: si=raw.find(f'IF SELECTCOM == {com}\n')
    if si==-1:
        m=re.search(rf'IF\s+SELECTCOM\s*==\s*{com}\b',raw); si=m.start()
    nl=raw.find('\n',si)
    ei=raw.find('IF SELECTCOM',nl)
    seg=raw[si:ei]
    assert seg.count('「」')==len(strings), f'COM{com}: file={seg.count(chr(0x300c)+chr(0x300d))}'
    for s in strings: seg=seg.replace('「」','「'+s+'」',1)
    raw=raw[:si]+seg+raw[ei:]
    total+=len(strings)

