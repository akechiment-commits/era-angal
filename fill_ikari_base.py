def main():
    raw = open(PATH, 'rb').read()
    assert b'\r\n' in raw, 'base ERB must be CRLF'
    text = raw.decode('cp932')
    n = text.count('「」')
    assert n == len(S), f'空「」数 {n} != 用意した {len(S)}'
    # 波ダッシュ正規化 & 禁止文字チェック
    for i, s in enumerate(S):
        s2 = s.replace('〜', '～').replace('~', '～').replace('—', '―').replace('―', '―')
        S[i] = s2
        for bad in ['私', 'わたし', '僕', '俺']:
            assert bad not in s2, f'[{i}] 禁止一人称: {bad} in {s2}'
        assert '「」' not in s2, f'[{i}] 空「」混入'
        try:
            s2.encode('cp932')
        except UnicodeEncodeError as e:
            raise SystemExit(f'[{i}] cp932不可: {s2}\n{e}')
    # 順に置換
    parts = text.split('「」')
    out = parts[0]
    for i, s in enumerate(S):
        out += '「' + s + '」' + parts[i+1]
    assert out.count('「」') == 0, '空「」が残存'
    data = out.encode('cp932')  # 先に確定
    with open(PATH, 'wb') as f:
        f.write(data)
    print(f'OK: {len(S)}枠記入, {len(data)} bytes')

main()
