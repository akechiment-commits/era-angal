# cp932/半角~チェック
def chk(s,where):
    if '~' in s: raise SystemExit(f'半角~ {where}: {s}')
    try: s.encode('cp932')
    except UnicodeEncodeError as e: raise SystemExit(f'cp932不可 {where}: {s} ({e})')
for num,a in D.items():
    for s in a: chk(s,f'COM{num}')
for d in (UFUFU,JUN):
    for num,(a,b) in d.items(): chk(a,f'COM{num}恋'); chk(b,f'COM{num}通')
for v in CSTR.values(): chk(v,'CSTR')

