CR='\r'
def L(s): return s+CR  # CRLF用に\r付与

# (1) キス/告白を COMヘッダ範囲で充填
heads=[(i,int(m.group(1))) for i,l in enumerate(lines) for m in [re.match(r'\s*;-{2,}\s*COM(\d+)',l)] if m]
for k,(i,num) in enumerate(heads):
    end=heads[k+1][0] if k+1<len(heads) else len(lines)
    if num not in D: continue
    it=iter(D[num]); c=[0]
    def repl(m,it=it,c=c):
        c[0]+=1; return m.group(1)+'「'+next(it)+'」'
    for j in range(i,end):
        if re.search(r'PRINTFORM[LW][ \t]+「」',lines[j]):
            lines[j]=re.sub(r'(PRINTFORM[LW][ \t]+)「」',repl,lines[j])
    if c[0]!=len(D[num]): raise SystemExit(f'COM{num}: {c[0]}!={len(D[num])}')

# (2) 独自枠ブロックを番号別に分割書換（純愛→ウフフの順＝後方から）
def find_block(cond):
    for i,l in enumerate(lines):
        if l.rstrip('\r').strip()==cond:
            # ENDIF(インデント0)まで
            for j in range(i+1,len(lines)):
                if lines[j].rstrip('\r')=='ENDIF': return i,j
    raise SystemExit('block not found: '+cond)

def build(dic,coms,onlyrenai=False):
    out=[]
    for idx,num in enumerate(coms):
        head=('IF' if idx==0 else 'ELSEIF')+f' SELECTCOM == {num}'
        ren,tu=dic[num]
        out+= [L(head),
               L('\tIF TALENT:TARGET:153'),
               L('\t\tPRINTFORMW 「'+ren+'」'),
               L('\tELSE'),
               L('\t\tPRINTFORMW 「'+tu+'」'),
               L('\tENDIF')]
    out.append(L('ENDIF'))
    return out

