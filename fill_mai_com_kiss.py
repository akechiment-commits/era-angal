import re
pat = re.compile(r'(PRINTFORM[LW]\s+)「」')

with open(PATH, 'rb') as f:
    raw = f.read()
assert b'\r\n' in raw
text = raw.decode('cp932')

total = 0
for tag, start, end, lst in regions:
    # 正規化＆cp932チェック
    L = []
    for s in lst:
        assert '~' not in s, f'{tag} 半角~: {s}'
        s = s.replace('〜', '～')
        s.encode('cp932')
        L.append(s)
    si = text.index(start)
    ei = text.index(end, si)
    span = text[si:ei]
    cnt = len(pat.findall(span))
    assert cnt == len(L), f'{tag}: 区間空{cnt} vs 本文{len(L)}'
    it = iter(L)
    span2 = pat.sub(lambda m: m.group(1) + '「' + next(it) + '」', span)
    assert not list(it)
    text = text[:si] + span2 + text[ei:]
    total += len(L)

data = text.encode('cp932')
assert b'\r\n' in data
with open(PATH, 'wb') as f:
    f.write(data)
print('ステップ3充填:', total, '枠 / COM_ERB残空:', len(pat.findall(text)))
