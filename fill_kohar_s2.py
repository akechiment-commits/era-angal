# ---- 共通処理 ----
def encode_check(lines):
    for s in lines:
        if '~' in s: raise SystemExit(f'半角チルダ: {s!r}')
        if '剝' in s: raise SystemExit(f'剝混入: {s!r}')
        try: s.encode('cp932')
        except UnicodeEncodeError as e: raise SystemExit(f'cp932不可: {s!r} {e}')

content = open(PATH,'rb').read().decode('cp932')

def fill_com(content, com, lines):
    encode_check(lines)
    mh = re.search(rf'(?m)^;--- COM{com} .*$', content)
    if not mh: raise SystemExit(f'header not found COM{com}')
    start = mh.end()
    me = re.search(r'(?m)^(;--- COM|@)', content[start:])
    end = start + (me.start() if me else len(content)-start)
    block = content[start:end]
    slots = list(re.finditer(r'(?m)^([ \t]*)(PRINTFORM[LW])([ \t]+)「」', block))
    if len(slots) != len(lines):
        raise SystemExit(f'COM{com}: slots={len(slots)} lines={len(lines)}')
    out=[]; last=0
    for i,m in enumerate(slots):
        out.append(block[last:m.start()])
        out.append(f"{m.group(1)}{m.group(2)}{m.group(3)}「{lines[i]}」")
        last=m.end()
    out.append(block[last:])
    return content[:start] + ''.join(out) + content[end:]

