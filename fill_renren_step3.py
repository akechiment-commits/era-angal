pat=re.compile(r'(PRINTFORM[LW]+ +)「」')

def fill(content, header, texts):
    i=content.index(header)
    # 区間終端＝次の ';--- ' か '@' ラベル
    nxt=content.find('\n;--- ', i+1)
    nxt2=content.find('\n@', i+1)
    cands=[x for x in (nxt,nxt2) if x!=-1]
    end=min(cands) if cands else len(content)
    span=content[i:end]
    ms=list(pat.finditer(span))
    assert len(ms)==len(texts), f'{header}: slot {len(ms)} != {len(texts)}'
    for m,txt in zip(reversed(ms), reversed(texts)):
        for bad in ('~','「','」'):
            assert bad not in txt, f'NG char in: {txt}'
        txt.encode('cp932')
        span=span[:m.start()]+m.group(1)+'「'+txt+'」'+span[m.end():]
    return content[:i]+span+content[end:]

