def fill(content, header, texts):
    i=content.index('\n'+header)+1   # 行頭（改行直後）の定義を確実に取る
    nxt2=content.find('\n@', i+1)
    if header.startswith('@'):
        end=nxt2 if nxt2!=-1 else len(content)   # @関数は次の@まで（内部の;---は無視）
    else:
        nxt=content.find('\n;--- ', i+1)
        cands=[x for x in (nxt,nxt2) if x!=-1]; end=min(cands) if cands else len(content)
    span=content[i:end]; ms=list(pat.finditer(span))
    assert len(ms)==len(texts), f'{header}: {len(ms)} != {len(texts)}'
    for m,txt in zip(reversed(ms), reversed(texts)):
        txt=txt.replace('♡','♪')
        for bad in ('~','「','」'): assert bad not in txt, f'NG {txt}'
        txt.encode('cp932')
        span=span[:m.start()]+m.group(1)+'「'+txt+'」'+span[m.end():]
    return content[:i]+span+content[end:]

