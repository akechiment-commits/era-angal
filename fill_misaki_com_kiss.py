def fill_eq(lines, com, texts):
    # 境界は == と >= の両方（独自範囲ブロックで取り違えないため）
    sel=[i for i,l in enumerate(lines) if re.search(r'IF SELECTCOM\s*(==|>=)\s*\d+',l)]
    for k,i in enumerate(sel):
        m=re.search(r'IF SELECTCOM\s*==\s*(\d+)',lines[i])
        if m and int(m.group(1))==com:
            end=sel[k+1] if k+1<len(sel) else len(lines)
            idx=[j for j in range(i,end) if '「」' in lines[j]]
            assert len(idx)==len(texts),f"COM{com} {len(idx)}!={len(texts)}"
            it=iter(texts)
            for j in idx: lines[j]=lines[j].replace('「」','「'+next(it)+'」',1)
            return
    raise SystemExit(f'COM{com}未検出')

def fill_range(lines, start, texts):
    for i,l in enumerate(lines):
        if re.search(rf'IF SELECTCOM\s*>=\s*{start}\b',l):
            # block until matching ENDIF (find next ';---' or blank-then-comment); use next ENDIF at col0
            end=i+1
            depth=1
            for j in range(i+1,len(lines)):
                s=lines[j].strip()
                if s.startswith('IF '): depth+=1
                elif s=='ENDIF':
                    depth-=1
                    if depth==0: end=j; break
            idx=[j for j in range(i,end+1) if '「」' in lines[j]]
            assert len(idx)==len(texts),f"range{start} {len(idx)}!={len(texts)}"
            it=iter(texts)
            for j in idx: lines[j]=lines[j].replace('「」','「'+next(it)+'」',1)
            return
    raise SystemExit(f'range{start}未検出')

