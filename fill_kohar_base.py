# 空 PRINTFORM「」 を文書順に置換（行頭がコメントでない PRINTFORM 行のみ）
pat = re.compile(r'(?m)^(?P<ind>[ \t]*)(?P<cmd>PRINTFORM[LW])([ \t]+)「」')
slots = list(pat.finditer(content))
print('空スロット数:', len(slots), ' 用意したセリフ数:', len(B))
if len(slots) != len(B):
    raise SystemExit('数が一致しません')

out = []
last = 0
for i, m in enumerate(slots):
    out.append(content[last:m.start()])
    out.append(f"{m.group('ind')}{m.group('cmd')}{m.group(3)}「{B[i]}」")
    last = m.end()
out.append(content[last:])
newtext = ''.join(out)

assert '「」' not in re.sub(r';.*', '', newtext), '空スロット残存'
data = newtext.encode('cp932')
assert b'\r\n' in data
open(PATH, 'wb').write(data)
print('書き込み完了:', len(data), 'bytes')
