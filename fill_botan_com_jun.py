# COMヘッダ位置（;--- COMxxx）
heads=[]
for i,l in enumerate(lines):
    m=re.match(r'\s*;-{2,}\s*COM(\d+)',l)
    if m: heads.append((i,int(m.group(1))))
# 各COMブロック範囲で空きスロ充填
filled=0
for k,(i,num) in enumerate(heads):
    end=heads[k+1][0] if k+1<len(heads) else len(lines)
    if num not in D: continue
    arr=D[num]; it=iter(arr); cnt=[0]
    def repl(m, it=it, cnt=cnt):
        cnt[0]+=1
        return m.group(1)+'「'+next(it)+'」'
    for j in range(i,end):
        if re.search(r'PRINTFORM[LW][ \t]+「」',lines[j]):
            lines[j]=re.sub(r'(PRINTFORM[LW][ \t]+)「」',repl,lines[j])
    if cnt[0]!=len(arr):
        raise SystemExit(f'COM{num}: 空き{cnt[0]} != 用意{len(arr)}')
    filled+=cnt[0]

new='\n'.join(lines)
data=new.encode('cp932')
with open(PATH,'wb') as f: f.write(data)
