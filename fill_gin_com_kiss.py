total=sum(len(v) for v in blocks.values())
# 正規化＋cp932チェック
for k in blocks:
    nn=[]
    for s in blocks[k]:
        s=s.replace('〜','～').replace('~','～')
        s.encode('cp932')
        nn.append(s)
    blocks[k]=nn

content=open(PATH,'rb').read().decode('cp932')
lines=content.split('\r\n')
cur=None; used={k:0 for k in blocks}
for i,l in enumerate(lines):
    s=l.strip()
    m=re.match(r';--- COM(\d+)',s)
    if m: cur=int(m.group(1))
    if re.search(r'PRINTFORM[LW]\s+「」',l) and cur in blocks and used[cur]<len(blocks[cur]):
        rep=blocks[cur][used[cur]]; used[cur]+=1
        lines[i]=re.sub(r'(PRINTFORM[LW]\s+)「」', lambda mm: mm.group(1)+'「'+rep+'」', l)
for k in blocks:
    assert used[k]==len(blocks[k]), f'COM{k}: {used[k]}/{len(blocks[k])}'
new='\r\n'.join(lines)
data=new.encode('cp932')
open(PATH,'wb').write(data)
print('OK Step3充填', sum(used.values()), '/', total, '残り空き:', new.count('「」'))
