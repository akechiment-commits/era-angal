# 波ダッシュ正規化（U+301C -> U+FF5E、半角~は禁止）
norm = []
for s in slots:
    assert '~' not in s, f'半角チルダ混入: {s}'
    s = s.replace('〜', '～')
    norm.append(s)
slots = norm

# cp932 エンコード事前チェック（失敗してもファイルは無傷）
for s in slots:
    try:
        s.encode('cp932')
    except UnicodeEncodeError as e:
        raise SystemExit(f'cp932不可: {e} in: {s}')

# 読み込み
with open(PATH, 'rb') as f:
    raw = f.read()
assert b'\r\n' in raw, 'CRLF前提が崩れている'
text = raw.decode('cp932')

# 空スロ数の検算（PRINTFORM[LW] 「」 のみ。コメント中の 「」 は対象外）
import re
pat = re.compile(r'(PRINTFORM[LW]\s+)「」')
empties = len(pat.findall(text))
print('PRINTFORM空スロ数:', empties, ' / 用意した本文:', len(slots))
assert empties == len(slots), f'不一致: 空{empties} vs 本文{len(slots)}'

# 順次置換（PRINTFORM行だけを先頭から順に埋める）
it = iter(slots)
def _rep(m):
    return m.group(1) + '「' + next(it) + '」'
out = pat.sub(_rep, text)

# 全スロ消費を確認
rest = list(it)
assert not rest, f'本文が余った: {len(rest)}'
assert len(pat.findall(out)) == 0, 'PRINTFORM空スロが残存'

# encode を変数に確定してから書く（1行 open().write() 禁止）
data = out.encode('cp932')
assert b'\r\n' in data
with open(PATH, 'wb') as f:
    f.write(data)

print('充填完了。残存PRINTFORM空スロ:', len(pat.findall(out)))
