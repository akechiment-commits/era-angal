def encode_check(lines):
    for i,s in enumerate(lines):
        if '~' in s: raise SystemExit(f'半角チルダ idx={i}: {s!r}')
        if '剝' in s: raise SystemExit(f'剝 idx={i}: {s!r}')
        if '♥' in s: raise SystemExit(f'ハート idx={i}: {s!r}')
        try: s.encode('cp932')
        except UnicodeEncodeError as e: raise SystemExit(f'cp932不可 idx={i}: {s!r} {e}')

