order=sorted([(lab,idx[lab]) for lab,_ in SEC], key=lambda x:x[1])
bounds={}
for k,(lab,i) in enumerate(order):
    e=order[k+1][1] if k+1<len(order) else len(lines)
    bounds[lab]=(i,e)
filled=0
for lab,arr in SEC:
    i,e=bounds[lab]
    it=iter(arr); c=[0]
    def repl(m,it=it,c=c):
        c[0]+=1; return m.group(1)+'「'+next(it)+'」'
    for j in range(i,e):
        if re.search(r'PRINTFORM[LW][ \t]+「」',lines[j]):
            lines[j]=re.sub(r'(PRINTFORM[LW][ \t]+)「」',repl,lines[j])
    if c[0]!=len(arr): raise SystemExit(f'{lab}: 空き{c[0]} != 用意{len(arr)}')
    filled+=c[0]

new='\n'.join(lines)
data=new.encode('cp932')
open(PATH,'wb').write(data)
chk2=open(PATH,'rb').read(); assert b'\r\n' in chk2 and chk2.decode('cp932')==new
rest=len(re.findall(r'PRINTFORM[LW][ \t]+「」',new))
print('OK 充填',filled,'/ 残空き(全体)',rest)
