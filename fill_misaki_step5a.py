def fill_label(lines, label, texts):
    i=next(j for j,l in enumerate(lines) if l.strip()==label)
    end=len(lines)
    for j in range(i+1,len(lines)):
        if lines[j].startswith('@'): end=j; break
    idx=[j for j in range(i,end) if '「」' in lines[j]]
    assert len(idx)==len(texts), f"{label} {len(idx)}!={len(texts)}"
    it=iter(texts)
    for j in idx: lines[j]=lines[j].replace('「」','「'+next(it)+'」',1)

