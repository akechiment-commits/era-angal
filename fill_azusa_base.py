# cp932 事前チェック
for s in slots:
    if '~' in s:
        raise SystemExit('半角チルダ混入: ' + s)
    try:
        s.encode('cp932')
    except UnicodeEncodeError as e:
        raise SystemExit('cp932不可: ' + repr(s) + ' / ' + str(e))

with open(fn, 'rb') as f:
    t = f.read().decode('cp932')

n = t.count('「」')
print('empty slots in file:', n, '/ provided:', len(slots))
assert n == len(slots), 'スロット数不一致'

# 順番に1個ずつ置換
for s in slots:
    t = t.replace('「」', '「' + s + '」', 1)

assert t.count('「」') == 0, '空きが残っている'

data = t.encode('cp932')  # 失敗してもファイル無傷
assert b'\r\n' in data and data.count(b'\r\n') == data.count(b'\n'), 'CRLF維持確認'
with open(fn, 'wb') as f:
    f.write(data)
print('done. base ERB filled.')
