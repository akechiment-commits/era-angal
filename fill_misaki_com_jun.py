# COM単位でブロックを切り出し、その中の「」を順に置換する（順序非依存・安全）
def fill_blocks(content, mapping):
    lines = content.split('\r\n')
    sel = [i for i,l in enumerate(lines) if re.search(r'IF SELECTCOM\s*==\s*\d+', l)]
    # COMごとの行範囲
    ranges = {}
    for k,i in enumerate(sel):
        com = int(re.search(r'==\s*(\d+)', lines[i]).group(1))
        end = sel[k+1] if k+1 < len(sel) else None
        if end is None:
            for j in range(i+1, len(lines)):
                if lines[j].startswith('@'): end = j; break
            else: end = len(lines)
        ranges[com] = (i, end)
    for com, texts in mapping.items():
        i, end = ranges[com]
        idx = [j for j in range(i, end) if '「」' in lines[j]]
        assert len(idx) == len(texts), f"COM{com}: 枠{len(idx)} != 文{len(texts)}"
        it = iter(texts)
        for j in idx:
            lines[j] = lines[j].replace('「」', '「' + next(it) + '」', 1)
    return '\r\n'.join(lines)

