for i,l in enumerate(lines):
    m=re.search(r'IF SELECTCOM\s*(==|>=)\s*(\d+)',l)
    if m: pos.setdefault(int(m.group(2)),i+1)
allc=sorted(pos)
total=0
for com,arr in D.items():
    s=pos[com]; nx=[pos[x] for x in allc if pos[x]>s]; e=min(nx) if nx else len(lines)
    c=0
    for i in range(s-1,e-1):
        if re.search(r'PRINTFORM[LW]\s*「」',lines[i]):
            lines[i]=lines[i].replace('「」','「'+arr[c]+'」',1); c+=1
    assert c==len(arr)==6, f'COM{com}: {c}'
    total+=c
out='\r\n'.join(lines)
