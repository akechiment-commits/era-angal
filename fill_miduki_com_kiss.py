raw=open(PATH,'rb').read().decode('cp932')
total=0
for marker, strings in BLOCKS:
    strings=[s.replace('〜','～') for s in strings]
    for s in strings:
        if '~' in s: sys.exit('半角~: '+s)
    si=raw.find(marker)
    assert si!=-1, '見つからない: '+marker
    # 現在の開始行を飛ばし、次の「IF SELECTCOM」開始行までを終端とする
    nl=raw.find('\n', si)
    ei=raw.find('IF SELECTCOM', nl)
    assert ei!=-1
    seg=raw[si:ei]
    n=seg.count('「」')
    assert n==len(strings), f'{marker}: file={n} script={len(strings)}'
    for s in strings:
        seg=seg.replace('「」','「'+s+'」',1)
    raw=raw[:si]+seg+raw[ei:]
    total+=len(strings)

out=raw.replace('\r\n','\n').replace('\n','\r\n')
open(PATH,'wb').write(out.encode('cp932'))
print('記入:', total, '/ 残り全体空き:', out.count('「」'))
