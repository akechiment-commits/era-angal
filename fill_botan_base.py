# cp932 事前チェック（半角~・cp932不可文字の検出）
for n, s in enumerate(fills):
    if '~' in s:
        raise SystemExit(f'[{n}] 半角チルダ混入: {s}')
    try:
        s.encode('cp932')
    except UnicodeEncodeError as e:
        raise SystemExit(f'[{n}] cp932不可: {s} ({e})')

assert len(fills) == 126, f'fills数が126でない: {len(fills)}'

raw = open(PATH, 'rb').read()
assert b'\r\n' in raw, 'CRLFでない'
text = raw.decode('cp932')

# 空きスロを文書順に充填
it = iter(fills)
cnt = 0
def repl(m):
    global cnt
    cnt += 1
    return m.group(1) + '「' + next(it) + '」'

# CRLFを保ったまま処理するため \n 単位ではなく全文で置換（改行はクォート外なので影響なし）
new = re.sub(r'(PRINTFORM[LW][ \t]+)「」', repl, text)
assert cnt == 126, f'置換数が126でない: {cnt}'

# 残空きゼロ確認
rest = len(re.findall(r'PRINTFORM[LW][ \t]+「」', new))
assert rest == 0, f'空き残: {rest}'

data = new.encode('cp932')  # ここで失敗してもファイル無傷
with open(PATH, 'wb') as f:
    f.write(data)

